"""Шестая проверка — В ЧЬЁМ ТЕЛЕ стоит наша правка.

`placement.py` сверяет правку с ОДНОЙ вендорской строкой перед ней. Её хватает,
пока соседняя строка своеобразна. На переезде 2.1.280 её не хватило:
`F(forkHud, …)` и `F(forkAgentBar, …)` встали в заголовок инструмента
NotebookEdit вместо композера. Хвост там такой же — `}), }), ],` — и соседняя
строка совпала. Разбор, форма, область, сироты и расстановка были зелёными, а
полоса расхода и полоса агентов из вкладки исчезли.

Здесь для каждой нашей строки (комментарий «форк» или имя `fork…`) берётся
верхнеуровневое объявление, в теле которого она стоит, и его ОТПЕЧАТОК: первый
строковый литерал от начала объявления до нашей строки. Литералы не мангрятся,
поэтому отпечаток у одного и того же места одинаков в обеих версиях: у
NotebookEdit это "NotebookEdit", у композера — его собственный первый литерал.
Последовательности отпечатков форка и порта сравниваются по порядку.

    python3 tools/enclosure.py <форк прежней версии> <перенесённый файл>

Расхождение — правка переехала в чужое тело или пропала. Пустой отпечаток
(литерала нет) печатается как имя объявления в скелете, это слабее: смотреть
глазами.
"""
import difflib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import port as P

ОБЪЯВЛЕНИЕ = re.compile(r"^(var|let|const|function|async function|class) ")
НАША = re.compile(r"форк|\bfork[A-Z]\w*")
ЛИТЕРАЛ = re.compile(r'"([^"\\\n]{3,})"')


def отпечатки(путь: str) -> list[tuple[int, str]]:
    строки = Path(путь).read_text(encoding="utf-8").split("\n")
    итог, начало, последний = [], 0, None
    for i, с in enumerate(строки):
        if ОБЪЯВЛЕНИЕ.match(с):
            начало = i
        if not НАША.search(с) or ОБЪЯВЛЕНИЕ.match(с) and "fork" in с.split("(")[0]:
            continue
        литерал = next((m.group(1) for j in range(начало, i + 1)
                        if not НАША.search(строки[j])
                        for m in [ЛИТЕРАЛ.search(строки[j])] if m), None)
        ключ = литерал or "⟨" + P.нормализовать(строки[начало])[:60] + "⟩"
        if ключ != последний:
            итог.append((i + 1, ключ))
            последний = ключ
    return итог


старые, новые = отпечатки(sys.argv[1]), отпечатки(sys.argv[2])
расхождений = 0
for тег, i1, i2, j1, j2 in difflib.SequenceMatcher(
        None, [к for _, к in старые], [к for _, к in новые], autojunk=False).get_opcodes():
    if тег == "equal":
        continue
    расхождений += 1
    print(f"✗ {тег}")
    for н, к in старые[i1:i2]:
        print(f"    было  {н:>7}: {к}")
    for н, к in новые[j1:j2]:
        print(f"    стало {н:>7}: {к}")
print(f"мест в форке {len(старые)}, в порте {len(новые)}, расхождений {расхождений}")
