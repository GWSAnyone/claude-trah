"""Где в новом вендоре начинается окно ханка — вход для `rebase.py`.

`rebase.py` требует строку цели, с которой начинать выравнивание, и брать её
глазами дорого: номера в новой версии уезжают на тысячи строк. Здесь первые три
строки контекста ханка сводятся к скелету (`port.нормализовать`) и ищутся в
цели по форме — имена перемангливаются, форма остаётся.

    python3 tools/where.py <база> <форк> <цель> <номер ханка> [ещё номера...]

Номера ханков — те же, что печатает `port.py` в строках «✗ ханк N». Несколько
мест в ответе значит, что форма неоднозначна: брать нужное по порядку следования
ханков, соседние окна идут по возрастанию.
"""
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import port as P

аргументы = sys.argv[1:]
строк = 3
if "--строк" in аргументы:
    i = аргументы.index("--строк")
    строк = int(аргументы[i + 1])
    del аргументы[i:i + 2]
база, форк, цель, *номера = аргументы
заголовки = [l for l in subprocess.run(["diff", "-U6", база, форк], capture_output=True, text=True).stdout.split("\n") if l.startswith("@@")]
стар = Path(база).read_text(encoding="utf-8").split("\n")
нов = [P.нормализовать(с) for с in Path(цель).read_text(encoding="utf-8").split("\n")]

for nh in map(int, номера):
    a, n = map(int, re.match(r"@@ -(\d+),(\d+)", заголовки[nh - 1]).groups())
    блок = [P.нормализовать(с) for с in стар[a - 1:a - 1 + строк]]
    места = [i + 1 for i in range(len(нов) - строк) if нов[i:i + строк] == блок]
    print(f"ханк {nh}: база {a}, строк {n} → в цели {места[:5] or 'не нашлось'}")
