#!/usr/bin/env python3
"""Карта модульных имён между двумя вендорными версиями, со свидетелем.

ЗАЧЕМ. Наши вставки живут внутри вендорных функций и зовут вендорных
помощников по модульным именам: `D` (jsx с одним ребёнком), `K0` (таблица
css-классов) и так далее. Переносчик `port.py` выводит имена ПОЗИЦИОННО из
строк, совпавших по форме, — но только те, что встретились рядом с ханком.
Модульное имя рядом может и не попасться, и тогда оно уезжает в новую версию
как есть. Это третий класс дефекта: разбор его не видит (имя объявлено — в
чужом модуле), сверка по форме не видит тоже (короткие имена нумеруются), и
вылезает он падением вебвью при первой отрисовке.

МЕТОД. Тот же, что у `port.py`, только применённый к ОБЪЯВЛЕНИЮ имени, а не к
месту правки. Берётся объявление в прежней версии, нормализуется по форме
(короткие имена — точкой), ищется в новой версии и обязано совпасть РОВНО один
раз. Дальше короткие имена выстраиваются позиционно, и из пары читается новое
имя. Не совпало или совпало дважды — имя называется, и его разбирают глазами.

    tools/namemap.py --прежняя v260.js --новая v269.js D E K0 GX …
"""

import argparse
import re
import sys
from pathlib import Path

ИМЯ = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")
КОРОТКОЕ = 3
СТРОК = 8  # сколько строк объявления брать в якорь


def нормализовать(строка: str) -> str:
    return ИМЯ.sub(lambda м: "·" if len(м.group()) <= КОРОТКОЕ else м.group(), строка)


def имена_позиционно(старая: str, новая: str) -> dict[str, str] | None:
    с, н = ИМЯ.findall(старая), ИМЯ.findall(новая)
    if len(с) != len(н):
        return None
    пары: dict[str, str] = {}
    for a, b in zip(с, н):
        if len(a) <= КОРОТКОЕ:
            if a in пары and пары[a] != b:
                return None
            пары[a] = b
    return пары


def объявление(строки: list[str], имя: str) -> int | None:
    """Номер строки, где имя объявлено на верхнем уровне.

    Верхний уровень опознаётся нулевой колонкой: prettier ставит модульные
    объявления без отступа, а всё вложенное — с отступом. Это грубо, но
    достаточно: ложное срабатывание отсеется требованием единственного
    совпадения по форме.
    """
    образцы = [
        re.compile(rf"^(?:var|let|const) {re.escape(имя)} = "),
        re.compile(rf"^function \*?{re.escape(имя)}\("),
        re.compile(rf"^class {re.escape(имя)}[ ({{]"),
        re.compile(rf"^  {re.escape(имя)} = "),
    ]
    for n, с in enumerate(строки):
        if any(о.match(с) for о in образцы):
            return n
    return None


def свидетель(куски: list[str]) -> str:
    """Первый неманглящийся литерал в объявлении — им имя опознаётся глазами."""
    for с in куски:
        m = re.search(r'"([^"]{3,60})"', с)
        if m:
            return m.group(1)
    for с in куски:
        m = re.search(r"\b([A-Za-z_$][A-Za-z0-9_$]{4,})\b", с)
        if m:
            return m.group(1)
    return куски[0].strip()[:60]


def найти(норм: list[str], ключ: list[str]) -> list[int]:
    места, первая = [], ключ[0]
    for i, с in enumerate(норм):
        if с == первая and норм[i:i + len(ключ)] == ключ:
            места.append(i)
    return места


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("имена", nargs="+")
    ap.add_argument("--прежняя", required=True)
    ap.add_argument("--новая", required=True)
    а = ap.parse_args()

    старые = Path(а.прежняя).read_text(encoding="utf-8").split("\n")
    новые = Path(а.новая).read_text(encoding="utf-8").split("\n")
    норм_новые = [нормализовать(с) for с in новые]

    плохо = 0
    print("КАРТА = {")
    for имя in а.имена:
        н = объявление(старые, имя)
        if н is None:
            плохо += 1
            print(f"    # ✗ {имя}: объявления не нашлось")
            continue
        # Якорь укорачивается с хвоста, пока совпадение не станет единственным:
        # длинное объявление могло измениться в глубине, начало — реже.
        места, якорь = [], []
        for длина in range(min(СТРОК, len(старые) - н), 1, -1):
            якорь = старые[н:н + длина]
            места = найти(норм_новые, [нормализовать(с) for с in якорь])
            if len(места) == 1:
                break
        if len(места) != 1:
            плохо += 1
            print(f"    # ✗ {имя}: совпадений {len(места)}"
                  f" (объявление в прежней — строка {н + 1})")
            continue
        карта: dict[str, str] = {}
        сорвано = False
        for сдвиг, стар in enumerate(якорь):
            пары = имена_позиционно(стар, новые[места[0] + сдвиг])
            if пары is None:
                сорвано = True
                break
            карта.update(пары)
        if сорвано or имя not in карта:
            плохо += 1
            print(f"    # ✗ {имя}: имена не выстроились")
            continue
        print(f'    "{имя}": ("{карта[имя]}", "{свидетель(якорь)}"),')
    print("}")
    print(f"\nимён {len(а.имена)}, не опознано {плохо}", file=sys.stderr)
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
