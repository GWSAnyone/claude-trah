#!/usr/bin/env python3
"""Уцелели ли наши функции при переносе — проверка по существу, а не по приметам.

Переименование само по себе безобидно: это переобозначение. Опасно ровно одно —
когда две разные переменные становятся одной. Поймать это можно так: взять тело
функции в форке и в перенесённом файле, заменить каждое короткое имя на номер
по порядку первого появления и сравнить. Переобозначение исчезает, а слияние
меняет рисунок номеров и вылезает наружу.

Печатается имя каждой пострадавшей функции и первая разошедшаяся строка.

    tools/verify.py <файл прежней версии> <перенесённый файл>

Прежняя версия задаётся аргументом, а не константой: форк переехал из
`Projects/claude-code-vsc` в `claude-trah/claude-code-vsc`, и зашитый путь
пережил переезд молча — проверка искала бы файл, которого нет.
"""
import re
import sys
from pathlib import Path

ИМЯ = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")
НАЧАЛО = re.compile(r"^(?:function|var|class) (fork[A-Za-z0-9_]*)\b")


def функции(путь: Path) -> dict[str, list[str]]:
    """Тела наших функций верхнего уровня: от объявления до `}` в нулевой колонке."""
    строки = путь.read_text(encoding="utf-8").split("\n")
    итог, имя, буфер = {}, None, []
    for с in строки:
        м = НАЧАЛО.match(с)
        if м and имя is None:
            имя, буфер = м.group(1), [с]
            continue
        if имя is not None:
            буфер.append(с)
            if с in ("}", "};") or (с and not с[0].isspace() and с.startswith("}")):
                итог[имя] = буфер
                имя, буфер = None, []
    return итог


def по_форме(строки: list[str]) -> list[str]:
    номера, счёт, итог = {}, [0], []

    def заменить(м):
        и = м.group()
        if len(и) > 3:
            return и
        if и not in номера:
            счёт[0] += 1
            номера[и] = f"#{счёт[0]}"
        return номера[и]

    for с in строки:
        итог.append(ИМЯ.sub(заменить, с))
    return итог


if len(sys.argv) != 3:
    raise SystemExit("нужны два файла: прежняя версия и перенесённая")
ФОРК, ПОРТ = Path(sys.argv[1]), Path(sys.argv[2])
а, б = функции(ФОРК), функции(ПОРТ)
пропали = sorted(set(а) - set(б))
общие = sorted(set(а) & set(б))
плохих = 0
for имя in общие:
    фа, фб = по_форме(а[имя]), по_форме(б[имя])
    if фа == фб:
        continue
    плохих += 1
    ка = {и for с in а[имя] for и in ИМЯ.findall(с) if len(и) <= 3}
    кб = {и for с in б[имя] for и in ИМЯ.findall(с) if len(и) <= 3}
    признак = ("СЛИЯНИЕ ИМЁН" if len(кб) < len(ка)
               else "перестановка номеров" if len(кб) == len(ка)
               else "имён стало больше")
    print(f"  ✗ {имя}: расходится — {признак} "
          f"(коротких имён: форк {len(ка)}, перенесено {len(кб)})")
    for i, (x, y) in enumerate(zip(фа, фб)):
        if x != y:
            print(f"      форк:      {а[имя][i].strip()[:90]}")
            print(f"      перенесено:{б[имя][i].strip()[:90]}")
            break
    else:
        print(f"      длина: форк {len(фа)}, перенесено {len(фб)}")

print(f"\nнаших функций в форке {len(а)}, в перенесённом {len(б)}, "
      f"совпало по форме {len(общие) - плохих}, разошлось {плохих}")
if пропали:
    print(f"НЕ ДОЕХАЛИ: {', '.join(пропали)}")
