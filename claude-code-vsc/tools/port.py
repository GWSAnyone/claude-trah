#!/usr/bin/env python3
"""Перенос правок форка расширения на новую вендорную версию.

ЗАЧЕМ ИМЕННО ТАК. Между вендорными версиями расходится почти весь бандл:
2.1.247 → 2.1.260 это 194 938 изменённых строк из 264 429, 2.1.260 → 2.1.269 —
152 854. Это перемангривание имён, а не правки: форма кода, строковые литералы
и имена свойств стоят на месте, а короткие локальные имена переставлены целиком.
Трёхсторонняя склейка на таком даёт конфликт в каждом ханке, а `patch` по
дословному контексту кладёт куски «с fuzz», и это хуже отказа: вставленный код
ссылается на имена, которых в новой версии уже нет.

ПОЭТОМУ ДВА ХОДА.

1. ПОИСК ПО ФОРМЕ. Строка нормализуется: каждое короткое имя (до трёх знаков —
   ровно те, что мангрятся) заменяется точкой, всё остальное остаётся как есть.
   Ханк ищется как последовательность нормализованных строк и обязан совпасть
   РОВНО один раз. Не совпал или совпал дважды — не применяется и называется по
   имени. Молча не теряется ничего, и это главное отличие от переноса руками.

2. ВЫВОД ИМЁН ПОЗИЦИЕЙ. Раз строки совпали по форме, у них одинаковый скелет:
   те же не-именные куски, те же длинные имена, столько же коротких. Значит
   короткие выстраиваются в пары позиционно, и карта `старое → новое` для ЭТОГО
   места выводится из самого совпадения, а не угадывается. Ею и переименовываются
   наши добавляемые строки.

Модульные имена, которых рядом с ханком может не оказаться, заданы явной картой
ниже. Она снимается не глазами, а `tools/namemap.py`: тем же поиском по форме,
только применённым к ОБЪЯВЛЕНИЮ имени. У каждой строки записан свидетель —
литерал или длинное имя, которое не мангрится.

ВХОДЫ. Прежняя версия задаётся ДВУМЯ файлами — чистым вендором и нашим форком,
— а не коммитом гита: история форка при переезде в `claude-trah` схлопнута в
один коммит, и брать базу оттуда больше нельзя. Все три файла должны быть
прогнаны через один и тот же prettier.

    tools/port.py --база v260-vendor.js --форк v260-fork.js --в v269-vendor.js

ШУМ ФОРМАТИРОВАНИЯ. Prettier не идемпотентен по переносам внутри объектов и
вызовов: развёрнутый вход даёт другую разбивку, чем минифицированный. Такие
ханки — тот же код другими переносами — переносить нечего, и они пропускаются
по признаку «удалённое и добавленное совпадают после снятия пробелов».
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

ИМЯ = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*")
КОРОТКОЕ = 3  # до скольких знаков имя считается манглированным

# Модульные имена 2.1.260 → 2.1.269 для `webview/index.js`, со свидетелем.
# Снято `tools/namemap.py` (22 имени) плюс два jsx-помощника, у которых
# объявления нет вовсе: они присваиваются скопом в теле модуля,
# `((L1 = hK0), (D = lN1), (E = lN1))` → `((M1 = Sw0), (F = NT1), (R = NT1))`,
# и опознаны по объекту рендера `{Fragment:…, jsx:…, jsxs:…}`.
КАРТА_ВЕБВЬЮ = {
    "D":   ("F",   "jsx один ребёнок: {Fragment: M1, jsx: F, jsxs: R}"),
    "E":   ("R",   "jsxs несколько детей: тот же объект рендера"),
    "K0":  ("j0",  "таблица классов блока инструмента: root_ZUQaOA"),
    "GX":  ("TX",  "таблица классов размышления: thinkingSummary_aHyQPQ"),
    "zh":  ("_y",  "таблица классов плашки: banner_Z3DrKA"),
    "X1":  ("e",   "useEffect: XQ.current.useEffect → RQ.current.useEffect"),
    "YH":  ("MZ",  "функция, объявление совпало по форме единственный раз"),
    "ZX":  ("kJ",  "класс блока содержимого"),
    "LK":  ("WF",  "Artifact"),
    "XL":  ("BT",  "string"),
    "iy":  ("DC",  "функция"),
    "PM1": ("JL1", "allowed"),
    "ZW0": ("QM0", "allowed"),
    "K30": ("eY0", "таблица тела инструмента: toolBodyWrapper_R6H5ZA"),
    "W30": ("tY0", "plaintext"),
    "im0": ("Xn0", "string"),
    "H6":  ("w6",  "таблица классов: container_Eg8KCQ"),
    "n5":  ("N5",  "default"),
    "qP":  ("nP",  "svg"),
    "JX":  ("_Z",  "класс сообщения"),
    "LG":  ("aG",  "функция"),
    "sQ0": ("vz0", "функция"),
    "iQ0": ("Eo",  "функция"),
    "aM1": ("jL1", "функция"),
}

# То же для `extension.js`. Имён всего два: наш код там почти не занимает
# вендорных помощников. `_$` — алиас модуля `vscode`, и он уже ездил туда-сюда:
# прошлый переезд менял `E$` → `_$`, этот возвращает обратно.
КАРТА_РАСШИРЕНИЯ = {
    "_$":  ("E$",  "алиас модуля: _$ = P(require(\"vscode\"))"),
    "W_$": ("hu$", "функция, объявление совпало по форме единственный раз"),
}

КАРТЫ = {"вебвью": КАРТА_ВЕБВЬЮ, "расширение": КАРТА_РАСШИРЕНИЯ}


def нормализовать(строка: str) -> str:
    return ИМЯ.sub(lambda м: "·" if len(м.group()) <= КОРОТКОЕ else м.group(), строка)


def имена_позиционно(старая: str, новая: str) -> dict[str, str] | None:
    """Пары коротких имён из двух строк одинаковой формы."""
    с, н = ИМЯ.findall(старая), ИМЯ.findall(новая)
    if len(с) != len(н):
        return None
    пары = {}
    for a, b in zip(с, н):
        if len(a) <= КОРОТКОЕ:
            if a in пары and пары[a] != b:
                return None  # одно имя в две стороны — доверять нельзя
            пары[a] = b
    return пары


def переименовать(строка: str, карта: dict[str, str]) -> str:
    return ИМЯ.sub(lambda м: карта.get(м.group(), м.group()), строка)


def шум_форматирования(х: dict) -> bool:
    """Тот же код другими переносами — переносить нечего."""
    сжать = lambda строки: re.sub(r"\s+", "", "".join(строки))
    return bool(х["минус"]) and сжать(х["минус"]) == сжать(х["плюс"])


def ханки(база: Path, форк: Path, контекст: int) -> list[dict]:
    diff = subprocess.run(
        ["diff", f"-U{контекст}", str(база), str(форк)],
        capture_output=True, text=True).stdout.split("\n")
    итог, тек = [], None
    for с in diff:
        if с.startswith("@@"):
            if тек:
                итог.append(тек)
            тек = {"до": [], "минус": [], "плюс": [], "после": [],
                   "строка": int(re.match(r"@@ -(\d+)", с).group(1))}
            continue
        if тек is None or с.startswith(("+++", "---")):
            continue
        тело = с[1:]
        if с.startswith("+"):
            тек["плюс"].append(тело)
        elif с.startswith("-"):
            тек["минус"].append(тело)
        elif с.startswith(" "):
            (тек["после"] if (тек["плюс"] or тек["минус"]) else тек["до"]).append(тело)
    if тек:
        итог.append(тек)
    return итог


def найти(норм_новые: list[str], ключ: list[str]) -> list[int]:
    if not ключ:
        return []
    места, первая = [], ключ[0]
    for i, с in enumerate(норм_новые):
        if с != первая:
            continue
        if норм_новые[i:i + len(ключ)] == ключ:
            места.append(i)
    return места


def перенести(новые: list[str], хс: list[dict],
              модульные: dict[str, tuple[str, str]]) -> tuple[list[str], list[dict]]:
    норм = [нормализовать(с) for с in новые]
    задания, отчёт = [], []
    for н, х in enumerate(хс, 1):
        if шум_форматирования(х):
            отчёт.append({"№": н, "итог": "шум форматирования", "строка": х["строка"]})
            continue
        якорь = х["до"] + х["минус"]
        if not якорь:
            отчёт.append({"№": н, "итог": "нечем зацепиться", "строка": х["строка"]})
            continue
        места = найти(норм, [нормализовать(с) for с in якорь])
        # Совпало много — удлиняем якорь хвостовым контекстом, он тоже наш.
        if len(места) > 1 and х["после"]:
            длинный = якорь + х["после"]
            места2 = найти(норм, [нормализовать(с) for с in длинный])
            if len(места2) == 1:
                места, якорь = места2, длинный
        # Не совпало вовсе — вендорный код рядом с ханком изменился не только
        # именами. Отрезаем контекст СПЕРЕДИ: дальние строки менялись чаще,
        # ближние к правке — реже. Короче трёх строк не опускаемся: на двух
        # совпадение перестаёт что-либо значить.
        if len(места) == 0:
            for срез in range(1, max(0, len(х["до"]) - 2) + 1):
                проба = х["до"][срез:] + х["минус"]
                if len(проба) < 3:
                    break
                места2 = найти(норм, [нормализовать(с) for с in проба])
                if len(места2) == 1:
                    места, якорь = места2, проба
                    х = {**х, "до": х["до"][срез:], "срез": срез}
                    break
                if len(места2) > 1:
                    break
        if len(места) != 1:
            отчёт.append({"№": н, "итог": f"совпадений {len(места)}",
                          "строка": х["строка"],
                          "первая": (х["плюс"] or х["минус"] or ["?"])[0].strip()[:66]})
            continue
        нач = места[0]
        # Карта имён этого места: позиционно из совпавших строк, поверх — модульная.
        карта = {с: н_ for с, (н_, _) in модульные.items()}
        сорвано = False
        for сдвиг, стар in enumerate(якорь):
            пары = имена_позиционно(стар, новые[нач + сдвиг])
            if пары is None:
                сорвано = True
                break
            карта.update(пары)
        if сорвано:
            отчёт.append({"№": н, "итог": "имена не выстроились", "строка": х["строка"]})
            continue
        задания.append((нач + len(х["до"]), len(х["минус"]),
                        [переименовать(с, карта) for с in х["плюс"]]))
        отчёт.append({"№": н, "итог": "перенесён", "строка": х["строка"],
                      "строк": len(х["плюс"]), "куда": нач + len(х["до"]) + 1})

    # С конца — иначе смещаются номера ещё не применённых.
    for где, скольких, чем in sorted(задания, key=lambda z: -z[0]):
        новые[где:где + скольких] = чем
    return новые, отчёт


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--база", required=True, help="чистый вендор ПРЕЖНЕЙ версии")
    ap.add_argument("--форк", required=True, help="наш файл ПРЕЖНЕЙ версии")
    ap.add_argument("--в", required=True, help="чистый вендор НОВОЙ версии (правится)")
    ap.add_argument("--карта", required=True, choices=sorted(КАРТЫ),
                    help="какая карта модульных имён: у файлов она своя")
    ap.add_argument("--контекст", type=int, default=6)
    ap.add_argument("--сухо", action="store_true")
    а = ap.parse_args()

    цель = Path(а.в)
    новые = цель.read_text(encoding="utf-8").split("\n")
    хс = ханки(Path(а.база), Path(а.форк), а.контекст)
    получилось, отчёт = перенести(новые, хс, КАРТЫ[а.карта])

    легло = [о for о in отчёт if о["итог"] == "перенесён"]
    шум = [о for о in отчёт if о["итог"] == "шум форматирования"]
    нет = [о for о in отчёт if о["итог"] not in ("перенесён", "шум форматирования")]
    print(f"{цель.name}: ханков {len(хс)}, перенесено {len(легло)},"
          f" шум {len(шум)}, не легло {len(нет)}")
    for о in нет:
        print(f"  ✗ ханк {о['№']} (строка прежней версии {о['строка']}): {о['итог']}"
              f"  | {о.get('первая', '')}")
    if not а.сухо:
        цель.write_text("\n".join(получилось), encoding="utf-8")
        print(f"записано: {цель}")
    return 1 if нет else 0


if __name__ == "__main__":
    sys.exit(main())
