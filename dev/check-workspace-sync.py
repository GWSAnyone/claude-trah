#!/usr/bin/env python3
"""Разошлись ли копии комплекта с тем, что стоит на машине.

    check-workspace-sync.py [--home КАТАЛОГ] [--all]

ЗАЧЕМ. `check-reproducible.py` отвечает на вопрос «что на машине есть, а в git
нет» — то есть смотрит на ПРИСУТСТВИЕ файла и дальше не заглядывает. Файл,
который в комплекте лежит и на машине лежит, он числит воспроизводимым, даже
если внутри у них давно разное.

Так и вышло с `serena/context-claude-code.yml`: правку сделали на машине, в
комплект её не перенесли, и расхождение жило незамеченным до ручной описи.
Здесь дело не в одном файле, а в классе: пара копий, которую никто не сверяет,
расходится молча, и находят это случайно через месяцы.

ЧТО СВЕРЯЕТСЯ. Все пары «файл комплекта → его место на машине» из таблиц
самого установщика (`ОБЩЕЕ`, `ПРИ_УСЛОВИИ`, хуки). Таблица соответствий должна
быть ОДНА: свой список здесь разъехался бы с установщиком — ровно та болезнь,
от которой эта проверка и заведена. Поэтому `serena/context-claude-code.yml` и
конвенция памяти `serena/global-memory_maintenance.md` попадают в сверку не
поимённо, а потому что они есть у установщика.

Собираемое (бриф, куски, проводка хуков) не сверяется: у него в комплекте нет
исходной копии, его делает сборщик — за это отвечает `trah.test.py`.

ЧТО СЧИТАЕТСЯ ПРОВАЛОМ (выход 1):

  разошлись        — оба файла есть, содержимое разное;
  не поставлено    — файл в комплекте есть, на машине его нет.

Не проваливает: файлы из `install-kit.ПРАВИТЬ_РУКАМИ` — их и положено править
под хозяина, побайтового совпадения там не бывает. Они печатаются отдельным
списком, а не замалчиваются: молчать про них значит завести второе слепое
пятно вместо первого. И `ПРИ_УСЛОВИИ`, когда утилиты, ради которой файл
существует, на машине нет.
"""
import argparse
import difflib
import importlib.util
import sys
from pathlib import Path

КОМПЛЕКТ = Path(__file__).resolve().parent.parent / "trah-setup"

# Сколько строк расхождения показывать. Больше — уже не отчёт, а `diff`,
# который читатель запустит сам, раз ему названы оба пути.
ПОКАЗЫВАТЬ_СТРОК = 8


def установщик():
    спец = importlib.util.spec_from_file_location("ик", КОМПЛЕКТ / "bin/install-kit.py")
    ик = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(ик)
    return ик


def пары(ик, дом: Path) -> list[dict]:
    """Все сверяемые пары: что откуда куда и можно ли им расходиться."""
    вышло: list[dict] = []

    def добавить(имя: str, куда: str, обязателен: bool, почему_нет: str = "",
                 откуда: Path | None = None) -> None:
        вышло.append({
            "имя": имя,
            "откуда": откуда if откуда is not None else КОМПЛЕКТ / имя,
            "куда": дом / куда,
            "руками": ик.ПРАВИТЬ_РУКАМИ.get(имя, ""),
            "обязателен": обязателен,
            "почему_нет": почему_нет,
        })

    for откуда, куда in ик.ОБЩЕЕ:
        добавить(откуда, куда, обязателен=True)

    # Чужих файлов в сверке больше нет: с 07.09.2026 модули соседних продуктов
    # живут в своём реестре `modules.local.json`, который комплект не пишет.
    # Сверять чужое с несуществующей исходной копией было бы нечем.
    for файл in sorted((КОМПЛЕКТ / "hooks").glob("*.py")):
        добавить(f"hooks/{файл.name}", f".claude/hooks/{файл.name}", обязателен=True)

    # Реестр модулей: без него диспетчер не позовёт ни одного сторожа и
    # промолчит об этом.
    добавить("hooks/modules.json", ".claude/hooks/modules.json", обязателен=True)

    return вышло


def расхождение(откуда: Path, куда: Path) -> tuple[int, int, list[str]]:
    """Сколько строк добавлено и убрано и как выглядят первые различия."""
    а = откуда.read_text(encoding="utf-8", errors="replace").splitlines(keepends=True)
    б = куда.read_text(encoding="utf-8", errors="replace").splitlines(keepends=True)
    строки = list(difflib.unified_diff(а, б, n=0, lineterm=""))[2:]
    добавлено = sum(1 for с in строки if с.startswith("+") and not с.startswith("+++"))
    убрано = sum(1 for с in строки if с.startswith("-") and not с.startswith("---"))
    видно = [с.rstrip("\n") for с in строки if not с.startswith("@@")][:ПОКАЗЫВАТЬ_СТРОК]
    return добавлено, убрано, видно


def проверить(дом: Path, показать_все: bool) -> int:
    ик = установщик()
    сошлись: list[str] = []
    разошлись: list[dict] = []
    нет_на_машине: list[dict] = []
    правятся_руками: list[dict] = []
    не_нужны: list[dict] = []

    for п in пары(ик, дом):
        if not п["откуда"].exists():
            # Установщик обещает файл, которого в комплекте нет. Это его беда,
            # не наша: он сам скажет об этом при установке.
            continue
        if not п["куда"].exists():
            (нет_на_машине if п["обязателен"] else не_нужны).append(п)
            continue
        if п["откуда"].read_bytes() == п["куда"].read_bytes():
            сошлись.append(п["имя"])
            continue
        добавлено, убрано, видно = расхождение(п["откуда"], п["куда"])
        п |= {"добавлено": добавлено, "убрано": убрано, "видно": видно}
        (правятся_руками if п["руками"] else разошлись).append(п)

    print(f"сошлись побайтово: {len(сошлись)}")
    if показать_все:
        for имя in сошлись:
            print(f"  = {имя}")
    if не_нужны:
        print(f"\nне поставлено и не надо: {len(не_нужны)}")
        for п in не_нужны:
            print(f"  {п['имя']:<40} — {п['почему_нет']}")

    if правятся_руками:
        print(f"\nразошлись ОЖИДАЕМО — правятся под хозяина: {len(правятся_руками)}")
        for п in правятся_руками:
            print(f"  {п['имя']:<40} +{п['добавлено']} −{п['убрано']} "
                  f"— {п['руками']}")
            # Путь называем и здесь. «Расхождение ожидаемо» не значит «смотреть
            # незачем»: под правкой под хозяина легко проезжает и настоящий
            # уход в сторону, а искать, куда файл поставлен, читатель не обязан.
            print(f"      diff -u {п['откуда']} {п['куда']}")

    if нет_на_машине:
        print(f"\nНЕ ПОСТАВЛЕНО ({len(нет_на_машине)}) — файл в комплекте есть, "
              "на машине его нет:")
        for п in нет_на_машине:
            print(f"  {п['имя']}")
            print(f"      в комплекте: {п['откуда']}")
            print(f"      ждали на:    {п['куда']}")
            print(f"      чинить:      python3 {КОМПЛЕКТ / 'bin/install-kit.py'}")

    if разошлись:
        print(f"\nРАЗОШЛИСЬ ({len(разошлись)}) — копии одного файла разного "
              "содержимого:")
        for п in разошлись:
            print(f"  {п['имя']}  +{п['добавлено']} −{п['убрано']} строк")
            print(f"      в комплекте: {п['откуда']} ({п['откуда'].stat().st_size} б)")
            print(f"      на машине:   {п['куда']} ({п['куда'].stat().st_size} б)")
            for с in п["видно"]:
                print(f"      │ {с}")
            print(f"      посмотреть:  diff -u {п['откуда']} {п['куда']}")

    плохих = len(разошлись) + len(нет_на_машине)
    if плохих:
        print(f"\nИТОГ: {плохих} расхождений. Решить, чья правда — комплекта или "
              "машины, и перенести в другую сторону РУКАМИ:")
        print("  правда машины  → скопировать в комплект и закоммитить")
        print(f"  правда комплекта → python3 {КОМПЛЕКТ / 'bin/install-kit.py'} "
              "(кладёт копию прежнего рядом)")
        return 1

    print("\nИТОГ: расхождений нет.")
    return 0


def main() -> int:
    р = argparse.ArgumentParser(description="сверить комплект с тем, что стоит на машине")
    р.add_argument("--home", default=str(Path.home()), help="где искать поставленное")
    р.add_argument("--all", action="store_true", help="перечислить и совпавшие файлы")
    а = р.parse_args()
    return проверить(Path(а.home), а.all)


if __name__ == "__main__":
    sys.exit(main())
