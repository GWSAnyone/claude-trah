# --- чтение журнала хука PostToolBatch --------------------------------------
def журнал(строки: list[dict]) -> Path:
    п = Path(tempfile.mkdtemp()) / "batches.jsonl"
    п.write_text("\n".join(json.dumps(с, ensure_ascii=False) for с in строки) + "\n",
                 encoding="utf-8")
    return п


ж = журнал([
    {"at": "2026-08-29T10:00:00+00:00", "session": "aaa", "width": 3,
     "tools": ["Read", "Read", "Grep"], "failed": 0},
    {"at": "2026-08-29T10:01:00+00:00", "session": "aaa", "width": 3,
     "tools": ["Write", "Write", "Write"], "failed": 1},
    {"at": "2026-08-29T10:02:00+00:00", "session": "aaa", "width": 1,
     "tools": ["Bash"], "failed": 0},
    {"at": "2026-08-30T10:00:00+00:00", "session": "bbb", "width": 8,
     "tools": ["Read"] * 8, "failed": 0},
])
