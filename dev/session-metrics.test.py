check("Bash — оболочка", sm._разряд("Bash") == "оболочка")
check("serena — символьные", sm._разряд("mcp__serena__find_symbol") == "символьные")
check("Read — текстовые", sm._разряд("Read") == "текстовые")
check("Edit — правки", sm._разряд("Edit") == "правки")
check("Agent — делегирование", sm._разряд("Agent") == "делегирование")
