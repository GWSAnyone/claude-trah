#!/usr/bin/env python3
"""Проверки `session-metrics.py` на подделанной стенограмме. Токенов не стоит.

Стенограмма подделывается в ЖИВОЙ форме: один ответ модели разложен по записям,
на каждый блок своя строка с общим `requestId`, и `usage` в них ПРОДУБЛИРОВАН —
ровно так, как в настоящих файлах. На обеих особенностях легко ошибиться:
первая даёт ширину 1 у всего, вторая задваивает токены.

Отдельная проверка внизу — перекрёстная: M1 обязана совпасть с числами
`batch-width.py` на одних и тех же данных. Это критерий закрытия итерации 1.
"""
import importlib.util
import json
import sys
import tempfile
from pathlib import Path

КАТАЛОГ = Path(__file__).resolve().parent


def _модуль(имя_файла: str, имя_модуля: str):
    спец = importlib.util.spec_from_file_location(имя_модуля, КАТАЛОГ / имя_файла)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


sm = _модуль("session-metrics.py", "session_metrics")
bw = _модуль("batch-width.py", "batch_width")

всего = 0
провалов = 0


def check(имя: str, условие: bool, подробность: str = "") -> None:
    global всего, провалов
    всего += 1
    if not условие:
        провалов += 1
        print(f"  ✗ {имя} {подробность}")


def пачка(время: str, инструменты: list[str], текст: str = "",
          усилие: str = "medium", токенов: int = 100,
          sidechain: bool = False) -> list[dict]:
    """Записи одного ответа модели: блоки разложены, usage продублирован."""
    usage = {"output_tokens": токенов, "input_tokens": 10,
             "cache_creation_input_tokens": 0, "cache_read_input_tokens": 0}
    общий = {"type": "assistant", "timestamp": время, "requestId": f"req-{время}",
             "effort": усилие, "version": "2.1.247"}
    if sidechain:
        общий["isSidechain"] = True
    записи = [{**общий, "message": {"content": [{"type": "text", "text": текст or "…"}],
                                    "usage": usage}}]
    записи += [{**общий, "message": {"content": [{"type": "tool_use", "name": и, "id": f"t{n}"}],
                                     "usage": usage}}
               for n, и in enumerate(инструменты)]
    return записи


def запрос(время: str, текст: str = "сделай") -> dict:
    return {"type": "user", "timestamp": время, "promptId": f"p-{время}",
            "message": {"role": "user", "content": текст}}


def результаты(время: str, ошибок: int, всего_: int) -> dict:
    блоки = [{"type": "tool_result", "tool_use_id": f"t{n}", "content": "ok",
              "is_error": n < ошибок} for n in range(всего_)]
    return {"type": "user", "timestamp": время, "message": {"role": "user", "content": блоки}}


def файл(записи: list[dict]) -> Path:
    п = Path(tempfile.mkdtemp()) / "t.jsonl"
    п.write_text("\n".join(json.dumps(з, ensure_ascii=False) for з in записи) + "\n",
                 encoding="utf-8")
    return п


