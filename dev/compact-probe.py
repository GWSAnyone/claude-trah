#!/usr/bin/env python3
"""Что стало со сводкой и с прицепленными файлами после сжатия.

Сводка сжатия в интерфейс не выводится — она ложится в стенограмму сессии.
Здесь достаём её длину и смотрим, чем вернулись файлы, читанные до сжатия:
текстом или пометкой. Это единственная проверка правки
`reminder-compact-file-reference`: пробой в ловушку сжатие не поймать.

Использование: compact-probe.py <стенограмма.jsonl | улов-посредника.jsonl>

Артефакта два, и они отвечают на РАЗНЫЕ вопросы. Стенограмма знает размеры
сводок. Пометок про файлы в ней нет ни одной — обмер 29.08.2026: они
вклеиваются в тело запроса при сборке и на диск не ложатся, а всё, что находил
там прежний поиск, было содержимым прочитанных файлов. Пометки считаются только
по улову `relay.py`.
"""
import json
import sys
from pathlib import Path

МЕТКИ = {
    "ссылка вместо содержимого (наш текст)": "Its contents are not carried over",
    "ссылка вместо содержимого (штатный текст)": "the contents are too large to include",
    # Сводку ищем НЕ по этой строке, а по пометке записи `isCompactSummary`:
    # `<summary>` встречается ещё и в уведомлениях о фоновых задачах. Метка
    # оставлена в списке ради единообразия вывода.
    "сводка сжатия": "<summary>",
}


def оценка(s: str) -> int:
    кир = sum(1 for c in s if "Ѐ" <= c <= "ӿ")
    return round(кир / 1.7 + (len(s) - кир) / 3.8)


def тексты(запись: dict):
    """Текст сообщения, включая вложенные блоки, но БЕЗ результатов инструментов.

    Пометка про файл приезжает служебным блоком внутри пользовательской записи,
    и лежит она в `content` блока, а не в `text` — прежняя редакция брала
    только `text` и не видела её вовсе.

    А `toolUseResult` сюда не берётся намеренно: в нём лежит содержимое
    прочитанных файлов. Обмер 29.08.2026: наш собственный кусок
    `reminder-compact-file-reference.md` содержит обе искомые строки, я его в
    той же сессии читал — и счёт рос на прочитанном, а не на случившемся.
    """
    м = запись.get("message") or {}
    с = м.get("content")
    if isinstance(с, str):
        yield с
        return
    if not isinstance(с, list):
        return
    for б in с:
        if not isinstance(б, dict):
            continue
        for ключ in ("text", "content"):
            зн = б.get(ключ)
            if isinstance(зн, str):
                yield зн
            elif isinstance(зн, list):
                for вн in зн:
                    if isinstance(вн, dict) and isinstance(вн.get("text"), str):
                        yield вн["text"]


def по_улову(записи: list[dict]) -> int:
    """Пометки считаем по ЗАПРОСАМ — это единственное место, где они есть.

    Обмер 29.08.2026: в стенограмме сессии пометки нет ни одной. Она
    вклеивается в тело запроса при его сборке и на диск не ложится вовсе, а всё,
    что там находилось прежним поиском, было содержимым прочитанных файлов и
    текстом самих кусков. Средство отвечало не на тот вопрос и отвечало
    неверно.
    """
    найдено = {и: 0 for и in МЕТКИ if и != "сводка сжатия"}
    for з in записи:
        for сообщение in з.get("body", {}).get("messages") or []:
            с = сообщение.get("content")
            блоки = с if isinstance(с, list) else [с]
            for б in блоки:
                текст = б if isinstance(б, str) else (
                    б.get("text") if isinstance(б, dict) else None)
                if not isinstance(текст, str) or not текст.startswith("Note: "):
                    continue
                for имя, метка in найдено.items():
                    if МЕТКИ[имя] in текст:
                        найдено[имя] += 1
    for имя, сколько in найдено.items():
        print(f"  {имя}: {сколько}")
    if not any(найдено.values()):
        print("  (ни одной пометки — в этом улове сжатие не случалось)")
    return 0


def по_стенограмме(записи: list[dict]) -> int:
    """Из стенограммы берём только размеры сводок: пометок здесь не бывает."""
    сводки = []
    for з in записи:
        if з.get("isCompactSummary"):
            сводки.extend(тексты(з))
    print(f"  сводок сжатия: {len(сводки)}")
    for n, с in enumerate(сводки, 1):
        print(f"    сводка {n}: {len(с)} символов, примерно {оценка(с)} токенов")
    print("  пометок про файлы здесь нет по устройству: они вклеиваются в тело\n"
          "  запроса и на диск не ложатся. Считать их можно только по улову\n"
          "  посредника — `relay.py`.")
    return 0


def main() -> int:
    путь = Path(sys.argv[1])
    записи = []
    for строка in путь.read_text(errors="replace").splitlines():
        if not строка.strip():
            continue
        try:
            записи.append(json.loads(строка))
        except json.JSONDecodeError:
            continue

    улов = bool(записи) and "body" in записи[0]
    print(f"записей: {len(записи)}  ({'улов посредника' if улов else 'стенограмма сессии'})")

    if улов:
        return по_улову(записи)
    return по_стенограмме(записи)


if __name__ == "__main__":
    raise SystemExit(main())
