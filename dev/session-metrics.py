from pathlib import Path

ПРОЕКТЫ = Path.home() / ".claude" / "projects"

# Разряды инструментов. Порядок важен: первое совпадение выигрывает.
РАЗРЯДЫ = (
    ("символьные", lambda и: и.startswith("mcp__serena__")),
    ("мышление", lambda и: и.startswith("mcp__sequential-thinking__")),
    ("оболочка", lambda и: и in ("Bash", "BashOutput", "KillShell", "PowerShell")),
    ("правки", lambda и: и in ("Write", "Edit", "MultiEdit", "NotebookEdit")),
    ("текстовые", lambda и: и in ("Read", "Grep", "Glob", "LS")),
    ("сеть", lambda и: и in ("WebSearch", "WebFetch")),
    ("делегирование", lambda и: и in ("Agent", "Task", "SendMessage")),
)

# Тики. Список собран из claude-code#77136 (528 реакций) плюс русские
# соответствия, потому что владельцу ответ приходит по-русски, а жалоба
# сообщества написана про английский. Регулярки высокой точности: лучше
# пропустить случай, чем считать метрику по ложным срабатываниям.
ТИКИ: dict[str, re.Pattern] = {
    # определение через отрицание: «Это не X. Это Y» / «не A, а B»
    "отрицание": re.compile(
        r"(?:\bне\s+\w+[,.]\s+(?:а|это)\s)"
        r"|(?:\bnot\s+\w+[.,]\s+(?:It|it)'?s?\s)"
        r"|(?:\bне\s+\w+,\s+а\s+\w+)",
        re.IGNORECASE,
    ),
    # «несущая мысль» и прямая калька load-bearing
    "несущий": re.compile(r"load[- ]bearing|\bнесущ(?:ий|ая|ее|ие|ую)\b", re.IGNORECASE),
    "ровно_то": re.compile(r"\bровно\s+(?:то|это|тот|та|те|так|такой)\b", re.IGNORECASE),
    "рамка": re.compile(r"honest framing|честн\w+\s+рамк\w+|правильн\w+\s+рамк\w+", re.IGNORECASE),
    "размахивание": re.compile(r"hand[- ]?wav|reflexive hedging", re.IGNORECASE),
    "спор": re.compile(
        r"here'?s where I'?d push back|вот\s+(?:тут|здесь)\s+я\s+(?:бы\s+)?(?:возраж|поспор)",
        re.IGNORECASE,
    ),
    # оформительские привычки, которые и дают ощущение «переукрашено»
    "тире": re.compile(r"—"),
    "жирный": re.compile(r"\*\*[^*\n]+\*\*"),
}

СЛОВА = re.compile(r"\S+")

# M9 — читаемость. Считать тики оказалось мало: по развёртке 29.08.2026 редкие
# тики на 600 словах не ловятся вовсе (при частоте 0.65 на 1000 ожидание — 0.4
# вхождения), а частый ровно один — длинное тире. Длина предложения меряется
# устойчиво на любом объёме и ближе к жалобе владельца «нереально воспринимать»,
# чем список манер: длинное предложение с врезкой через тире и есть то, что
# приходится перечитывать.
КОД = re.compile(r"```.*?```", re.DOTALL)
ТАБЛИЦА = re.compile(r"^\s*\|.*$", re.MULTILINE)
КОНЕЦ = re.compile(r"[.!?…]+(?=\s|$)")
# Длину предложения считаем ТОЛЬКО по значащим словам. Наивное деление по
# пробелам засчитывает одиночное тире за слово — и тогда M9 растёт ровно от
# того, что меряет M8. Две метрики начали бы подтверждать друг друга вместо
# того, чтобы мерить разное.
СЛОВО = re.compile(r"\w[\w'’-]*")


def предложения(текст: str) -> list[str]:
    """Предложения видимого текста без кода, таблиц и маркеров списка.

    Код и таблицы выброшены намеренно: точка в `2.1.247` и вертикальная черта
    разметки рвут текст на осколки, и средняя длина предложения превращается в
    измерение доли таблиц, а не читаемости.
    """
    чистый = ТАБЛИЦА.sub("", КОД.sub(" ", текст))
    чистый = re.sub(r"^\s*[-*+]\s+|^\s*\d+\.\s+", "", чистый, flags=re.MULTILINE)
    куски = [к.strip() for к in КОНЕЦ.split(чистый)]
    return [к for к in куски if len(СЛОВО.findall(к)) >= 3]


def стенограммы(доводы: list[str], сессий: int | None, проект: str | None) -> list[Path]:
    """Какие файлы считать: явные пути, иначе каталог проекта."""
    пути = [Path(д) for д in доводы if д.endswith(".jsonl")]
    if not пути:
        корень = проект or str(Path.cwd())
        каталог = ПРОЕКТЫ / корень.replace("/", "-")
        if not каталог.is_dir():
            return []
        пути = sorted(каталог.glob("*.jsonl"), key=lambda p: p.stat().st_mtime)
    if сессий:
        пути = пути[-сессий:]
    return пути


def _слов(текст: str) -> int:
    return len(СЛОВА.findall(текст))


def _текст_блока(блок: dict) -> str:
    if блок.get("type") == "text":
        return блок.get("text") or ""
    if блок.get("type") == "thinking":
        return блок.get("thinking") or ""
    return ""


class Пачка:
    """Один ответ модели, собранный из всех записей с общим requestId."""

    __slots__ = ("ключ", "когда", "инструменты", "текст", "размышление",
                 "усилие", "версия", "токены_выход", "токены_вход", "токены_кэш")

    def __init__(self, ключ: str, когда: str):
        self.ключ = ключ
        self.когда = когда
        self.инструменты: list[str] = []
        self.текст = ""
        self.размышление = ""
        self.усилие = "<нет>"
        self.версия = "<нет>"
        self.токены_выход = 0
        self.токены_вход = 0
        self.токены_кэш = 0


def разбор(путь: Path, с_даты: str | None, с_подагентами: bool,
           по_дату: str | None = None) -> tuple[list[Пачка], list[bool], list[str]]:
    """Возвращает (пачки в порядке появления, флаги ошибок вызовов, времена запросов владельца)."""
    группы: dict[str, Пачка] = {}
    порядок: list[str] = []
    ошибки: list[bool] = []
    запросы: list[str] = []
    try:
        строки = путь.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return [], [], []

    # Стенограмма из VS Code несёт копии прежней истории: в сессии Э3
    # (13.09.2026) 36 612 записей из 53 761 были повторами по `uuid`. Без отсева
    # повтор с тем же `requestId` дописывал вызовы в уже собранную пачку и
    # задваивал ошибки и запросы владельца.
    виденные: set[str] = set()
    for строка in строки:
        строка = строка.strip()
        if not строка:
            continue
        try:
            з = json.loads(строка)
        except json.JSONDecodeError:
            continue
        uuid = з.get("uuid")
        if uuid:
            if uuid in виденные:
                continue
            виденные.add(uuid)
        тип = з.get("type")
        if тип not in ("assistant", "user"):
            continue
        if з.get("isSidechain") and not с_подагентами:
            continue
        когда = з.get("timestamp") or ""
        if когда and ((с_даты and когда < с_даты) or (по_дату and когда >= по_дату)):
            continue
        сообщение = з.get("message") or {}
        содержимое = сообщение.get("content")

        if тип == "user":
            # Настоящий запрос владельца против переноски результата вызова.
            if isinstance(содержимое, str):
                if содержимое.strip():
                    запросы.append(когда)
            elif isinstance(содержимое, list):
                есть_результат = any(
                    isinstance(б, dict) and б.get("type") == "tool_result" for б in содержимое
                )
                for б in содержимое:
                    if isinstance(б, dict) and б.get("type") == "tool_result":
                        ошибки.append(bool(б.get("is_error")))
                if not есть_результат and з.get("promptId"):
                    запросы.append(когда)
            continue

        if not isinstance(содержимое, list):
            continue
        ключ = (з.get("requestId") or сообщение.get("id") or з.get("uuid") or когда)
        пачка = группы.get(ключ)
        if пачка is None:
            пачка = группы[ключ] = Пачка(ключ, когда)
            порядок.append(ключ)
            пачка.усилие = з.get("effort") or "<нет>"
            пачка.версия = з.get("version") or "<нет>"
            usage = сообщение.get("usage") or {}
            # usage продублирован по записям группы — берём один раз.
            пачка.токены_выход = int(usage.get("output_tokens") or 0)
            пачка.токены_вход = int(usage.get("input_tokens") or 0)
            пачка.токены_кэш = int(usage.get("cache_creation_input_tokens") or 0)
        for б in содержимое:
            if not isinstance(б, dict):
                continue
            если_тип = б.get("type")
            if если_тип == "tool_use":
                пачка.инструменты.append(б.get("name") or "?")
            elif если_тип == "text":
                пачка.текст += (б.get("text") or "") + "\n"
            elif если_тип == "thinking":
                пачка.размышление += (б.get("thinking") or "") + "\n"

    return [группы[к] for к in порядок], ошибки, запросы


def _разряд(инструмент: str) -> str:
    for имя, годен in РАЗРЯДЫ:
        if годен(инструмент):
            return имя
    return "прочее"


def _секунд(начало: str, конец: str) -> float | None:
    try:
        a = datetime.fromisoformat(начало.replace("Z", "+00:00"))
        b = datetime.fromisoformat(конец.replace("Z", "+00:00"))
    except (ValueError, AttributeError):
        return None
    d = (b - a).total_seconds()
    return d if d >= 0 else None


def метрики(пачки: list[Пачка], ошибки: list[bool], запросы: list[str]) -> dict:
    """Сводит пачки в восемь метрик. Пустой вход даёт нули, а не исключение.

    Метрики бывают двух родов, и путать их нельзя. Пачечные (M1, M2, M7b, M8)
    считаются по одному ответу модели и живут в любой выборке. Запросные
    (M3, M5, M6, M7) требуют разбиения на запросы владельца, а признака
    запроса — усилия, версии — у запроса нет. В разбивке по корзинам их
    считать не из чего, и там они возвращают None, а печатаются как «н/д».
    Ноль вместо None читался бы как измеренный ноль — это ловушка, а не цифра.
    """
    с_вызовами = [п for п in пачки if п.инструменты]
    ширины = [len(п.инструменты) for п in с_вызовами]

    разряды = Counter()
    for п in пачки:
        for и in п.инструменты:
            разряды[_разряд(и)] += 1
    одиночные = Counter(п.инструменты[0] for п in с_вызовами if len(п.инструменты) == 1)

    # Сегменты по запросам владельца: пачки, попавшие между двумя запросами.
    сегменты: list[list[Пачка]] = []
    if запросы:
        границы = sorted(запросы)
        текущий: list[Пачка] = []
        i = 0
        for п in sorted(пачки, key=lambda x: x.когда):
            while i < len(границы) and п.когда >= границы[i]:
                if текущий:
                    сегменты.append(текущий)
                текущий = []
                i += 1
            текущий.append(п)
        if текущий:
            сегменты.append(текущий)

    пачек_на_запрос = [len(с) for с in сегменты if с]
    финальные = [_слов(с[-1].текст) for с in сегменты if с and с[-1].текст.strip()]
    длительности = [
        d for с in сегменты if с
        for d in [_секунд(с[0].когда, с[-1].когда)] if d is not None
    ]
    токены_на_запрос = [sum(п.токены_выход for п in с) for с in сегменты if с]

    # Пачечные близнецы: работают и в корзинах, где сегментов нет.
    токены_на_пачку = [п.токены_выход for п in пачки if п.токены_выход]
    слов_на_ответ = [_слов(п.текст) for п in пачки if п.текст.strip()]

    видимый = "\n".join(п.текст for п in пачки)
    слов_видимых = _слов(видимый)
    фразы = предложения(видимый)
    длины = [len(СЛОВО.findall(ф)) for ф in фразы]
    с_тире = sum(1 for ф in фразы if "—" in ф)
    тики = {имя: len(рег.findall(видимый)) for имя, рег in ТИКИ.items()}
    на_тысячу = {
        имя: round(1000 * n / слов_видимых, 2) if слов_видимых else 0.0
        for имя, n in тики.items()
    }

    def сред(xs, знаков=2):
        return round(sum(xs) / len(xs), знаков) if xs else 0.0

    def мед(xs):
        return round(statistics.median(xs), 2) if xs else 0.0

    def пара(xs, знаков=2):
        return {"среднее": сред(xs, знаков), "медиана": мед(xs)}

    есть_сегменты = bool(сегменты)
    return {
        "пачек": len(с_вызовами),
        "вызовов": sum(ширины),
        "запросов": len(сегменты),
        "M1_ширина": {
            "среднее": сред(ширины),
            "медиана": мед(ширины),
            "максимум": max(ширины) if ширины else 0,
            "доля_одиночных": round(100 * sum(1 for ш in ширины if ш == 1) / len(ширины))
            if ширины else 0,
            "одиночные_топ": одиночные.most_common(5),
        },
        "M2_состав": dict(разряды.most_common()),
        "M3_пачек_на_запрос": пара(пачек_на_запрос) if есть_сегменты else None,
        "M4_ошибок_проц": round(100 * sum(ошибки) / len(ошибки), 1) if ошибки else None,
        "M5_слов_в_ответе": пара(финальные, 0) if есть_сегменты else None,
        "M5b_слов_на_пачку": пара(слов_на_ответ, 0),
        "M6_секунд_на_запрос": пара(длительности, 0) if есть_сегменты else None,
        "M7_токенов_на_запрос": пара(токены_на_запрос, 0) if есть_сегменты else None,
        "M7b_токенов_на_пачку": пара(токены_на_пачку, 0),
        "M8_тиков_на_1000": на_тысячу,
        "M9_читаемость": {
            "предложений": len(фразы),
            "слов_в_предложении": сред(длины),
            "медиана_длины": мед(длины),
            "доля_длинных_проц": round(100 * sum(1 for d in длины if d >= 30) / len(длины))
            if длины else 0,
            "доля_с_тире_проц": round(100 * с_тире / len(фразы)) if фразы else 0,
        },
        "слов_видимых": слов_видимых,
    }


def собрать(пути: list[Path], с_даты: str | None, с_подагентами: bool,
            делить: str | None, по_дату: str | None = None) -> dict[str, dict]:
    """Считает метрики целиком и, если просили, с разбивкой по признаку."""
    все_пачки: list[Пачка] = []
    все_ошибки: list[bool] = []
    все_запросы: list[str] = []
    for путь in пути:
        п, о, з = разбор(путь, с_даты, с_подагентами, по_дату)
        все_пачки.extend(п)
        все_ошибки.extend(о)
        все_запросы.extend(з)

    итог = {"ВСЁ": метрики(все_пачки, все_ошибки, все_запросы)}
    if делить:
        поле = {"effort": "усилие", "version": "версия"}.get(делить)
        if поле:
            корзины: dict[str, list[Пачка]] = defaultdict(list)
            for п in все_пачки:
                корзины[getattr(п, поле)].append(п)
            for имя, список in sorted(корзины.items(), key=lambda kv: -len(kv[1])):
                # Ошибки и запросы по корзинам не делятся: они не несут признака.
                итог[имя] = метрики(список, [], [])
    return итог


def из_журнала(путь: Path, с_даты: str | None, по_дату: str | None,
               сессия: str | None = None) -> dict:
    """Ширина по журналу хука `PostToolBatch` — вторая, независимая дорога.

    Стенограмма восстанавливает пачку группировкой по `requestId`, и это
    восстановление. Хук видит пачку живьём, ровно тем составом, каким она ушла
    в исполнение. Числа обязаны совпасть; расхождение значит, что врёт одна из
    дорог, и по одной этого не увидеть. Сверка 29.08.2026 на сессии
    6d216244: обе дороги дали среднее 2.33, медиану 3, максимум 3, одиночных 33%.
    """
    ширины: list[int] = []
    неуспешных = 0
    вызовов = 0
    одиночные = Counter()
    сессии = set()
    try:
        строки = путь.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return {"пачек": 0}
    for с in строки:
        с = с.strip()
        if not с:
            continue
        try:
            з = json.loads(с)
        except json.JSONDecodeError:
            continue
        когда = з.get("at") or ""
        if когда and ((с_даты and когда < с_даты) or (по_дату and когда >= по_дату)):
            continue
        # Отбор по сессии нужен для сверки двух дорог: журнал копит все сессии
        # подряд, а стенограмма всегда про одну. Без отбора сравнивались бы
        # разные выборки, и совпадение чисел ничего бы не значило.
        if сессия and not str(з.get("session") or "").startswith(сессия):
            continue
        ш = int(з.get("width") or 0)
        if ш <= 0:
            continue
        ширины.append(ш)
        вызовов += ш
        неуспешных += int(з.get("failed") or 0)
        сессии.add(з.get("session") or "")
        имена = з.get("tools") or []
        if ш == 1 and имена:
            одиночные[имена[0]] += 1
    if not ширины:
        return {"пачек": 0}
    return {
        "пачек": len(ширины),
        "вызовов": вызовов,
        "сессий": len(сессии),
        "среднее": round(sum(ширины) / len(ширины), 2),
        "медиана": round(statistics.median(ширины), 2),
        "максимум": max(ширины),
        "доля_одиночных": round(100 * sum(1 for ш in ширины if ш == 1) / len(ширины)),
        "неуспешных_проц": round(100 * неуспешных / вызовов, 1) if вызовов else 0.0,
        "одиночные_топ": одиночные.most_common(5),
    }


def печать_журнала(св: dict, путь: Path) -> None:
    if not св.get("пачек"):
        print(f"журнал пуст или его нет: {путь}")
        return
    print(f"журнал хука: {путь}")
    print(f"  сессий {св['сессий']}, пачек {св['пачек']}, вызовов {св['вызовов']}")
    print(f"  M1 ширина       среднее {св['среднее']}  медиана {св['медиана']}  "
          f"макс {св['максимум']}  одиночных {св['доля_одиночных']}%")
    print(f"  неуспешных вызовов {св['неуспешных_проц']}%")
    if св["одиночные_топ"]:
        print(f"  одиночки: {', '.join(f'{k}×{v}' for k, v in св['одиночные_топ'])}")


def печать(итог: dict[str, dict], файлов: int) -> None:
    def пара(значение: dict | None, знак: str = "") -> str:
        if значение is None:
            return "н/д (в корзине нет запросов владельца)"
        return f"среднее {значение['среднее']}{знак}  медиана {значение['медиана']}{знак}"

    print(f"стенограмм: {файлов}")
    for имя, м in итог.items():
        print(f"\n{'=' * 62}\n{имя}  —  пачек {м['пачек']}, вызовов {м['вызовов']}, "
              f"запросов {м['запросов']}, слов {м['слов_видимых']}")
        ш = м["M1_ширина"]
        print(f"  M1 ширина       среднее {ш['среднее']}  медиана {ш['медиана']}  "
              f"макс {ш['максимум']}  одиночных {ш['доля_одиночных']}%")
        if ш["одиночные_топ"]:
            print(f"     одиночки:    {', '.join(f'{k}×{v}' for k, v in ш['одиночные_топ'])}")
        if м["M2_состав"]:
            состав = м["M2_состав"]
            симв, обол = состав.get("символьные", 0), состав.get("оболочка", 0)
            отн = f"  [символьные/оболочка = {round(симв / обол, 2)}]" if обол else ""
            print(f"  M2 состав       {', '.join(f'{k} {v}' for k, v in состав.items())}{отн}")
        print(f"  M3 пачек/запрос {пара(м['M3_пачек_на_запрос'])}")
        м4 = м["M4_ошибок_проц"]
        print(f"  M4 ошибок       {'н/д' if м4 is None else f'{м4}%'}")
        print(f"  M5 слов/ответ   {пара(м['M5_слов_в_ответе'])}")
        print(f"  M5b слов/пачку  {пара(м['M5b_слов_на_пачку'])}")
        print(f"  M6 секунд       {пара(м['M6_секунд_на_запрос'])}")
        print(f"  M7 токенов/зпр  {пара(м['M7_токенов_на_запрос'])}")
        print(f"  M7b токенов/пач {пара(м['M7b_токенов_на_пачку'])}")
        т = м["M8_тиков_на_1000"]
        print(f"  M8 тиков/1000   {', '.join(f'{k} {v}' for k, v in т.items() if v)}")
        ч = м["M9_читаемость"]
        print(f"  M9 читаемость   предложений {ч['предложений']}, "
              f"слов в предложении {ч['слов_в_предложении']} (медиана {ч['медиана_длины']}), "
              f"длинных {ч['доля_длинных_проц']}%, с тире {ч['доля_с_тире_проц']}%")


def main(argv: list[str] | None = None) -> int:
    р = argparse.ArgumentParser(description="Мерка сессии по стенограммам")
    р.add_argument("пути", nargs="*", help="файлы .jsonl; без них — каталог проекта")
    р.add_argument("--sessions", type=int, default=None, help="только последние N стенограмм")
    р.add_argument("--since", default=None, help="только записи с этой даты (ISO), включительно")
    р.add_argument("--until", default=None, help="только записи ДО этой даты (ISO), исключительно")
    р.add_argument("--project", default=None, help="корень проекта вместо текущего каталога")
    р.add_argument("--with-subagents", action="store_true", help="считать и подагентов")
    р.add_argument("--group-by", choices=("effort", "version"), default=None,
                   help="разбить выборку по признаку")
    р.add_argument("--json", action="store_true", help="выдать JSON вместо таблицы")
    р.add_argument("--hook-log", nargs="?", const="", default=None,
                   metavar="ПУТЬ",
                   help="считать по журналу хука PostToolBatch, а не по стенограммам")
    р.add_argument("--session", default=None,
                   help="только эта сессия (начало идентификатора), для сверки с её стенограммой")
    а = р.parse_args(argv)

    if а.hook_log is not None:
        путь = Path(а.hook_log) if а.hook_log else (
            Path(os.environ.get("TRAH_METRICS_DIR",
                                str(Path.home() / ".claude" / "metrics")))
            / "batches.jsonl")
        св = из_журнала(путь, а.since, а.until, а.session)
        if а.json:
            print(json.dumps(св, ensure_ascii=False, indent=2))
        else:
            печать_журнала(св, путь)
        return 0 if св.get("пачек") else 1

    пути = стенограммы(а.пути, а.sessions, а.project)
    if not пути:
        print("стенограмм не нашлось", file=sys.stderr)
        return 1
    итог = собрать(пути, а.since, а.with_subagents, а.group_by, а.until)
    if а.json:
        print(json.dumps(итог, ensure_ascii=False, indent=2))
    else:
        печать(итог, len(пути))
    return 0


if __name__ == "__main__":
    sys.exit(main())
