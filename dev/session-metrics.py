#!/usr/bin/env python3
"""Мерка сессии: восемь метрик по стенограммам, с разбивкой по чему угодно.

Зачем ещё один инструмент рядом с `batch-width.py`. Тот отвечает на один
вопрос — ширина пачки. Этот отвечает на все восемь, которыми закрываются
итерации плана `docs/plans/2026-08-29-rychagi-kachestva.md`, и умеет главное:
делить выборку по `effort`, версии или ветке. В стенограмме `effort` пишется
на каждый ответ модели, а в истории этой машины он меняется — значит сравнение
уровней снимается с реальной работы, а не с подстроенной задачи.

    M1  ширина пачки: среднее, медиана, доля одиночных
    M2  состав инструментов: оболочка / символьные / текстовые / правки
    M3  пачек на один запрос владельца
    M4  доля неуспешных вызовов
    M5  длина финального ответа в словах
    M6  секунд на один запрос владельца
    M7  токенов на один запрос владельца
    M8  плотность тиков на 1000 слов

УСТРОЙСТВО СТЕНОГРАММЫ, три ловушки, все проверены 29.08.2026 на 170 файлах:

1. Один ответ модели разложен по НЕСКОЛЬКИМ записям — на каждый блок своя
   строка, общий у них `requestId`. Считать по записям значит получить ширину 1
   у всего. Группируем.
2. `usage` в этих записях ОДИНАКОВ: во всех 6061 группах ровно одно различное
   значение `output_tokens`. Складывать по записям — задвоить примерно вдвое.
   Берём одно значение на группу.
3. Текст и вызовы инструментов лежат в РАЗНЫХ записях одной группы. Чтобы
   получить полный ответ, содержимое группы склеивается.

ЧЕГО ЭТА МЕРКА НЕ ВИДИТ. Текстовые блоки, за которыми в том же ходе идёт ещё
размышление, пропадают из стенограммы (claude-code#74260). Значит M5 и знаменатель
M8 занижены систематически, и сравнивать их можно только между собой, а не с
абсолютной истиной.
"""
