#!/usr/bin/env python3
"""Счёт и окрестности строки в бинарнике сборки — истина, когда опись врёт.

ЗАЧЕМ, ЕСЛИ ЕСТЬ `catalogue.py`. Опись форка tweakcc — карта, и она неполна:
проверено 29.08.2026, строк `End git commit messages with` и `Co-Authored-By` в
`prompts-2.1.247.json` нет вовсе, а в бинарнике они есть. Когда куска в описи не
нашлось, ищем здесь, по байтам самого файла версии.

ЧТО ЗНАЧАТ ЧИСЛА. Счёт по сырому файлу ВЫШЕ того, что видит скрипт правок:
часть строк лежит второй копией в области байткода bun, и она патчу не видна.
Поэтому 2 здесь обычно значит одно видимое совпадение. Окончательное число
всегда даёт сама сборка — она отбивается, если якорь найден не столько раз,
сколько объявлено.

    anchors.py 2.1.247 "игла" ["ещё игла"...]   сколько раз встречается
    anchors.py 2.1.247 --around "игла"          текст вокруг каждого вхождения
    anchors.py /путь/к/файлу "игла"             можно и путём, не только версией

Наружу идут только числа — кроме `--around`, который для того и нужен, чтобы
показать окрестность и дать взять якорь точно.
"""
import sys
from pathlib import Path

ВЕРСИИ = Path.home() / ".local/share/claude/versions"


def файл(имя: str) -> Path:
    """Довод — путь или номер версии; версия ищется среди установленных."""
    п = Path(имя)
    if п.exists():
        return п
    return ВЕРСИИ / имя


def счёт(байты: bytes, игла: str) -> int:
    return байты.count(игла.encode())


def окрестность(байты: bytes, игла: str, до: int = 260, после: int = 420) -> list[str]:
    """Куски текста вокруг каждого вхождения иглы."""
    вышло = []
    н = байты.find(игла.encode())
    while н != -1:
        вышло.append(байты[max(0, н - до): н + после].decode("utf-8", errors="replace"))
        н = байты.find(игла.encode(), н + 1)
    return вышло


def main() -> int:
    д = sys.argv[1:]
    if not д:
        print(__doc__)
        return 1
    цель = файл(д[0])
    if not цель.exists():
        print(f"нет такого файла: {цель}")
        return 1
    байты = цель.read_bytes()
    print(f"{цель.name}, {len(байты)} байт")

    if "--around" in д:
        игла = д[д.index("--around") + 1]
        куски = окрестность(байты, игла)
        if not куски:
            print("не найдено")
            return 1
        for к in куски:
            print("-" * 60)
            print(к)
        return 0

    иглы = [a for a in д[1:] if not a.startswith("--")]
    if not иглы:
        print("нечего искать: назовите иглу")
        return 1
    for и in иглы:
        print(f"  {счёт(байты, и):3}  {и[:78]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
