// Движок режима `claude trah` на модах Claude Code (2.1.287+).
//
// Данные — куски комплекта `trah-setup/fragments/*.md` с `route: "mod"` — сюда
// подставляет `trah.py build`: строка `const ДАННЫЕ = …` ниже в исходнике пустая,
// а в собранном моде (`~/.local/share/claude/trah/mod-<версия>/`) в ней лежат
// правки. Править руками собранный файл бесполезно: следующая сборка его затрёт.
//
// ПРОМАХ ЯКОРЯ — НЕ ОШИБКА СЕССИИ. Якорь, не найденный в тексте, оставляет текст
// штатным: режим деградирует до обычного поведения, а не ломается. Узнаёт о
// промахе `trah.py verify` — по журналу `TRAH_MOD_LOG` (событие приходило,
// правка не легла ни разу).
//
// ЧТО ЗДЕСЬ, А ЧТО НЕТ. Мод берёт только те куски, чей текст доходит модом в ТО
// ЖЕ место, что и патчем: описания инструментов, системный промпт главной
// сессии, напоминания. Бриф подагента, дополнения встроенным агентам, задание
// сводки и промпт оценщика `/goal` мод достаёт лишь припиской в другое место
// (задание вместо системного промпта, дополнение вместо замены) — они остались
// патчем бинарника (владелец, 02.10.2026: «нельзя терять качество»).
//
// ВСЁ, ЧТО ЗОВЁТ `$`, — В try. Вызовы `$` асинхронны, и упавший хук пропускается
// ЦЕЛИКОМ, вместе со своей правкой (замер 02.10.2026: `$.fs.write` с путём-обещанием
// уронил все двенадцать хуков пробы, и ни одна метка не доехала).

const ДАННЫЕ = /*@ДАННЫЕ@*/ { правки: [] } /*@/ДАННЫЕ@*/

const журнал = {} // id куска → { пришло, легло }

async function записать($) {
  try {
    const путь = await $.env.get('TRAH_MOD_LOG')
    if (путь) await $.fs.write(путь, JSON.stringify(журнал, null, 1))
  } catch {}
}

function отметить(id, легло) {
  const з = (журнал[id] ??= { пришло: 0, легло: 0 })
  з.пришло += 1
  if (легло) з.легло += 1
}

// Правки одного куска к одному тексту. Возвращает новый текст и легла ли хоть одна.
function применить(текст, кусок) {
  let легло = false
  for (const п of кусок.правки) {
    if (!текст.includes(п.anchor)) continue
    текст = текст.split(п.anchor).join(п.with)
    легло = true
  }
  return [текст, легло]
}

function куски(событие, отбор = () => true) {
  return ДАННЫЕ.правки.filter(к => к.event === событие && отбор(к))
}

// ── файл после сжатия — ссылкой, а не содержимым ─────────────────────────────
//
// После сжатия CLI вкладывает прочитанные до него файлы заново ЦЕЛИКОМ, если они
// влезают под потолок чтения, — сжатие выбрасывает содержимое и тут же
// возвращает его (замер 02.10.2026 на 2.1.287, вложение `file`). Кусок
// `reminder-compact-file-reference` отдаёт вместо него ссылку: тот же текст, что
// CLI пишет сам для файла, обрезанного по потолку. Правила (CLAUDE.md,
// AGENTS.md, `/rules/`, указатель чекпоинта) возвращаются целиком.
//
// Вложение после сжатия от `@`-упоминания по самому событию не отличить: поля
// `detail` в типах 2.1.287 нет. Отличает переписка. Вложение `file` после
// сжатия — это файл, чей путь ни одно сообщение пользователя ПОСЛЕ последней
// сводки не назвало через `@`. Флажок в памяти процесса не годится: ответ на
// вложение CLI спрашивает заново при `--resume`, и в новом процессе флажка уже
// нет. Замер 02.10.2026: `-p`-ход после `/compact` получил notes.txt целиком.
const ПУТЬ_ФАЙЛА = /"file_path":"((?:[^"\\]|\\.)*)"/

async function ссылкаПослеСжатия($, e, текст) {
  const к = ДАННЫЕ.правки.find(к => к.handler === 'ссылка-после-сжатия')
  if (!к || e.type !== 'file' || e.agentId) return null
  const m = текст.match(ПУТЬ_ФАЙЛА)
  if (!m) return null
  const путь = JSON.parse(`"${m[1]}"`)
  const д = к.данные
  if (д.кончается_на.some(х => путь.endsWith(х)) || д.содержит.some(х => путь.includes(х))) return null
  let сообщения
  try { сообщения = await $.session.messages() } catch { return null }
  const сводка = сообщения.findLastIndex(с => с.role === 'user' && с.text.includes(д.сводка))
  if (сводка < 0) return null
  const назван = сообщения.slice(сводка + 1).some(с => с.role === 'user' &&
    [...с.text.matchAll(/@(\S+)/g)].some(([, т]) => {
      т = т.replace(/^\.\/|^~\//, '')
      return путь === т || путь.endsWith('/' + т)
    }))
  if (назван) return null
  отметить(к.id, true)
  return д.начало + путь + к.правки[0].with + д.конец
}

// ── сжатие по заказу ──────────────────────────────────────────────────────────
//
// Сессия заказывает сжатие себе сама: `compact-order.py` кладёт файл
// `~/<данные.каталог>/<id сессии>`, его текст — довесок к указаниям. Заказ
// исполняется в конце хода главной сессии, если файл свежее старта процесса и
// прошлого исполненного: удалить файл мод не может (`$.fs` без удаления).
// `$.session.compact` «отклоняется, пока идёт ход» — если `turn.complete` ещё
// считается ходом, вызов повторяется сразу за ним.
//
// В SDK-сессии (VS Code) `$.session.compact` отклоняется всегда: «not available
// in a headless (-p / SDK) session yet» (2.1.287, проверено 02.10.2026). Там
// заказ исполняет форк расширения — `forkCompactOnOrder` в
// `claude-code-vsc/ext/extension/extension.js` шлёт `/compact` после хода.
const СТАРТ = Date.now()
let исполнен = 0

async function сжатиеПоЗаказу($) {
  const к = ДАННЫЕ.правки.find(к => к.handler === 'сжатие-по-заказу')
  if (!к) return
  let путь, когда
  try {
    путь = `${await $.env.get('HOME')}/${к.данные.каталог}/${await $.session.id()}`
    когда = (await $.fs.stat(путь)).mtimeMs
  } catch { return }
  if (когда <= Math.max(СТАРТ, исполнен)) return
  исполнен = когда
  const указания = (await $.fs.read(путь).catch(() => '')).trim() || undefined
  const сжать = async () => {
    const r = await $.session.compact(указания ? { instructions: указания } : {})
    отметить(к.id, !r.skip)
    await записать($)
  }
  try {
    await сжать()
  } catch {
    setTimeout(() => сжать().catch(() => { отметить(к.id, false); return записать($) }), 0)
  }
}

export function register(on) {
  // Пустой, но не лишний: первый `session.start` CLI ДОЖИДАЕТСЯ до первого
  // запроса. Без него в `-p` первый запрос мог уйти раньше, чем мод загружен, —
  // замер 02.10.2026: проба в ловушку (ответ 400 сразу) не получила ни одной
  // правки, тот же мод при запуске с повторами — все.
  on('session.start', async ($, e, next) => next(e))

  on('turn.complete', async ($, e, next) => {
    const r = await next(e)
    if (!e.agentId) await сжатиеПоЗаказу($)
    return r
  })

  // ── описания инструментов ─────────────────────────────────────────────────
  on('tool.describe', async ($, e, next) => {
    const r = await next(e)
    const свои = куски('tool.describe', к => к.match.tool === e.tool)
    if (!свои.length) return r
    let описание = r.description
    for (const к of свои) {
      const [т, легло] = применить(описание, к)
      описание = т
      отметить(к.id, легло)
    }
    await записать($)
    return { ...r, description: описание }
  })

  // ── системный промпт главной сессии ───────────────────────────────────────
  // Секции ищутся по всему списку: якорь куска не знает, в какой секции он
  // живёт, а id секций (`lean_body`, `communication`, …) — штатные и меняются
  // вместе с составом промпта. До подагентов и оценщика `/goal` это событие НЕ
  // доходит (замер 02.10.2026).
  on('prompt.compose', async ($, e, next) => {
    const r = await next(e)
    const свои = куски('prompt.compose')
    if (!свои.length) return r
    const легло = Object.fromEntries(свои.map(к => [к.id, false]))
    const секции = r.sections.map(с => {
      let текст = с.text
      for (const к of свои) {
        const [т, л] = применить(текст, к)
        текст = т
        if (л) легло[к.id] = true
      }
      return текст === с.text ? с : { ...с, text: текст }
    })
    for (const к of свои) отметить(к.id, легло[к.id])
    await записать($)
    return { sections: секции }
  })

  // ── напоминания, которые CLI вставляет сам ────────────────────────────────
  on('prompt.attachment', async ($, e, next) => {
    const r = await next(e)
    if (r.text == null) return r
    const ссылка = await ссылкаПослеСжатия($, e, r.text)
    if (ссылка != null) {
      await записать($)
      return { text: ссылка }
    }
    let текст = r.text
    const свои = куски('prompt.attachment', к => к.match.type === e.type)
    for (const к of свои) {
      const [т, легло] = применить(текст, к)
      текст = т
      отметить(к.id, легло)
    }
    if (свои.length) await записать($)
    return текст === r.text ? r : { text: текст }
  })

}
