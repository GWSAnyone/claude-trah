#!/usr/bin/env python3
"""Проверки `nudge-capability.py`. Токенов не стоит.

Хук ничего не блокирует, поэтому цена ошибки у него односторонняя: пропуск
стоит одну несказанную подсказку, а ложное срабатывание — доверие ко всем
остальным. Отсюда перекос набора: отрицательных случаев здесь больше, чем
положительных, и они списаны с обычной работы, а не выдуманы.
"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

HOOK = str(Path(__file__).resolve().parent / "nudge-capability.py")
ROOT = str(Path(__file__).resolve().parents[2])

всего = 0
провалов = 0


def check(имя: str, условие: bool, подробность: str = "") -> None:
    global всего, провалов
    всего += 1
    if not условие:
        провалов += 1
        print(f"  ✗ {имя} {подробность}")


def run(prompt: str, session: str = "сессия-1", tmp: str = "/tmp",
        mode: str | None = None, raw: str | None = None):
    payload = raw if raw is not None else json.dumps(
        {"prompt": prompt, "session_id": session, "cwd": ROOT}, ensure_ascii=False)
    env = dict(os.environ, TMPDIR=tmp)
    # Умолчание хука, а не то, что стоит в окружении машины: иначе тест мерит
    # настройку хоста.
    if mode is None:
        env.pop("NUDGE_CAPABILITY", None)
    else:
        env["NUDGE_CAPABILITY"] = mode
    res = subprocess.run([sys.executable, HOOK], input=payload,
                         capture_output=True, text=True, env=env)
    return res.returncode, res.stdout


def сказал_про(текст: str, что: str) -> bool:
    return {"security": "`security`", "sequential": "sequential-thinking"}[что] in текст


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        # ── безопасность: срабатывает ────────────────────────────────────────
        для_срабатывания = [
            ("приманка замера", "Перед выкаткой проверь на дыры хук "
             "trah-setup/hooks/guard-destructive.py — он решает, пускать ли "
             "разрушительную команду."),
            ("прямая просьба", "Проверь этот обработчик на безопасность."),
            ("слово «уязвимость»", "Нет ли тут уязвимостей в разборе токена?"),
            ("по-английски", "Check this handler for vulnerabilities before we ship."),
            ("оборот сообщества", "Сделай security review этой ветки."),
            ("аудит", "Нужен аудит безопасности загрузки файлов."),
        ]
        for i, (имя, prompt) in enumerate(для_срабатывания):
            код, текст = run(prompt, session=f"без-{i}", tmp=tmp)
            check(f"безопасность: {имя}", код == 0 and сказал_про(текст, "security"),
                  repr(текст[:80]))

        # ── безопасность: молчит ─────────────────────────────────────────────
        молчание = [
            ("обычная проверка тестов", "Проверь тесты и почини красный."),
            ("«безопасно ли» без разбора", "Безопасно ли просто удалить этот файл?"),
            ("проверка пароля как задача", "Напиши функцию проверки пароля."),
            ("дыра в другом смысле", "В таблице дыры в нумерации, почини счётчик."),
            ("правка стиля", "Поменяй цвет кнопки на синий."),
            ("сборка", "Собери проект и покажи ошибки компиляции."),
        ]
        for i, (имя, prompt) in enumerate(молчание):
            код, текст = run(prompt, session=f"тихо-{i}", tmp=tmp)
            check(f"молчит: {имя}", код == 0 and текст == "", repr(текст[:80]))

        # ── разбор последствий ───────────────────────────────────────────────
        длинная = ("Мы думаем перенести хранение чекпоинтов из файла "
                   ".claude/.checkpoint-* в sqlite. Разбери последствия: кто "
                   "сейчас читает указатель, что сломается при переносе, в "
                   "каком порядке мигрировать и где потеряем восстановление "
                   "после сжатия.")
        код, текст = run(длинная, session="раз-1", tmp=tmp)
        check("разбор: оба признака и длина", код == 0 and сказал_про(текст, "sequential"),
              repr(текст[:80]))

        короткая = "Перенеси функцию в соседний файл, проверь зависимости."
        код, текст = run(короткая, session="раз-2", tmp=tmp)
        check("разбор: короткий перенос не в счёт", код == 0 and текст == "",
              repr(текст[:80]))

        без_последствий = ("Перенеси все вызовы старого клиента на новый по "
                           "всему дереву, включая тесты и примеры, и поправь "
                           "импорты там, где они разъехались после переименования.")
        код, текст = run(без_последствий, session="раз-3", tmp=tmp)
        check("разбор: перемена без последствий — молчание", код == 0 and текст == "",
              repr(текст[:80]))

        без_перемены = ("Расскажи, кто сейчас читает указатель чекпоинта и что "
                        "случится, если он окажется пустым: интересуют "
                        "последствия для восстановления после сжатия и для "
                        "хука, который его пишет.")
        код, текст = run(без_перемены, session="раз-4", tmp=tmp)
        check("разбор: последствия без перемены — молчание", код == 0 and текст == "",
              repr(текст[:80]))

        # ── способность уже названа ──────────────────────────────────────────
        код, текст = run("Позови навык security и проверь на дыры этот хук.",
                         session="назв-1", tmp=tmp)
        check("навык назван — подсказка не нужна", код == 0 and текст == "",
              repr(текст[:80]))

        код, текст = run(длинная + " Возьми sequential-thinking.",
                         session="назв-2", tmp=tmp)
        check("разбор назван — подсказка не нужна", код == 0 and текст == "",
              repr(текст[:80]))

        код, текст = run("Проверь на дыры", raw=json.dumps(
            {"prompt": "/security проверь на дыры", "session_id": "назв-3"}), tmp=tmp)
        check("прямой вызов через слэш — молчание", код == 0 and текст == "",
              repr(текст[:80]))

        # ── один раз за сессию ───────────────────────────────────────────────
        код, первый = run("Проверь этот обработчик на безопасность.",
                          session="повтор", tmp=tmp)
        код2, второй = run("И ещё раз проверь на дыры соседний файл.",
                           session="повтор", tmp=tmp)
        check("первый раз — сказал", сказал_про(первый, "security"), repr(первый[:60]))
        check("второй раз в той же сессии — молчит", код2 == 0 and второй == "",
              repr(второй[:80]))
        код3, третий = run("Проверь этот обработчик на безопасность.",
                           session="другая-сессия", tmp=tmp)
        check("другая сессия — снова сказал", сказал_про(третий, "security"),
              repr(третий[:60]))

        # Две способности разом: память по одной не глушит другую.
        обе = ("Перед выкаткой проверь на дыры и заодно разбери последствия: "
               "мы переносим хранилище в sqlite, что сломается и в каком "
               "порядке мигрировать, кто сейчас читает указатель.")
        код, текст = run(обе, session="обе", tmp=tmp)
        check("две способности разом — обе названы",
              сказал_про(текст, "security") and сказал_про(текст, "sequential"),
              repr(текст[:80]))
        код, ещё = run(обе, session="обе", tmp=tmp)
        check("повтор обеих — молчание", код == 0 and ещё == "", repr(ещё[:80]))

        # ── выключатель и мусор на входе ─────────────────────────────────────
        код, текст = run("Проверь на безопасность этот код.", session="выкл",
                         tmp=tmp, mode="off")
        check("выключатель гасит", код == 0 and текст == "", repr(текст[:80]))

        код, текст = run("", session="пусто", tmp=tmp)
        check("пустая задача — тишина", код == 0 and текст == "", repr(текст[:80]))

        код, текст = run("", raw="не json", tmp=tmp)
        check("мусор на входе не роняет", код == 0 and текст == "", repr(текст[:80]))

        код, текст = run("", raw=json.dumps({"session_id": "нет-задачи"}), tmp=tmp)
        check("нет поля prompt — тишина", код == 0 and текст == "", repr(текст[:80]))

        код, текст = run("Проверь этот обработчик на безопасность.",
                         raw=json.dumps({"prompt": "Проверь этот обработчик на "
                                                   "безопасность."}), tmp=tmp)
        check("нет session_id — подсказка всё равно даётся",
              код == 0 and сказал_про(текст, "security"), repr(текст[:80]))

        # Некуда писать состояние: подскажем лишний раз, но не упадём.
        код, текст = run("Проверь этот обработчик на безопасность.",
                         session="без-записи", tmp="/proc/нет-такого")
        check("состояние некуда писать — не падает",
              код == 0 and сказал_про(текст, "security"), repr(текст[:80]))

    print(f"всего: {всего}   провалов: {провалов}")
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(main())
