#!/usr/bin/env python3
"""Проверки `goal.py` — чтения активной цели из стенограммы.

Стенограммы синтетические: настоящей с `goal_status` под рукой нет, а форма
записи снята с живого файла 03.09.2026 — вложение лежит записью верхнего
уровня `{"type":"attachment","attachment":{...}}`.
"""
import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import goal  # noqa: E402

всего = 0
провалов = 0


def check(имя: str, ок: bool, деталь: str = "") -> None:
    global всего, провалов
    всего += 1
    if not ок:
        провалов += 1
    print(f"{'✓' if ок else '✗'} {имя}" + (f"  — {деталь}" if not ок and деталь else ""))


def запись(**поля) -> str:
    """Запись-вложение goal_status в форме живой стенограммы."""
    return json.dumps({
        "type": "attachment",
        "uuid": "u",
        "timestamp": "2026-09-03T12:00:00.000Z",
        "attachment": {"type": "goal_status", **поля},
    }, ensure_ascii=False)


ПОСТАНОВКА = запись(met=False, sentinel=True, condition="тесты зелены")
ОТКАЗ1 = запись(met=False, condition="тесты зелены", reason="не запускали")
ОТКАЗ2 = запись(met=False, condition="тесты зелены", reason="один упал")
ДОСТИГНУТА = запись(met=True, condition="тесты зелены", reason="27/0", iterations=3)
ПРОВАЛЕНА = запись(met=False, failed=True, condition="тесты зелены", reason="нет сети")
СНЯТА = запись(met=True, sentinel=True, condition="тесты зелены")
ЧУЖОЕ = json.dumps({"type": "assistant", "message": {"content": "goal_status"}})
БИТАЯ = "{это не json"


def стенограмма(*строки) -> str:
    ф = tempfile.NamedTemporaryFile("w", suffix=".jsonl", delete=False,
                                    encoding="utf-8")
    with ф:
        for с in строки:
            ф.write(с + "\n")
    return ф.name


пути = []


def с(*строки) -> str:
    п = стенограмма(*строки)
    пути.append(п)
    return п


try:
    # ── когда цели нет ───────────────────────────────────────────────────────
    check("файла нет — None", goal.состояние("/нет/такого.jsonl") is None)
    check("пустой путь — None", goal.состояние("") is None)
    check("None вместо пути — None", goal.состояние(None) is None)
    check("стенограмма без вложений — None", goal.состояние(с(ЧУЖОЕ)) is None)

    # ── активная цель ────────────────────────────────────────────────────────
    ц = goal.состояние(с(ПОСТАНОВКА))
    check("только постановка — цель активна", ц is not None)
    check("условие прочитано дословно", ц and ц["условие"] == "тесты зелены",
          str(ц))
    check("отказов пока ноль", ц and ц["отказов"] == 0, str(ц))
    check("причины пока нет", ц and ц["причина"] is None, str(ц))

    ц = goal.состояние(с(ПОСТАНОВКА, ОТКАЗ1, ОТКАЗ2))
    check("два отказа сосчитаны", ц and ц["отказов"] == 2, str(ц))
    check("причина берётся последняя", ц and ц["причина"] == "один упал", str(ц))

    # ── цель закрыта ─────────────────────────────────────────────────────────
    check("достигнута — цели нет",
          goal.состояние(с(ПОСТАНОВКА, ОТКАЗ1, ДОСТИГНУТА)) is None)
    check("признана невыполнимой — цели нет",
          goal.состояние(с(ПОСТАНОВКА, ОТКАЗ1, ПРОВАЛЕНА)) is None)
    check("снята вручную — цели нет",
          goal.состояние(с(ПОСТАНОВКА, ОТКАЗ1, СНЯТА)) is None)

    # ── вторая постановка обнуляет счёт ──────────────────────────────────────
    # Иначе отказы прежней цели приписывались бы нынешней, и потолок срабатывал
    # бы на ровном месте сразу после перепостановки.
    ц = goal.состояние(с(ПОСТАНОВКА, ОТКАЗ1, ОТКАЗ2, ДОСТИГНУТА,
                         ПОСТАНОВКА, ОТКАЗ1))
    check("счёт идёт с ПОСЛЕДНЕЙ постановки", ц and ц["отказов"] == 1, str(ц))

    # ── устойчивость разбора ────────────────────────────────────────────────
    ц = goal.состояние(с(БИТАЯ, ЧУЖОЕ, ПОСТАНОВКА, БИТАЯ, ОТКАЗ1))
    check("битая строка и чужая запись не ломают разбор",
          ц and ц["отказов"] == 1, str(ц))

    без_условия = запись(met=False, sentinel=True)
    check("вложение без условия — цели нет",
          goal.состояние(с(без_условия)) is None)

    # ── потолок ─────────────────────────────────────────────────────────────
    check("потолок — десять", goal.ПОТОЛОК_ОТКАЗОВ == 10,
          str(goal.ПОТОЛОК_ОТКАЗОВ))
    check("None не застряла", not goal.застряла(None))
    check("девять отказов — не застряла", not goal.застряла({"отказов": 9}))
    check("десять отказов — застряла", goal.застряла({"отказов": 10}))

    ц = goal.состояние(с(ПОСТАНОВКА, *[ОТКАЗ1] * 10))
    check("десять отказов подряд читаются как застревание",
          ц and goal.застряла(ц), str(ц))

    # ── указание к выжимке ──────────────────────────────────────────────────
    текст = goal.указание_к_выжимке({"условие": "тесты зелены", "отказов": 0})
    check("указание несёт условие дословно", "«тесты зелены»" in текст)
    check("указание требует раздел в выжимке", "## Active goal" in текст)
    check("указание объясняет, почему без него цель ломается",
          "reads ONLY the transcript" in текст)
    check("указание требует чисел, а не слов", "in numbers" in текст)
    check("указание помнит про решения под вопросом",
          "under uncertainty" in текст)
finally:
    for п in пути:
        try:
            os.unlink(п)
        except OSError:
            pass

print(f"\nвсего: {всего}   провалов: {провалов}")
sys.exit(1 if провалов else 0)
