#!/usr/bin/env python3
"""Заказать сжатие самой себе. Не хук — помощник, живущий рядом с хуками.

# Зачем он есть

`/compact` исполняется только с клавиатуры. Каждый путь, которым текст попадает
в очередь сессии не от человека — кадр по сокету, `SendMessage`, доклад
наблюдателя, автопродолжение, крон, poll-событие, мост SDK, — ставит
`skipSlashCommands`, и команда приезжает обычным текстом. Поэтому сжатие
случалось либо на потолке окна, либо когда человек нажмёт: обе точки выбирает
не тот, кто знает, закончен ли кусок работы.

Кусок бинарника `sys-compact-on-order` открывает ровно одну щель: кадр
`type:"user"` с текстом `/compact…`, пришедший от СВОЕГО процесса, исполняется
как команда. Свой — по родословной: ядро отдаёт pid подключившегося через
SO_PEERCRED, дальше читаются его предки, и своим считается тот, у кого pid
сессии среди них. Этот скрипт запускается инструментом Bash, то есть прямым
потомком сессии, и условию отвечает (проверено 30.08.2026: в стенограмме
пробной сессии кадр записан как `origin.selfSent: true`, а следом лежит запись
`<command-name>/compact</command-name>` — форма, которую CLI пишет только при
ИСПОЛНЕНИИ команды).

Заказ встаёт в очередь и разбирается ПОСЛЕ текущего хода: модель доделывает,
отвечает — и сжатие идёт. Это ровно та точка, которой не хватало.

# Почему чекпоинт проверяется здесь, а не хуком

`PreCompact` (`checkpoint.py guard`) уже отбивает ручное сжатие без свежего
чекпоинта. Гонять заказ через его отказ — лишний круг: текст отказа уходит в
окно терминала, а не обязательно к модели, и ход тратится впустую. Здесь
проверка стоит ДО заказа, и ответ приходит тем же ходом, прямо в результате
Bash: чекпоинт протух — сжатие не заказано, вот что сделать.

Правило свежести берётся у `checkpoint.py`, а не переписывается: две редакции
одного порога разойдутся молча.

# Что НЕ посылается

`session_id` в кадре по умолчанию не ставится. Кусок бинарника принимает его
как запасной признак «свой», но выше по обработчику стоит проверка, которая
РОНЯЕТ кадр целиком, если объявленный id не совпал с настоящим. Идентификатор
в окружении фиксируется при запуске сессии и после сжатия может разойтись с
живым — тогда заказ пропал бы молча. Родословная такого изъяна не имеет.
Ключ `--id` оставлен для тех, кто зовёт снаружи и родством не обладает.

Использование:
    compact-order.py [довесок к указаниям] [--again] [--id] [--dry-run]

Коды возврата: 0 — заказано; 1 — отказано по делу (чекпоинт, повтор);
2 — сломано окружение (нет сокета).
"""
import importlib.util
import json
import os
import sys
import time
from pathlib import Path

ХУКИ = Path(os.environ.get("TRAH_HOOKS_DIR", str(Path.home() / ".claude" / "hooks")))

# Транспорт лежит рядом одним файлом: форма кадра написана в `sockmsg.py`
# один раз, потому что ошибиться в ней — значит промахнуться молча.
sys.path.insert(0, str(ХУКИ))
import sockmsg  # noqa: E402

# Повторный заказ в течение этого срока считается промахом, а не намерением:
# сжатие уже идёт, второе съело бы только что родившуюся сводку.
ПОВТОР_СЕК = 5 * 60


def чекпоинт_модуль():
    """Модуль `checkpoint.py` рядом. Ошибка импорта — не повод молчать."""
    путь = ХУКИ / "checkpoint.py"
    if not путь.exists():
        raise SystemExit(f"нет {путь}: помощник ставится вместе с хуками")
    спец = importlib.util.spec_from_file_location("checkpoint_hook", путь)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль



def метка_повтора(cp, cwd: str, session_id: str) -> Path:
    return Path(cwd) / ".claude" / f".compact-ordered-{cp.suffix_for(session_id)}"


def недавно(файл: Path) -> float | None:
    """Сколько секунд назад заказывали в прошлый раз, или None."""
    try:
        return time.time() - файл.stat().st_mtime
    except OSError:
        return None


def main(аргументы: list[str]) -> int:
    снова = "--again" in аргументы
    с_идентификатором = "--id" in аргументы
    вхолостую = "--dry-run" in аргументы
    довесок = " ".join(a for a in аргументы if not a.startswith("--")).strip()

    путь = sockmsg.путь_сокета()
    if not sockmsg.есть_канал(путь):
        sys.stderr.write(
            "Сокет сессии не найден: заказать сжатие некуда.\n"
            f"  CLAUDE_CODE_MESSAGING_SOCKET={os.environ.get('CLAUDE_CODE_MESSAGING_SOCKET')!r}\n"
            f"  CLAUDE_PID={os.environ.get('CLAUDE_PID')!r}\n"
            "Так бывает, если скрипт запущен не из сессии.\n")
        return 2

    cp = чекпоинт_модуль()
    cwd = os.getcwd()
    session_id = os.environ.get("CLAUDE_CODE_SESSION_ID", "")
    путь_чекпоинта = cp.resolve_checkpoint(cwd, session_id)
    данные = cp.load(путь_чекпоинта)

    if данные is None:
        sys.stderr.write(
            "Сжатие НЕ заказано: чекпоинта нет.\n\n"
            "Разговор свернётся в пересказ, и всё, что выработано, но не "
            "записано на диск, пропадёт. Сначала `/checkpoint`, потом позвать "
            "этот скрипт снова.\n")
        return 1

    if беда := cp.stale_reason(путь_чекпоинта, данные):
        вид, минут = беда
        что = (f"чекпоинт протух на {минут} мин" if вид == "stale" else
               f"файл чекпоинта на {минут} мин В БУДУЩЕМ — разошлись часы "
               "машины, и судить о свежести нечем")
        sys.stderr.write(
            f"Сжатие НЕ заказано: {что}.\n\n"
            f"  записан: {cp.written_at(путь_чекпоинта, данные)}\n"
            f"  план:    {данные.get('plan', '—')}\n\n"
            "С тех пор сделано многое, чего в плане нет. `/checkpoint`, потом "
            "сюда снова.\n")
        return 1

    метка = метка_повтора(cp, cwd, session_id)
    прошло = недавно(метка)
    if прошло is not None and прошло < ПОВТОР_СЕК and not снова:
        sys.stderr.write(
            f"Сжатие НЕ заказано: предыдущий заказ был {int(прошло)} с назад.\n\n"
            "Оно разбирается в конце хода — скорее всего уже идёт. Если это "
            "всё-таки нужно повторить, добавь `--again`.\n")
        return 1

    текст = "/compact" + (" " + довесок if довесок else "")
    кадр: dict = {"type": "user", "message": {"content": текст}}
    if с_идентификатором and session_id:
        кадр["session_id"] = session_id

    if вхолостую:
        print(json.dumps({"сокет": путь, "кадр": кадр}, ensure_ascii=False))
        return 0

    try:
        sockmsg.отправить(путь, кадр)
    except OSError as e:
        sys.stderr.write(f"Кадр не ушёл: {e}\n")
        return 2

    метка.parent.mkdir(parents=True, exist_ok=True)
    метка.write_text(time.strftime("%Y-%m-%dT%H:%M:%S") + "\n", encoding="utf-8")
    print(f"Сжатие заказано: {текст!r} → {путь}\n"
          "Оно сработает в конце этого хода, после твоего ответа. "
          "Указания к пересказу подаёт хук PreCompact — повторять их не нужно.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
