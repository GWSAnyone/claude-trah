#!/usr/bin/env python3
"""Кадр в сокет своей же сессии. Общий транспорт для трёх соседей.

Сессия открывает сокет `<каталог времени выполнения>/cc-socks/<pid>.sock` и
кладёт путь к нему в окружение всего, что запускает. Кадр — строка JSON:

    {"type": "user", "message": {"content": "…"}}

Сообщение встаёт в очередь и разбирается ПОСЛЕ текущего хода. Это и есть та
точка, ради которой всё затевалось: работа доделана, ответ дан — и только
тогда приходит следующее.

Что важно знать про то, чем кадр становится:

  * обычный текст приезжает сообщением от соседа, с припиской «это не от
    твоего пользователя». Приписка намеренная и полезная: она запрещает
    считать такое сообщение согласием владельца;
  * текст `/compact…` от СВОЕГО процесса исполняется как команда — это делает
    кусок бинарника `sys-compact-on-order`. Своим считается тот, у кого pid
    сессии среди предков; проверяет это ядро, а не кадр.

Три места пользуются одним этим файлом, чтобы форма строки была написана один
раз: ошибиться в ней значит промахнуться молча — CLI просто уронит кадр.
"""
import json
import os
import socket
import time


def путь_сокета() -> str:
    """Сокет этой сессии: из окружения, а если его нет — собранный по pid."""
    из_среды = os.environ.get("CLAUDE_CODE_MESSAGING_SOCKET")
    if из_среды:
        return из_среды
    pid = os.environ.get("CLAUDE_PID")
    корень = os.environ.get("XDG_RUNTIME_DIR") or f"/run/user/{os.getuid()}"
    return f"{корень}/cc-socks/{pid}.sock" if pid else ""


def отправить(путь: str, кадр: dict) -> None:
    """Одна строка JSON в сокет. Ответа не ждём: обработчик отвечать не обязан."""
    с = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    с.settimeout(5)
    с.connect(путь)
    с.sendall((json.dumps(кадр, ensure_ascii=False) + "\n").encode())
    # Дать обработчику дочитать строку до закрытия соединения.
    time.sleep(0.4)
    с.close()


def послать(текст: str, приоритет: str = "next", session_id: str = "") -> str:
    """Отправить текст себе. Возвращает пустую строку при успехе, иначе беду.

    `session_id` по умолчанию НЕ ставится: обработчик роняет весь кадр, если
    объявленный идентификатор не совпал с живым, а тот, что лежит в окружении,
    фиксируется при запуске сессии и может разойтись. Родословная надёжнее.
    """
    путь = путь_сокета()
    if not путь or not os.path.exists(путь):
        return f"сокета нет: {путь or '(не назван)'}"
    кадр: dict = {"type": "user", "message": {"content": текст}}
    if приоритет in ("now", "next", "later"):
        кадр["priority"] = приоритет
    if session_id:
        кадр["session_id"] = session_id
    try:
        отправить(путь, кадр)
    except OSError as e:
        return f"кадр не ушёл: {e}"
    return ""
