#!/usr/bin/env python3
"""PostToolBatch: учёт ширины пачки. НИЧЕГО не блокирует.

Зачем отдельное событие. `Stop` срабатывает раз на весь ответ, `PostToolUse` —
на каждый вызов; ни то, ни другое не видит ПАЧКУ. `PostToolBatch` срабатывает
ровно на неё: один раз после того, как разрешилась группа параллельных вызовов,
и до следующего обращения к модели. Это единственное место, откуда ширину видно
живьём, а не восстановлением по стенограмме.

Устройство входа проверено по бинарнику 2.1.247, а не по документации, и
документация в одном месте врёт: обещанного поля `batch_results` там нет вовсе
(0 вхождений), список зовётся `tool_calls` (6 вхождений). Каждый его элемент —
объект с `tool_name`, `tool_input` и, если вызов успел ответить, `tool_response`.

ХУК ОБЯЗАН БЫТЬ БЕЗВРЕДНЫМ. Он стоит на горячем пути между пачкой и следующим
обращением к модели, и `exit 2` здесь оборвал бы агентский цикл. Поэтому выход
всегда 0, а любое исключение гасится: сломанная мерка не стоит сломанной сессии.
"""

import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

def журнал() -> Path:
    """Куда писать. Вычисляется В ФУНКЦИИ, а не на импорте, и вот почему.

    `Path.home()` бросает, когда домашний каталог не определяется — так бывает
    в контейнере, запущенном с `--user`, у которого нет записи в `/etc/passwd`.
    На уровне модуля это исключение не поймать ничем, и хук выходит с кодом 1,
    нарушая собственный договор «выход всегда 0».

    `or`, а не значение по умолчанию у `get`: переменная, выставленная В ПУСТУЮ
    строку, умолчание не подхватывает, и журнал уезжает в текущий каталог, то
    есть в репозиторий. Проверено запуском 29.08.2026 — уезжал.
    """
    корень = os.environ.get("TRAH_METRICS_DIR") or str(
        Path.home() / ".claude" / "metrics")
    return Path(корень) / "batches.jsonl"

# Потолок журнала. Пачек за день бывает тысячи, строка весит около сотни байт;
# сотня мегабайт — это годы работы, но диск чужой, и молча его заполнять нельзя.
ПОТОЛОК = 100 * 1024 * 1024


def запись(payload: dict) -> dict | None:
    """Строка журнала по одному событию, или None если считать нечего."""
    вызовы = payload.get("tool_calls")
    if not isinstance(вызовы, list) or not вызовы:
        return None

    имена: list[str] = []
    неуспешных = 0
    for в in вызовы:
        if not isinstance(в, dict):
            continue
        имя = в.get("tool_name")
        # Элемент без строкового имени пропускаем, а не считаем безымянным.
        # Сам харнесс такие отбрасывает (`!("tool_name" in e) || typeof
        # e.tool_name !== "string"` -> null), и досчитывать их значило бы
        # завышать ширину — то есть портить ровно ту величину, ради которой
        # хук и написан. Мерка обязана ошибаться в меньшую сторону.
        if not isinstance(имя, str) or not имя:
            continue
        имена.append(имя)
        # `succeeded` есть не всегда; когда его нет, за неудачу считаем только
        # явную пометку в ответе. Догадываться о неуспехе по пустому ответу
        # нельзя: половина инструментов законно отвечает пусто.
        если_успех = в.get("succeeded")
        ответ = в.get("tool_response")
        явная_ошибка = isinstance(ответ, dict) and ответ.get("is_error") is True
        if если_успех is False or явная_ошибка:
            неуспешных += 1

    if not имена:
        return None

    return {
        "at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "session": payload.get("session_id") or "",
        "cwd": payload.get("cwd") or "",
        "width": len(имена),
        "tools": имена,
        "failed": неуспешных,
    }


def дописать(строка: dict) -> None:
    путь = журнал()
    путь.parent.mkdir(parents=True, exist_ok=True)
    if путь.exists() and путь.stat().st_size > ПОТОЛОК:
        return
    with путь.open("a", encoding="utf-8") as ф:
        ф.write(json.dumps(строка, ensure_ascii=False) + "\n")


def main() -> int:
    try:
        payload = json.load(sys.stdin)
    except Exception:
        return 0
    try:
        строка = запись(payload)
        if строка is not None:
            дописать(строка)
    except Exception:
        # Молча. Хук на горячем пути не имеет права ни падать, ни говорить.
        return 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
