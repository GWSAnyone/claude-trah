#!/usr/bin/env python3
"""Проверки `nudge-compact.py`. Токенов не стоит.

Хук будит следующий ход, а значит его ложное срабатывание стоит лишнего хода
модели, а не одной несказанной строки. Отсюда перекос набора: границы лесенки
проверяются с обеих сторон, а «молчит» проверяется на каждом пути, которым хук
может замолчать.

Кадр ловится настоящим сокетом: форма строки — это то, что разбирает CLI, и
ошибиться в ней значит промахнуться молча.
"""
import json
import os
import socket
import subprocess
import sys
import tempfile
import threading
import time
from pathlib import Path

HOOK = str(Path(__file__).resolve().parent / "nudge-compact.py")
М = 1_000_000

всего = 0
провалов = 0


def check(имя: str, условие: bool, подробность: str = "") -> None:
    global всего, провалов
    всего += 1
    if not условие:
        провалов += 1
        print(f"  ✗ {имя} {подробность}")


# Сессия-заглушка: общая для четырёх наборов; под Windows — именованный канал.
sys.path.insert(0, str(Path(__file__).resolve().parent))
from ear_for_tests import Ухо  # noqa: E402


def модуль(окружение: dict | None = None):
    """Свежий разбор хука. С `окружение` — под другими порогами.

    Пороги читаются на импорте, поэтому проверить настройку можно только
    импортом заново: подменить константу после загрузки значило бы проверять
    не тот путь, каким модуль живёт в работе.
    """
    import importlib.util
    прежнее = {}
    if окружение:
        for ключ, значение in окружение.items():
            прежнее[ключ] = os.environ.get(ключ)
            os.environ[ключ] = значение
    try:
        спец = importlib.util.spec_from_file_location("nudge_compact", HOOK)
        м = importlib.util.module_from_spec(спец)
        спец.loader.exec_module(м)
        return м
    finally:
        for ключ, значение in прежнее.items():
            if значение is None:
                os.environ.pop(ключ, None)
            else:
                os.environ[ключ] = значение


def стенограмма(каталог: str, чтения: list, мусор: bool = False,
                имя: str = "лента.jsonl", граница_после: int | None = None,
                мнимая_граница: bool = False) -> str:
    """Файл стенограммы: строки с расходом, а между ними — обычная жизнь.

    `граница_после` — вставить настоящую границу сжатия после N-го ответа.
    `мнимая_граница` — вставить строку, где слова-приметы лежат ОБЫЧНЫМ
    ТЕКСТОМ: так они попадают в стенограмму вместе с исходниками скриптов, и
    поиск по подстроке принимал их за границу.
    """
    путь = Path(каталог) / имя
    строки = [json.dumps({"type": "user", "message": {"content": "привет"}})]
    if мнимая_граница:
        строки.append(json.dumps({
            "type": "user", "toolUseResult": {"type": "create"},
            "message": {"content": "тут в тексте есть compact_boundary "
                                   "и isCompactSummary, но это не граница"}},
            ensure_ascii=False))
    for n, ч in enumerate(чтения):
        if граница_после is not None and n == граница_после:
            строки.append(json.dumps({"type": "system",
                                      "subtype": "compact_boundary"}))
            строки.append(json.dumps({"type": "user", "isCompactSummary": True,
                                      "message": {"content": "сводка"}},
                                     ensure_ascii=False))
        # Каждый ответ модели ложится в стенограмму ДВУМЯ записями с одним и
        # тем же `requestId` — так это и выглядит в жизни. Счёт обязан
        # засчитать его один раз.
        for блок in range(2):
            строки.append(json.dumps({
                "type": "assistant", "isSidechain": n % 2 == 1,
                "uuid": f"u{n}-{блок}", "requestId": f"req{n}",
                "message": {"id": f"msg{n}",
                            "usage": {"input_tokens": 10,
                                      "cache_read_input_tokens": ч}}}))
    if мусор:
        строки.append('{"это не json — cache_read_input_tokens')
    путь.write_text("\n".join(строки) + "\n", encoding="utf-8")
    return str(путь)


def run(полезное: dict, tmp: str, режим: str | None = None,
        сырьё: str | None = None, сокет: str | None = None,
        окружение: dict | None = None):
    env = dict(os.environ, TMPDIR=tmp, **(окружение or {}))
    if режим is None:
        env.pop("NUDGE_COMPACT", None)
    else:
        env["NUDGE_COMPACT"] = режим
    env.pop("CLAUDE_PID", None)
    if сокет:
        env["CLAUDE_CODE_MESSAGING_SOCKET"] = сокет
    else:
        env["CLAUDE_CODE_MESSAGING_SOCKET"] = str(Path(tmp) / "сокета-нет.sock")
    вход = сырьё if сырьё is not None else json.dumps(полезное, ensure_ascii=False)
    р = subprocess.run([sys.executable, HOOK], input=вход,
                       capture_output=True, text=True, env=env)
    решение = None
    if р.stdout.strip():
        try:
            решение = json.loads(р.stdout)
        except ValueError:
            решение = {"битый вывод": р.stdout}
    return р.returncode, решение


def main() -> int:
    м = модуль()

    # ── лесенка: границы с обеих сторон ──────────────────────────────────────
    print("лесенка")
    # Числа берутся ИЗ МОДУЛЯ, а не вписаны сюда. Пороги настраиваются
    # переменными окружения (TRAH_COMPACT_FIRST_M, TRAH_COMPACT_STEP_M), и
    # проверка с зашитыми 15/30/10 падала бы у каждого, кто их поменял, — то
    # есть ровно у того, ради кого настройку и заводили.
    П, Ш = м.ПЕРВАЯ, м.ШАГ
    # Значение «заведомо за первой ступенью». Раньше здесь стояло 20 млн —
    # число, верное ровно до дня, когда умолчание порога сдвинули с 15 на 30.
    ПОРОГ = м.ПЕРВАЯ + М
    for всего_, ждём in [
        (0, None), (П - 1, None),
        (П, П), (П + 1, П), (П + Ш - 1, П),
        (П + Ш, П + Ш), (П + 2 * Ш - 1, П + Ш),
        (П + 2 * Ш, П + 2 * Ш),
        (П + 10 * Ш, П + 10 * Ш), (П + 10 * Ш + 1, П + 10 * Ш),
    ]:
        check(f"{всего_} → {ждём}", м.ступень(всего_) == ждём, str(м.ступень(всего_)))

    # Умолчание — вещь договорная, и договор записан здесь: владелец выбрал
    # 30 млн и шаг 30 млн 08.09.2026, потому что на прежних 15/30/10
    # напоминание приходило чаще, чем удавалось закрыть шаг.
    check("умолчание первой ступени — 30 млн", м.ПЕРВАЯ == 30 * М, str(м.ПЕРВАЯ))
    check("умолчание шага — 30 млн", м.ШАГ == 30 * М, str(м.ШАГ))
    check("вторая ступень идёт ровно через шаг", м.ВТОРАЯ == м.ПЕРВАЯ + м.ШАГ)

    # Переменные окружения действительно меняют пороги, а мусор в них — нет.
    for окружение, ждём_первую, ждём_шаг in [
        ({"TRAH_COMPACT_FIRST_M": "12", "TRAH_COMPACT_STEP_M": "7"}, 12 * М, 7 * М),
        ({"TRAH_COMPACT_FIRST_M": "не число"}, 30 * М, 30 * М),
        ({"TRAH_COMPACT_FIRST_M": "0"}, 30 * М, 30 * М),
        ({"TRAH_COMPACT_STEP_M": "-5"}, 30 * М, 30 * М),
    ]:
        свой = модуль(окружение)
        check(f"порог из окружения {окружение}",
              свой.ПЕРВАЯ == ждём_первую and свой.ШАГ == ждём_шаг,
              f"первая={свой.ПЕРВАЯ}, шаг={свой.ШАГ}")

    # ── счёт по стенограмме ──────────────────────────────────────────────────
    print("счёт чтения из кеша")
    with tempfile.TemporaryDirectory() as tmp:
        файл = стенограмма(tmp, [1000, 2000, 3000])
        check("расход одного запроса считается ОДИН раз, а не по записям",
              м.прочитано_из_кеша(файл) == 6000, str(м.прочитано_из_кеша(файл)))

        # Без ключа запроса считать нечем — тогда по записям, лишь бы не ноль.
        безключа = Path(tmp) / "безключа.jsonl"
        безключа.write_text("\n".join(json.dumps({
            "type": "assistant",
            "message": {"usage": {"cache_read_input_tokens": 700}}})
            for _ in range(3)) + "\n", encoding="utf-8")
        check("без requestId и message.id считается по записям",
              м.прочитано_из_кеша(str(безключа)) == 2100,
              str(м.прочитано_из_кеша(str(безключа))))

        # Только `message.id` — так лежат четыре записи из живой стенограммы.
        толькоид = Path(tmp) / "толькоид.jsonl"
        толькоид.write_text("\n".join(json.dumps({
            "type": "assistant",
            "message": {"id": "m1", "usage": {"cache_read_input_tokens": 900}}})
            for _ in range(3)) + "\n", encoding="utf-8")
        check("при отсутствии requestId работает message.id",
              м.прочитано_из_кеша(str(толькоид)) == 900,
              str(м.прочитано_из_кеша(str(толькоид))))

        # ── граница сжатия обнуляет счёт ─────────────────────────────────────
        сгранью = стенограмма(tmp, [1000, 2000, 3000, 4000],
                              имя="сгранью.jsonl", граница_после=2)
        check("считается только то, что ПОСЛЕ последней границы",
              м.прочитано_из_кеша(сгранью) == 7000,
              str(м.прочитано_из_кеша(сгранью)))

        двеграни = стенограмма(tmp, [9000], имя="двеграни.jsonl", граница_после=0)
        check("граница перед единственным ответом ничего не съедает",
              м.прочитано_из_кеша(двеграни) == 9000,
              str(м.прочитано_из_кеша(двеграни)))

        мнимая = стенограмма(tmp, [1000, 2000], имя="мнимая.jsonl",
                             мнимая_граница=True)
        check("слова-приметы в ТЕКСТЕ границей не считаются",
              м.прочитано_из_кеша(мнимая) == 3000,
              str(м.прочитано_из_кеша(мнимая)))

        битый = стенограмма(tmp, [5000], мусор=True, имя="битая.jsonl")
        check("битая строка не роняет счёт",
              м.прочитано_из_кеша(битый) == 5000, str(м.прочитано_из_кеша(битый)))

        check("нет файла — ноль, а не падение",
              м.прочитано_из_кеша(str(Path(tmp) / "нет-такого.jsonl")) == 0)

        пусто = Path(tmp) / "пусто.jsonl"
        пусто.write_text("", encoding="utf-8")
        check("пустая стенограмма — ноль", м.прочитано_из_кеша(str(пусто)) == 0)

    # ── добавочный счёт ──────────────────────────────────────────────────────
    print("добавочный счёт")
    with tempfile.TemporaryDirectory() as tmp:
        файл = стенограмма(tmp, [1000, 2000], имя="растущая.jsonl")
        сост = м.досчитать(файл, {})
        check("первый проход считает всё", сост["всего"] == 3000, str(сост))
        смещение = сост["смещение"]

        сост2 = м.досчитать(файл, сост)
        check("повторный проход по неизменному файлу ничего не добавляет",
              сост2["всего"] == 3000 and сост2["смещение"] == смещение, str(сост2))

        with open(файл, "a", encoding="utf-8") as ф:
            ф.write(json.dumps({
                "type": "assistant", "requestId": "req-новый",
                "message": {"id": "msg-новый",
                            "usage": {"cache_read_input_tokens": 4000}}}) + "\n")
        сост3 = м.досчитать(файл, сост2)
        check("дописанное дочитывается", сост3["всего"] == 7000, str(сост3))
        check("и смещение выросло", сост3["смещение"] > смещение, str(сост3))

        # Недописанная строка не считается и не двигает смещение: стенограмму
        # пишут прямо в этот момент.
        with open(файл, "a", encoding="utf-8") as ф:
            ф.write('{"type":"assistant","requestId":"req-обрыв","message":'
                    '{"usage":{"cache_read_input_tokens":9999}}}')
        сост4 = м.досчитать(файл, сост3)
        check("оборванная строка не засчитана", сост4["всего"] == 7000, str(сост4))
        check("и смещение не сдвинуто",
              сост4["смещение"] == сост3["смещение"], str(сост4))

        другой = стенограмма(tmp, [5000], имя="другая.jsonl")
        сост5 = м.досчитать(другой, сост4)
        check("другой файл считается с начала", сост5["всего"] == 5000, str(сост5))

        Path(файл).write_text("", encoding="utf-8")
        сост6 = м.досчитать(файл, сост3)
        check("урезанный файл считается с начала",
              сост6["всего"] == 0 and сост6["смещение"] == 0, str(сост6))

    # ── доставка кадром ──────────────────────────────────────────────────────
    print("доставка")
    with tempfile.TemporaryDirectory() as tmp:
        ухо = Ухо(str(Path(tmp) / "сессия.sock"))
        try:
            много = стенограмма(tmp, [ПОРОГ // 2, ПОРОГ // 2 + М])
            код, решение = run({"session_id": "д1", "transcript_path": много},
                               tmp, сокет=ухо.адрес)
            time.sleep(0.6)
            check("при живом сокете отказа НЕТ", решение is None, str(решение))
            check("кадр ушёл ровно один", len(ухо.строки) == 1, str(len(ухо.строки)))
            кадр = json.loads(ухо.строки[0]) if ухо.строки else {}
            check("кадр — user-сообщение", кадр.get("type") == "user", str(кадр))
            текст = кадр.get("message", {}).get("content", "")
            # Два расхода по половине порога плюс миллион: столько и должно
            # быть названо. Число берётся из тех же слагаемых, что и лента, —
            # зашитое «16.0M» пережило бы смену порога и врало бы молча.
            check("в кадре названо число",
                  f"{(ПОРОГ // 2 + ПОРОГ // 2 + М) / М:.1f}M" in текст, текст[:120])
            check("в кадре названа ступень", f"rung {м.ПЕРВАЯ // М}M" in текст,
                  текст[:120])
            check("в кадре названа команда заказа",
                  "compact-order.py" in текст, текст[:200])
            check("в кадре сказано про доведение шага",
                  "logical close" in текст, текст[:300])
            check("в кадре сказано, что работа продолжится сама",
                  "carries on by itself" in текст, текст[-300:])
            check("и названо право не сжиматься сейчас",
                  "carry on" in текст, текст[-200:])
        finally:
            ухо.закрыть()

    # ── запасной путь: сокета нет ────────────────────────────────────────────
    print("запасной путь")
    with tempfile.TemporaryDirectory() as tmp:
        много = стенограмма(tmp, [ПОРОГ])
        код, решение = run({"session_id": "з1", "transcript_path": много}, tmp)
        check("без сокета — отказ вместо кадра",
              решение is not None and решение.get("decision") == "block", str(решение))
        check("и текст тот же", "compact-order.py" in (решение or {}).get("reason", ""))

        # На `PostToolBatch` решений не бывает: печатать туда отказ — значит
        # писать в никуда, а состояние при этом уже помечено сработавшим.
        много2 = стенограмма(tmp, [ПОРОГ], имя="пачка.jsonl")
        код, решение = run({"session_id": "з2", "transcript_path": много2,
                            "hook_event_name": "PostToolBatch"}, tmp)
        check("на PostToolBatch отказа не печатает",
              код == 0 and решение is None, str(решение))
        # Кадр не ушёл — ступень не засчитана: следующий `Stop` той же сессии
        # обязан сказать своё, а не молчать до следующей ступени.
        код, решение = run({"session_id": "з2", "transcript_path": много2}, tmp)
        check("недоставленная на PostToolBatch ступень повторяется на Stop",
              решение is not None and решение.get("decision") == "block", str(решение))

    # ── лесенка помнит ───────────────────────────────────────────────────────
    print("память лесенки")
    with tempfile.TemporaryDirectory() as tmp:
        мало = стенограмма(tmp, [м.ПЕРВАЯ // 2], имя="мало.jsonl")
        код, решение = run({"session_id": "п1", "transcript_path": мало}, tmp)
        check("до первой ступени молчит", код == 0 and решение is None, str(решение))

        много = стенограмма(tmp, [м.ПЕРВАЯ + М], имя="много.jsonl")
        код, решение = run({"session_id": "п1", "transcript_path": много}, tmp)
        check(f"за первой ступенью ({(м.ПЕРВАЯ + М) // М} млн) срабатывает",
              решение is not None, str(решение))

        код, решение = run({"session_id": "п1", "transcript_path": много}, tmp)
        check("ту же ступень второй раз не повторяет", решение is None, str(решение))

        ещё = стенограмма(tmp, [м.ПЕРВАЯ + М, м.ШАГ], имя="ещё.jsonl")
        код, решение = run({"session_id": "п1", "transcript_path": ещё}, tmp)
        check("следующая ступень срабатывает", решение is not None, str(решение))
        текст2 = (решение or {}).get("reason", "")
        check("названа вторая ступень", f"rung {м.ВТОРАЯ // М}M" in текст2, текст2[:120])
        check("вторая ступень говорит СТРОГО",
              "no longer a suggestion" in текст2, текст2[:200])
        check("и требует сжатия в этом же ходе",
              "in THIS turn" in текст2, текст2[:300])
        check("и требует назвать отказ вслух",
              "say plainly in your reply that you refused" in текст2, текст2[-300:])
        check("на второй ступени мягкой оговорки уже НЕТ",
              "the reminder returns at the next rung" not in текст2, текст2[-200:])

        код, решение = run({"session_id": "п2", "transcript_path": много}, tmp)
        check("у другой сессии счёт свой", решение is not None, str(решение))

        # ── сжатие обнуляет и счёт, и лесенку ────────────────────────────────
        # Без сброса запомненная ступень оставалась бы навсегда недостижимой, и
        # одно сжатие затыкало напоминания до конца сессии.
        после = стенограмма(tmp, [м.ПЕРВАЯ + М, м.ШАГ, м.ПЕРВАЯ + М],
                            имя="после.jsonl", граница_после=2)
        код, решение = run({"session_id": "п1", "transcript_path": после}, tmp)
        check("после сжатия лесенка начинается заново", решение is not None,
              str(решение))
        check("и это снова первая ступень",
              f"rung {м.ПЕРВАЯ // М}M" in (решение or {}).get("reason", ""),
              (решение or {}).get("reason", "")[:120])

    # ── цель `/goal` ─────────────────────────────────────────────────────────
    print("цель")

    def с_целью(путь: str, отказов: int = 0,
                условие: str = "весь набор зелен") -> str:
        """Дописать в стенограмму постановку цели и N отказов оценщика."""
        def вложение(n, **поля):
            return json.dumps({"type": "attachment", "uuid": f"g{n}",
                               "attachment": {"type": "goal_status",
                                              "condition": условие, **поля}},
                              ensure_ascii=False) + "\n"
        with open(путь, "a", encoding="utf-8") as ф:
            ф.write(вложение(0, met=False, sentinel=True))
            for i in range(отказов):
                ф.write(вложение(i + 1, met=False, reason="тесты не запускали"))
        return путь

    with tempfile.TemporaryDirectory() as tmp:
        # Напоминание о сжатии при активной цели обязано сказать, что цель
        # сжатие переживает. Иначе цель читается как повод отложить — а она
        # существует ровно для того, чтобы конец шага не наступал, и без этой
        # приписки сессия не сможет ни закончить, ни сжаться.
        много = с_целью(стенограмма(tmp, [ПОРОГ], имя="сцелью.jsonl"))
        код, решение = run({"session_id": "ц1", "transcript_path": много}, tmp)
        текст = (решение or {}).get("reason", "")
        check("при активной цели сказано, что цель переживёт сжатие",
              "SURVIVES compaction" in текст, текст[-300:])
        check("и что цель не повод отложить",
              "NOT a reason to postpone" in текст, текст[-300:])

        без = стенограмма(tmp, [ПОРОГ], имя="безцели.jsonl")
        код, решение = run({"session_id": "ц2", "transcript_path": без}, tmp)
        check("без цели этой приписки нет",
              "SURVIVES compaction" not in (решение or {}).get("reason", ""))

    # ── застрявшая цель ──────────────────────────────────────────────────────
    # Предела итераций у `/goal` нет вовсе, а каждая попытка остановиться стоит
    # вызова модели по всей стенограмме. Застревание молча — это счёт, который
    # растёт сам по себе, без всякой связи с размером контекста, поэтому и
    # разбирается оно отдельно от лесенки сжатия.
    print("застрявшая цель")
    with tempfile.TemporaryDirectory() as tmp:
        ухо = Ухо(str(Path(tmp) / "сессия.sock"))
        try:
            мало = с_целью(стенограмма(tmp, [1 * М], имя="застряла.jsonl"),
                           отказов=10)
            run({"session_id": "з1", "transcript_path": мало}, tmp,
                сокет=ухо.адрес)
            time.sleep(0.6)
            весь = " ".join(ухо.строки)
            check("десять отказов — сессии сказали",
                  "judged NOT MET 10" in весь, весь[:200])
            check("и названо условие", "весь набор зелен" in весь, весь[:200])
            check("и запрещено снимать цель самому",
                  "owner's call" in весь, весь[-250:])

            # Тот же десяток второй раз — молчим: иначе один и тот же текст
            # приходил бы на каждой попытке остановиться.
            ухо.строки.clear()
            run({"session_id": "з1", "transcript_path": мало}, tmp,
                сокет=ухо.адрес)
            time.sleep(0.6)
            check("тот же десяток второй раз не повторяется",
                  not ухо.строки, str(ухо.строки))

            девять = с_целью(стенограмма(tmp, [1 * М], имя="девять.jsonl"),
                             отказов=9)
            ухо.строки.clear()
            run({"session_id": "з2", "transcript_path": девять}, tmp,
                сокет=ухо.адрес)
            time.sleep(0.6)
            check("девять отказов — ещё молчим", not ухо.строки, str(ухо.строки))
        finally:
            ухо.закрыть()

    # ── молчание ─────────────────────────────────────────────────────────────
    print("молчание")
    with tempfile.TemporaryDirectory() as tmp:
        много = стенограмма(tmp, [ПОРОГ])
        код, решение = run({"session_id": "м1", "transcript_path": много,
                            "stop_hook_active": True}, tmp)
        check("при stop_hook_active молчит — иначе петля",
              решение is None, str(решение))

        код, решение = run({"session_id": "м2", "transcript_path": много}, tmp,
                           режим="off")
        check("выключатель работает", решение is None, str(решение))

        код, решение = run({"session_id": "м3"}, tmp)
        check("без пути к стенограмме молчит", код == 0 and решение is None)

        код, решение = run({}, tmp, сырьё="это не json")
        check("битый вход не роняет хук", код == 0 and решение is None)

        код, решение = run({"session_id": "м4", "transcript_path": "/нет/такого"}, tmp)
        check("недоступная стенограмма — молчание", решение is None, str(решение))

    # ── кран строки состояния ────────────────────────────────────────────────
    #
    # С 2.1.251 числа кеша приезжают во вход строки состояния, и копит их
    # `statusline/cache-tap.py`. Стенограмма осталась запасным путём, и оба
    # пути проверяются: подменять источник молча — то же, что считать неверно.
    print("кран строки состояния")

    def кран(tmp, сессия, чтения, снято=None, обнулено=None) -> None:
        д = {"всего_чтения": чтения, "запросов": 100,
             "снято": time.time() if снято is None else снято}
        if обнулено is not None:
            д["обнулено"] = обнулено
        каталог = Path(tmp) / "cache-tap"
        каталог.mkdir(parents=True, exist_ok=True)
        (каталог / f"{сессия}.json").write_text(
            json.dumps(д, ensure_ascii=False), encoding="utf-8")

    with tempfile.TemporaryDirectory() as tmp:
        мало = стенограмма(tmp, [1 * М])

        кран(tmp, "к1", ПОРОГ)
        код, решение = run({"session_id": "к1", "transcript_path": мало}, tmp)
        check("кран берётся вместо стенограммы", решение is not None,
              "стенограмма одна дала бы 1 млн и молчание")

        # Протухший кран — это не неверное число, а СТАРОЕ: напоминание пришло
        # бы с опозданием на всё время, что строка состояния не рисовалась.
        кран(tmp, "к2", ПОРОГ, снято=time.time() - 10_000)
        код, решение = run({"session_id": "к2", "transcript_path": мало}, tmp)
        check("протухшему крану не верим", решение is None, str(решение))

        кран(tmp, "к3", ПОРОГ)
        код, решение = run({"session_id": "к3", "transcript_path": мало}, tmp,
                           окружение={"NUDGE_COMPACT_SOURCE": "transcript"})
        check("кран отключается переменной", решение is None, str(решение))

        (Path(tmp) / "cache-tap" / "к4.json").parent.mkdir(exist_ok=True)
        (Path(tmp) / "cache-tap" / "к4.json").write_text("не json", encoding="utf-8")
        много = стенограмма(tmp, [ПОРОГ])
        код, решение = run({"session_id": "к4", "transcript_path": много}, tmp)
        check("битый кран роняет нас на стенограмму, а не в тишину",
              решение is not None, str(решение))

    # Сдвиг проверяем прямо на функции: через подпроцесс не видно, пересчитан
    # он или взят из состояния, а вся суть именно в этом.
    print("сдвиг под краном")
    import importlib.util
    спец = importlib.util.spec_from_file_location("nudge_compact", HOOK)
    нк = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(нк)

    with tempfile.TemporaryDirectory() as tmp:
        путь = стенограмма(tmp, [7 * М])
        сост: dict = {}
        всего1 = нк.со_сдвигом({"всего_чтения": 2 * М}, сост, путь)
        check("сдвиг снимается со стенограммы", всего1 == 9 * М, str(всего1))
        check("сдвиг запомнен", сост["сдвиг"] == 7 * М, str(сост.get("сдвиг")))

        # Второй заход не должен снова читать стенограмму: подсовываем путь в
        # никуда — если бы читал, сдвиг обнулился бы.
        всего2 = нк.со_сдвигом({"всего_чтения": 3 * М}, сост, "/нет/такого")
        check("сдвиг не пересчитывается каждый раз", всего2 == 10 * М, str(всего2))

        # Сжатие обнулило кран — сдвиг обязан сняться заново, иначе он завышал
        # бы счёт до конца сессии и следующая ступень пришла бы сразу.
        всего3 = нк.со_сдвигом({"всего_чтения": 0, "обнулено": 111.0}, сост, путь)
        check("после обнуления крана сдвиг снимается заново",
              всего3 == 7 * М and сост["видел_обнуление"] == 111.0, str(всего3))
        всего4 = нк.со_сдвигом({"всего_чтения": 1 * М, "обнулено": 111.0},
                               сост, "/нет/такого")
        check("то же обнуление второй раз сдвиг не трогает", всего4 == 8 * М,
              str(всего4))

    print(f"\nвсего: {всего}, провалов: {провалов}")
    return 1 if провалов else 0


