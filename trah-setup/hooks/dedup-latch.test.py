#!/usr/bin/env python3
"""Тесты защёлки дублей.

Ядро подменено скриптом-заглушкой (`DEDUP_TOOL`): тесту нужны не uv и не
Haiku, а то, как хук ведёт себя на каждое состояние настройки и на каждый
ответ ядра. Главное:

1. Не настроено — ничего не сканируется, просьба настроить ОДИН раз за сессию.
2. Выключено и не-код — полное молчание.
3. Включено — проверка на каждой `every`-й правке, модели только DUP.
4. Сломанное ядро не выглядит как «дублей нет» — и говорится об этом один раз.
"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ЗДЕСЬ = Path(__file__).resolve().parent
ХУК = ЗДЕСЬ / "dedup-latch.py"
ЯДРО = ЗДЕСЬ.parent / "dedup"

всего = 0
провалов = 0


def check(имя: str, условие: bool, подробность: str = "") -> None:
    global всего, провалов
    всего += 1
    if not условие:
        провалов += 1
        print(f"  ✗ {имя} {подробность}")


дом = Path(tempfile.mkdtemp(prefix="dedup-latch-test-"))
проект = дом / "proj"
(проект / ".git").mkdir(parents=True)
(проект / "src").mkdir()
код = проект / "src" / "a.rs"
код.write_text("fn a() {}\n")
код2 = проект / "src" / "b.rs"
код2.write_text("fn b() {}\n")
текст = проект / "README.md"
текст.write_text("x\n")
заглушка = дом / "fake-tool.py"
ответ = дом / "answer.json"


def ядро_отвечает(найдено: list, код_выхода: int = 0) -> None:
    ответ.write_text(json.dumps({"found": найдено, "code": код_выхода}))


заглушка.write_text(
    "#!/usr/bin/env python3\n"
    "import json, sys\n"
    f"a = json.load(open({str(ответ)!r}))\n"
    "print(json.dumps(a['found']))\n"
    "sys.exit(a['code'])\n")
заглушка.chmod(0o755)


def запустить(путь: Path, сессия: str = "s1") -> tuple[int, str]:
    п = {"hook_event_name": "PostToolUse", "tool_name": "Edit", "session_id": сессия,
         "cwd": str(проект), "tool_input": {"file_path": str(путь)}}
    г = subprocess.run([sys.executable, str(ХУК)], input=json.dumps(п), text=True, capture_output=True,
                       env={**os.environ, "HOME": str(дом), "DEDUP_HOME": str(ЯДРО),
                            "DEDUP_TOOL": str(заглушка)})
    return г.returncode, г.stderr


def настройка(**поля) -> None:
    (проект / ".claude").mkdir(exist_ok=True)
    (проект / ".claude" / "dedup.json").write_text(json.dumps(поля))


def дубль(второй: str = "src/other.rs") -> dict:
    return {"id": "x", "mine": "src/a.rs:1 a", "other": f"{второй}:1 c",
            "units": [{"file": "src/a.rs"}, {"file": второй}],
            "judge": {"label": "DUP", "why": "одно и то же", "keep": "2"}}


print("dedup-latch.py")

# --- не настроено -------------------------------------------------------------
код_, err = запустить(код)
check("нет настройки: просьба настроить", код_ == 2 and "не настроена" in err and str(проект) in err, err)
код_, err = запустить(код2)
check("нет настройки: второй раз за сессию молчит", код_ == 0 and err == "", err)
код_, err = запустить(код, сессия="s2")
check("нет настройки: в новой сессии просит снова", код_ == 2, err)
код_, err = запустить(текст, сессия="s3")
check("не код: молчит даже без настройки", код_ == 0 and err == "", err)
настройка(state="setup")
код_, err = запустить(код, сессия="s4")
check("state setup — то же, что нет настройки", код_ == 2 and "не настроена" in err, err)

# --- выключено ----------------------------------------------------------------
настройка(state="off")
ядро_отвечает([дубль()])
for _ in range(6):
    код_, err = запустить(код, сессия="s5")
    check("off: молчит на любой правке", код_ == 0 and err == "", err)

# --- включено -----------------------------------------------------------------
настройка(state="on", every=2)
ядро_отвечает([дубль()])
код_, err = запустить(код, сессия="s6")
check("on: первая правка не проверяется", код_ == 0 and err == "", err)
код_, err = запустить(код2, сессия="s6")
check("on: вторая (every=2) проверяется и показывает DUP",
      код_ == 2 and "ЗАЩЁЛКА ДУБЛЕЙ" in err and "src/other.rs" in err, err)
check("on: вне пачки нет пометки о переносе", "перенос" not in err, err)

ядро_отвечает([{**дубль(), "judge": {"label": "IDIOM", "why": "", "keep": ""}}])
запустить(код, сессия="s7")
код_, err = запустить(код2, сессия="s7")
check("on: не-DUP модели не показывается", код_ == 0 and err == "", err)

ядро_отвечает([дубль("src/b.rs")])
запустить(код, сессия="s8")
код_, err = запустить(код2, сессия="s8")
check("on: второй член правлен в пачке — пометка о переносе", код_ == 2 and "перенос" in err, err)

# --- сломано ------------------------------------------------------------------
ядро_отвечает([], 3)
запустить(код, сессия="s9")
код_, err = запустить(код2, сессия="s9")
check("код 3 ядра: сказано, что защёлка сломана", код_ == 2 and "СЛОМАНА" in err, err)
запустить(код, сессия="s9")
код_, err = запустить(код2, сессия="s9")
check("сломано: второй раз за сессию молчит", код_ == 0 and err == "", err)
ошибка = list((дом / ".cache" / "dedup" / "roots").glob("proj-*/last-error.json"))
check("сломано: причина записана на диск", len(ошибка) == 1)

ядро_отвечает([], 1)
запустить(код, сессия="s10")
код_, err = запустить(код2, сессия="s10")
check("падение ядра — тоже «сломана»", код_ == 2 and "СЛОМАНА" in err, err)

# --- поиск настройки вверх ----------------------------------------------------
вложенный = проект / "src" / "deep"
вложенный.mkdir()
глубокий = вложенный / "c.rs"
глубокий.write_text("fn c() {}\n")
настройка(state="off")
код_, err = запустить(глубокий, сессия="s11")
check("настройка находится вверх от файла", код_ == 0 and err == "", err)

# --- без сети модулей ---------------------------------------------------------
код_, err = subprocess.run([sys.executable, str(ХУК)], input="не json", text=True, capture_output=True,
                           env={**os.environ, "HOME": str(дом), "DEDUP_HOME": str(ЯДРО)}).returncode, ""
check("мусор на входе — молчание", код_ == 0)

print(f"  проверок {всего}, провалов {провалов}")
sys.exit(1 if провалов else 0)
