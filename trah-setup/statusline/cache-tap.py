#!/usr/bin/env python3
"""Кран на строку состояния: копить чтение из кеша и передать вход дальше.

ЗАЧЕМ
=====

С 2.1.251 во вход строки состояния приезжает `prompt_cache` — накопительный
счёт запросов, доля попаданий, тёплый ли кеш, — и `context_window` с расходом
ПОСЛЕДНЕГО запроса. Тех же чисел `nudge-compact.py` до сих пор добивался
разбором стенограммы: 36 МБ, добавочный проход со смещением, привязанным к пути
файла, и две починки счёта позади (считать по запросам, а не по записям;
считать с последнего сжатия, а не за всю жизнь).

Строка состояния зовётся сама, раз в несколько секунд. Значит копить должен
кран, а не хук: хук просыпается на пачке вызовов и пропустил бы всё между ними.

КАК СЧИТАЕТСЯ
=============

Замер 29.08.2026, 75 секунд живой сессии: `prompt_cache.requests` растёт по
единице на запрос и НЕ обнуляется, `cache_read_input_tokens` равен размеру
контекста на последнем запросе и меняется медленно. Отсюда:

    всего += (запросов_сейчас - запросов_прежде) * чтение_сейчас

При обновлении раз в три секунды разница почти всегда единица, и приближение
тугое. Если строка состояния не рисовалась (окно не в фокусе, сессия в фоне),
разница накопится — и умножится на чтение, которое за это время едва сдвинулось.

ПОЧЕМУ ПЕРЕДАЧЕЙ, А НЕ ЗАМЕНОЙ. Строка состояния — вещь владельца. Кран садится
ПЕРЕД настоящим сборщиком, отдаёт ему те же байты и печатает его вывод. Любая
беда крана гасится молча: он пишет в stdout, а stdout здесь — сама строка, и
сообщение об ошибке стёрло бы её.

ФАЙЛ НА СЕССИЮ, А НЕ ОБЩИЙ. Первая редакция клала весь вход в один
`last-input.json` — и соседняя сессия затирала его через секунду. Поймано на
первом же замере: половина строк пришла с пустым расходом. Ключ — `session_id`.

    <TMPDIR>/cache-tap/<session_id>.json

Выключатель: `CACHE_TAP=off` — чистая передача.
Кого звать дальше: `CACHE_TAP_NEXT`, по умолчанию `claude-hud.sh` рядом.
Обнуление после сжатия: `cache-tap.py --reset` на `PostCompact`.
"""
import json
import os
import subprocess
import sys
import time
from pathlib import Path

СОСТОЯНИЕ = Path(os.environ.get("TMPDIR", "/tmp")) / "cache-tap"
ДАЛЬШЕ = os.environ.get(
    "CACHE_TAP_NEXT", str(Path(__file__).resolve().parent / "claude-hud.sh"))


def файл(session_id: str) -> Path:
    return СОСТОЯНИЕ / f"{session_id or 'unknown'}.json"


def прочитать(путь: Path) -> dict:
    try:
        return json.loads(путь.read_text(encoding="utf-8"))
    except Exception:
        return {}


def записать(путь: Path, данные: dict) -> None:
    """Атомарно: файл читают хуки, пока мы пишем."""
    путь.parent.mkdir(parents=True, exist_ok=True)
    временный = путь.with_suffix(f".tmp{os.getpid()}")
    временный.write_text(json.dumps(данные, ensure_ascii=False), encoding="utf-8")
    временный.replace(путь)


def досчитать(вход: dict, прежнее: dict) -> dict:
    """Новое состояние сессии из входа строки состояния и прошлого состояния."""
    кеш = вход.get("prompt_cache") or {}
    окно = вход.get("context_window") or {}
    расход = окно.get("current_usage") or {}
    запросов = кеш.get("requests")
    чтение = расход.get("cache_read_input_tokens")

    всего = int(прежнее.get("всего_чтения") or 0)
    прежних = прежнее.get("запросов")
    if isinstance(запросов, int) and isinstance(чтение, int):
        if not isinstance(прежних, int) or запросов < прежних:
            # Счётчик пошёл назад — сессия перезапустилась. Считаем с нуля, а
            # не задним числом: прошлую жизнь мы всё равно не восстановим, а
            # отрицательная разница испортила бы счёт молча.
            прирост = 0
        else:
            прирост = (запросов - прежних) * чтение
        всего += прирост

    return {
        "всего_чтения": всего,
        "запросов": запросов if isinstance(запросов, int) else прежних,
        "чтение_последнего": чтение,
        "доля_попаданий": кеш.get("hit_ratio"),
        "тёплый": кеш.get("warm"),
        "ttl": кеш.get("ttl"),
        "промахов": кеш.get("misses"),
        "окно_процентов": окно.get("used_percentage"),
        "предел_недели": ((вход.get("rate_limits") or {}).get("seven_day") or {})
            .get("used_percentage"),
        "предел_пяти_часов": ((вход.get("rate_limits") or {}).get("five_hour") or {})
            .get("used_percentage"),
        "стоимость": (вход.get("cost") or {}).get("total_cost_usd"),
        "модель": (вход.get("model") or {}).get("id"),
        "стенограмма": вход.get("transcript_path"),
        "версия": вход.get("version"),
        "снято": time.time(),
        # Счёт обнулён вот когда: строка нужна, чтобы отличить «сжатия не было»
        # от «сжатие было, но счёт почему-то большой».
        "обнулено": прежнее.get("обнулено"),
    }


def сброс() -> int:
    """`PostCompact`: сжатие обнулило контекст, значит и накопленный счёт.

    Без этого лесенка напоминаний не сбрасывалась бы никогда: `requests` сжатие
    не трогает, счёт продолжал бы расти, и следующая ступень пришла бы сразу.
    """
    try:
        полезное = json.loads(sys.stdin.read() or "{}")
    except Exception:
        полезное = {}
    путь = файл(str(полезное.get("session_id") or ""))
    состояние = прочитать(путь)
    if not состояние:
        return 0
    состояние["всего_чтения"] = 0
    состояние["обнулено"] = time.time()
    записать(путь, состояние)
    return 0


def main() -> int:
    if "--reset" in sys.argv:
        return сброс()

    сырьё = sys.stdin.buffer.read()

    if os.environ.get("CACHE_TAP") != "off":
        try:
            вход = json.loads(сырьё.decode("utf-8", "replace"))
            if isinstance(вход, dict):
                путь = файл(str(вход.get("session_id") or ""))
                записать(путь, досчитать(вход, прочитать(путь)))
        except Exception:
            pass

    if not Path(ДАЛЬШЕ).exists():
        return 0
    р = subprocess.run([ДАЛЬШЕ] if os.access(ДАЛЬШЕ, os.X_OK)
                       else ["bash", ДАЛЬШЕ], input=сырьё)
    return р.returncode


if __name__ == "__main__":
    sys.exit(main())
