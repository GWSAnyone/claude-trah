    р.add_argument("--home", default=str(Path.home()), help="куда ставить")
    а = р.parse_args()

    дом = Path(а.home)
    отчёт = Отчёт(а.dry_run, дом, а.replace_theirs)
    есть = проверить_окружение()

    if not есть["python3"]:
        print("python3 не найден — на нём держатся все хуки", file=sys.stderr)
