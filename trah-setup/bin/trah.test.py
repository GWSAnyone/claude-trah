#!/usr/bin/env python3
"""Проверки сборщика брифа из кусков.

Вычитание куска — единственное место, где ошибка стоит не поломки, а ТИШИНЫ:
правило исчезает из брифа, в бинарник не доехало, и никто этого не видит.
Поэтому оно проверяется синтетикой, а не ожиданием живого случая: на сегодня
ни у одного куска брифа `covered_by` не заполнен, и без этих проверок код
вычитания не исполнялся бы вовсе.

Побайтовое воспроизведение обоих настоящих брифов проверяется здесь же —
это сторож раскроя: потеряется кусок или разъедется разделитель, тест назовёт
файл.
"""
import importlib.util
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ЗДЕСЬ = Path(__file__).resolve().parent
КОРЕНЬ = ЗДЕСЬ.parent.parent

спец = importlib.util.spec_from_file_location("trah", ЗДЕСЬ / "trah.py")
trah = importlib.util.module_from_spec(спец)
спец.loader.exec_module(trah)
# Проверки брифа подменяют `пути` заглушкой; настоящую придерживаем здесь,
# иначе проверки прицела мерили бы заглушку и молча проходили бы всегда.
НАСТОЯЩИЕ_ПУТИ = trah.пути

провалов = 0


def проверить(что: str, условие: bool, подробность: str = "") -> None:
    global провалов
    if условие:
        print(f"  ✓ {что}")
    else:
        провалов += 1
        print(f"  ✗ {что}  {подробность}")


def кусок(каталог: Path, id_: str, порядок: int, тело: str,
          covered_by=None, вид="section") -> None:
    заголовок = {"id": id_, "route": "brief", "scope": "проба",
                 "kind": вид, "order": порядок, "covered_by": covered_by or []}
    (каталог / f"{id_}.md").write_text(
        "---\n" + json.dumps(заголовок, ensure_ascii=False) + "\n---\n" + тело + "\n",
        encoding="utf-8")


def манифест(каталог: Path, состояния: dict) -> None:
    (каталог / "м.json").write_text(json.dumps(
        {"собрано": "проба",
         "куски": {id_: {"маршрут": "either", "доставлен": с}
                   for id_, с in состояния.items()}},
        ensure_ascii=False), encoding="utf-8")


print("сборка брифа из кусков")
with tempfile.TemporaryDirectory() as tmp:
    tmp = Path(tmp)
    trah.КУСКИ = tmp
    кусок(tmp, "первый", 10, "## Первый\nтекст")
    кусок(tmp, "второй", 20, "## Второй\nтекст", covered_by=["патч-А"])
    кусок(tmp, "третий", 30, "## Третий\nтекст", covered_by=["патч-А", "патч-Б"])
    манифест(tmp, {"патч-А": "проверено", "патч-Б": "записан"})
    trah.пути = lambda в: (в, None, None, None, tmp / "м.json")

    полный = trah.собрать_бриф("проба", урезать=False)
    проверить("без урезания едут все куски",
              полный.count("##") == 3, полный)
    проверить("порядок — по полю order",
              полный.index("Первый") < полный.index("Второй") < полный.index("Третий"))

    урезанный = trah.собрать_бриф("проба", урезать=True)
    проверить("кусок с проверенным покрытием вычтен",
              "Второй" not in урезанный, урезанный)
    проверить("кусок с ЧАСТИЧНЫМ покрытием остаётся — промах патча не теряет правило",
              "Третий" in урезанный, урезанный)
    проверить("кусок без covered_by остаётся всегда",
              "Первый" in урезанный, урезанный)

    # Манифеста нет — значит ничего не доставлено, значит вычитать нечего.
    trah.пути = lambda в: (в, None, None, None, tmp / "манифеста-нет.json")
    без_манифеста = trah.собрать_бриф("проба", урезать=True)
    проверить("без манифеста бриф полный, а не пустой",
              без_манифеста == полный, без_манифеста)

    # Область без кусков — это опечатка в имени, и молчать о ней нельзя:
    # пустой бриф выглядит как удавшаяся сборка ровно до первого вопроса модели.
    try:
        trah.собрать_бриф("такой-области-нет", урезать=False)
        проверить("неизвестная область — отказ, а не пустой бриф", False)
    except SystemExit:
        проверить("неизвестная область — отказ, а не пустой бриф", True)

print("побайтовое воспроизведение настоящих брифов")
trah.КУСКИ = КОРЕНЬ / "trah-setup/fragments"
# Области берутся из кусков, а пути — резолвером: список в тесте был бы третьим
# местом, где записано одно и то же, и первым, которое отстанет.
#
# Область, которой некуда писать, ПРОПУСКАЕТСЯ, а не проваливает тест: бриф
# экосистемы принадлежит её репозиторию, и у того, кто склонировал только
# комплект, этого репозитория нет. Пропуск при этом печатается — молчаливый
# пропуск неотличим от пройденной проверки.
for область in trah.все_области():
    путь = trah.куда_бриф(область)
    if путь is None or not путь.exists():
        print(f"  · {область}: пропущена, файла нет ({путь})")
        continue
    собрано = trah.собрать_бриф(область, урезать=False)
    было = путь.read_text(encoding="utf-8")
    исходник = область
    if собрано == было:
        проверить(f"{исходник} воспроизведён побайтово", True)
    else:
        # Первое расхождение — по строкам: искать его глазами в 300 строках дорого.
        a, b = было.splitlines(), собрано.splitlines()
        n = next((i for i in range(max(len(a), len(b)))
                  if a[i:i + 1] != b[i:i + 1]), 0)
        проверить(f"{исходник} воспроизведён побайтово", False,
                  f"строка {n + 1}: было {a[n:n+1]}, стало {b[n:n+1]}")

print("\nприцел версии")
with tempfile.TemporaryDirectory() as tmp:
    было_пин = trah.ПИН
    trah.ПИН = Path(tmp) / "version.txt"
    trah.пути = НАСТОЯЩИЕ_ПУТИ
    try:
        trah.целевая_версия()
        проверить("без файла прицела — отказ, а не догадка", False, "не отбилось")
    except SystemExit as e:
        проверить("без файла прицела — отказ, а не догадка", "нет файла" in str(e))

    trah.ПИН.write_text("   \n", encoding="utf-8")
    try:
        trah.целевая_версия()
        проверить("пустой прицел — отказ", False, "не отбилось")
    except SystemExit as e:
        проверить("пустой прицел — отказ", "пуст" in str(e))

    trah.ПИН.write_text("9.9.9\n", encoding="utf-8")
    проверить("прицел читается с обрезкой пробелов",
              trah.целевая_версия() == "9.9.9")
    # Главное: без аргумента берётся ПРИЦЕЛ, а не самая свежая в versions/.
    # Прежняя редакция сканировала каталог, и обновление молча уводило сборку.
    проверить("пути() без версии идут от прицела",
              trah.пути(None)[0] == "9.9.9")
    проверить("названная версия сильнее прицела",
              trah.пути("1.2.3")[0] == "1.2.3")
    trah.ПИН = было_пин

print("\nскрипт правок: сверка и счёт промахов")
# Проверяем НАСТОЯЩИМ узлом: скрипт исполняет node внутри tweakcc, и ошибка в
# нём — это сорванная сборка, а не сорванный тест.
ЯДРО = shutil.which("node")


def прогнать(куски_, js_: str, сверка: bool) -> tuple[int, str]:
    тело = trah.собрать_скрипт(куски_, только_сверка=сверка)
    with tempfile.TemporaryDirectory() as tmp:
        ф = Path(tmp) / "п.js"
        ф.write_text(
            "const тело = " + json.dumps(тело, ensure_ascii=False) + ";\n"
            "const js = " + json.dumps(js_, ensure_ascii=False) + ";\n"
            "try { const r = new Function('js', тело)(js);"
            " console.log('OK'); console.log(r); }\n"
            "catch (e) { console.log('THROW'); console.log(e.message); }\n",
            encoding="utf-8")
        р = subprocess.run([ЯДРО, str(ф)], capture_output=True, text=True)
        строки = р.stdout.split("\n", 1)
        return (0 if строки[0] == "OK" else 1), (строки[1] if len(строки) > 1 else "")


def правка(id_: str, якорь: str, чем: str, счёт: int) -> dict:
    return {"id": id_, "route": "binary", "тело": "", "файл": f"{id_}.md",
            "edits": [{"op": "replace", "anchor": якорь, "with": чем, "count": счёт}]}


if not ЯДРО:
    проверить("node на машине есть", False, "без него скрипт правок не проверить")
else:
    двое = [правка("первый", "AAA", "ZZZ", 1), правка("второй", "BBB", "YYY", 1)]

    бросило, текст = прогнать(двое, "AAA и BBB", сверка=False)
    проверить("сошлись оба — правка применяется", бросило == 0 and "ZZZ и YYY" in текст,
              текст[:120])

    # Ради этого всё и затевалось: узнать про ВСЕ промахи за один прогон.
    # Прежняя редакция бросала на первом, и переезд на новую версию шёл
    # переборкой: починил один якорь — пересобрал — узнал про следующий.
    бросило, текст = прогнать(двое, "ничего похожего", сверка=False)
    проверить("не сошлись оба — названы оба", бросило == 1
              and "первый" in текст and "второй" in текст, текст[:200])
    проверить("сказано, сколько именно не сошлось", "якорей не сошлось: 2" in текст,
              текст[:120])

    смесь = [правка("живой", "AAA", "ZZZ", 1), правка("мёртвый", "BBB", "YYY", 1)]
    бросило, текст = прогнать(смесь, "AAA один раз", сверка=False)
    проверить("промах одного не прячет остальных", бросило == 1
              and "мёртвый" in текст and "живой" not in текст, текст[:200])

    # Сверка: не подставляет НИЧЕГО и отчитывается всегда, даже когда всё сошлось.
    бросило, текст = прогнать(двое, "AAA и BBB", сверка=True)
    проверить("сверка отчитывается через исключение", бросило == 1, текст[:120])
    метка = текст.find("ОТЧЁТ")
    отчёт = json.JSONDecoder().raw_decode(текст[метка + len("ОТЧЁТ"):]) [0] if метка >= 0 else []
    проверить("в отчёте оба якоря", len(отчёт) == 2, текст[:200])
    проверить("отчёт несёт ожидаемый и найденный счёт",
              отчёт and отчёт[0]["ждём"] == 1 and отчёт[0]["прямо"] == 1, str(отчёт))
    проверить("сверка не подставляет текст", "ZZZ" not in текст, текст[:200])

print("провалов:", провалов)
sys.exit(1 if провалов else 0)
