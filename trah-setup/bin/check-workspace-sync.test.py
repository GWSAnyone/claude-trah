#!/usr/bin/env python3
"""Проверка `check-workspace-sync.py` — на поддельном доме, host не трогается.

Сверка ходит по `~`, поэтому проверять её на живой машине нельзя: там свои
расхождения, и тест мерил бы состояние хозяйской машины, а не сам скрипт. Она
умеет `--home`, и каждый случай ниже собирает свежий дом во временном каталоге
и портит уже ЕГО.

Обе стороны проверяются: молчит, когда копии сходятся, и кричит — называя файл
и оба пути, — когда разошлись. Проверки только на «кричит» мало: сверка,
которая ругается всегда, ничем не лучше сверки, которая молчит всегда.
"""

import importlib.util
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

КОМПЛЕКТ = Path(__file__).resolve().parent.parent
СКРИПТ = str(КОМПЛЕКТ / "bin/check-workspace-sync.py")

# Файлы, вокруг которых всё и затевалось: расхождение в них жило незамеченным.
КОНТЕКСТ = ("serena/context-claude-code.yml", ".serena/contexts/claude-code.yml")
ПАМЯТЬ = ("serena/global-memory_maintenance.md",
          ".serena/memories/global/memory_maintenance.md")
# Этому расходиться положено — он в `install-kit.ПРАВИТЬ_РУКАМИ`.
РУКАМИ = ("output-styles/serena-first.md", ".claude/output-styles/serena-first.md")


def сверка():
    """Сам скрипт как модуль — чтобы взять его же список пар."""
    спец = importlib.util.spec_from_file_location("сверка", СКРИПТ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


def поддельный_дом(врем: str):
    """Дом, в который комплект разложен ПОЛНОСТЬЮ и побайтово.

    Раскладываем по тем же парам, которые сверка и проверяет: цель теста — не
    повторить установщик, а получить заведомо сошедшееся состояние, от которого
    можно отсчитывать порчу.
    """
    дом = Path(врем)
    м = сверка()
    for п in м.пары(м.установщик(), дом):
        if not п["откуда"].exists() or not п["обязателен"]:
            continue
        п["куда"].parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(п["откуда"], п["куда"])
    return дом


def запустить(дом: Path, *флаги: str) -> tuple[int, str]:
    res = subprocess.run([sys.executable, СКРИПТ, "--home", str(дом), *флаги],
                         capture_output=True, text=True)
    return res.returncode, res.stdout + res.stderr


def main() -> int:
    провалов = 0

    def check(имя: str, ок: bool, подробность: str = "") -> None:
        nonlocal провалов
        if not ок:
            провалов += 1
        print(f"{'✓' if ок else '✗'} {имя}" + (f"  — {подробность}" if not ок and подробность else ""))

    # ── копии сходятся — сверка молчит ───────────────────────────────────────
    with tempfile.TemporaryDirectory() as врем:
        дом = поддельный_дом(врем)
        код, вывод = запустить(дом)
        check("всё сошлось: код 0", код == 0, вывод[-300:])
        check("всё сошлось: сказано, что расхождений нет",
              "расхождений нет" in вывод, вывод[-200:])
        check("всё сошлось: ничего не названо разошедшимся",
              "РАЗОШЛИСЬ" not in вывод and "НЕ ПОСТАВЛЕНО" not in вывод, вывод[-300:])
        check("сверка вообще что-то сверила, а не нашла пустоту",
              "сошлись побайтово: 0" not in вывод, вывод[:80])
        # Оба файла из плана должны быть в сверке ПОИМЁННО видимы при --all:
        # иначе «сошлось» может значить «до них не дошли руки».
        код_все, вывод_все = запустить(дом, "--all")
        check("контекст Serena попал в сверку", f"= {КОНТЕКСТ[0]}" in вывод_все,
              вывод_все[:400])
        check("конвенция памяти попала в сверку", f"= {ПАМЯТЬ[0]}" in вывод_все,
              вывод_все[:400])
        check("--all не меняет вердикт", код_все == 0)

    # ── контекст Serena разошёлся — сверка кричит и называет, ЧТО и ГДЕ ──────
    with tempfile.TemporaryDirectory() as врем:
        дом = поддельный_дом(врем)
        цель = дом / КОНТЕКСТ[1]
        цель.write_text(цель.read_text(encoding="utf-8") +
                        "\n# правка, которой нет в комплекте\n", encoding="utf-8")
        код, вывод = запустить(дом)
        check("контекст разошёлся: код 1", код == 1, вывод[-300:])
        check("контекст разошёлся: назван файл",
              КОНТЕКСТ[0] in вывод, вывод[-400:])
        check("контекст разошёлся: назван путь в комплекте",
              str(КОМПЛЕКТ / КОНТЕКСТ[0]) in вывод, вывод[-400:])
        check("контекст разошёлся: назван путь на машине",
              str(цель) in вывод, вывод[-400:])
        check("контекст разошёлся: показана сама строка расхождения",
              "правка, которой нет в комплекте" in вывод, вывод[-400:])
        check("контекст разошёлся: сказано, чем чинить",
              "diff -u" in вывод, вывод[-400:])

    # ── конвенция памяти не поставлена ───────────────────────────────────────
    #
    # Их имя при установке МЕНЯЕТСЯ (`global-` → `memories/global/`), и именно
    # поэтому их дважды забывали поставить: сверка по имени файла молчала.
    with tempfile.TemporaryDirectory() as врем:
        дом = поддельный_дом(врем)
        (дом / ПАМЯТЬ[1]).unlink()
        код, вывод = запустить(дом)
        check("память не поставлена: код 1", код == 1, вывод[-300:])
        check("память не поставлена: раздел «НЕ ПОСТАВЛЕНО»",
              "НЕ ПОСТАВЛЕНО" in вывод, вывод[-400:])
        check("память не поставлена: назван файл комплекта",
              ПАМЯТЬ[0] in вывод, вывод[-400:])
        check("память не поставлена: назван путь, где её ждали",
              str(дом / ПАМЯТЬ[1]) in вывод, вывод[-400:])
        check("память не поставлена: сказано, чем чинить",
              "install-kit.py" in вывод, вывод[-400:])

    # ── содержимое памяти разошлось ──────────────────────────────────────────
    #
    # Конвенция памяти числится в `install-kit.ПРАВИТЬ_РУКАМИ` — «перечисляет
    # чужие экосистемы», — и требовать от неё побайтового совпадения нельзя.
    # Но и молчать про её расхождение нельзя: это ровно тот случай, ради
    # которого сверка заведена. Обещание тут другое — назвать файл, размер
    # расхождения и оба пути, не роняя вердикт.
    with tempfile.TemporaryDirectory() as врем:
        дом = поддельный_дом(врем)
        цель = дом / ПАМЯТЬ[1]
        цель.write_text("совсем другая конвенция\n", encoding="utf-8")
        код, вывод = запустить(дом)
        check("память разошлась: вердикт не уронен — правится руками", код == 0,
              вывод[-300:])
        check("память разошлась: названа в списке ожидаемых",
              "ОЖИДАЕМО" in вывод and ПАМЯТЬ[0] in вывод, вывод[-400:])
        check("память разошлась: назван путь на машине",
              str(цель) in вывод, вывод[-400:])
        check("память разошлась: назван размер расхождения",
              "+1 −" in вывод, вывод[-400:])

    # ── правится руками — расхождение ожидаемо и вердикта не меняет ──────────
    with tempfile.TemporaryDirectory() as врем:
        дом = поддельный_дом(врем)
        цель = дом / РУКАМИ[1]
        цель.write_text(цель.read_text(encoding="utf-8") + "\nсвой каталог\n",
                        encoding="utf-8")
        код, вывод = запустить(дом)
        check("правится руками: код 0 — не провал", код == 0, вывод[-300:])
        check("правится руками: назван отдельным списком",
              "ОЖИДАЕМО" in вывод and РУКАМИ[0] in вывод, вывод[-400:])
        check("правится руками: не попал в РАЗОШЛИСЬ",
              "РАЗОШЛИСЬ" not in вывод, вывод[-300:])

    # ── дом пуст: всё не поставлено, но скрипт не падает ─────────────────────
    with tempfile.TemporaryDirectory() as врем:
        код, вывод = запустить(Path(врем))
        check("пустой дом: код 1, а не падение", код == 1, вывод[-300:])
        check("пустой дом: сошлось ноль", "сошлись побайтово: 0" in вывод, вывод[:80])

    print(f"\nпровалов: {провалов}")
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(main())
