#!/usr/bin/env python3
"""Проверки установщика комплекта. Токенов не стоит.

Две вещи, каждая из которых ломается молча.

СПИСОК `ОБЩЕЕ` — белый список путей, набранный руками. Опечатка в исходном
пути не роняет установку: файл просто не кладётся, а в докладе это теряется
среди трёх десятков строк. Поэтому здесь проверяется, что КАЖДЫЙ источник из
списка существует на диске.

ВОРОТА ПО MCP — навык `browser` без сервера playwright обещает инструменты,
которых в сессии не будет, и уводит по ложному следу. Проверяется, что ворота
и правда закрываются, а не украшают собой код.
"""
import contextlib
import importlib.util
import io
import json
import sys
import tempfile
from pathlib import Path

КАТАЛОГ = Path(__file__).resolve().parent
спец = importlib.util.spec_from_file_location("install_kit", КАТАЛОГ / "install-kit.py")
ik = importlib.util.module_from_spec(спец)
спец.loader.exec_module(ik)

всего = 0
провалов = 0


def check(имя: str, условие: bool, подробность: str = "") -> None:
    global всего, провалов
    всего += 1
    if not условие:
        провалов += 1
        print(f"  ✗ {имя} {подробность}")


print("install-kit.py")

# --- каждый источник из ОБЩЕЕ существует ------------------------------------
for откуда, куда in ik.ОБЩЕЕ:
    check(f"источник есть: {откуда}", (ik.КОМПЛЕКТ / откуда).exists(),
          f"-> нет {ik.КОМПЛЕКТ / откуда}")
    check(f"назначение внутри дома: {откуда}", not Path(куда).is_absolute(),
          f"={куда}")

# --- ключи ТРЕБУЕТ_MCP действительно перечислены в ОБЩЕЕ --------------------
источники = {откуда for откуда, _ in ik.ОБЩЕЕ}
for ключ in ik.ТРЕБУЕТ_MCP:
    check(f"ТРЕБУЕТ_MCP ссылается на файл из ОБЩЕЕ: {ключ}", ключ in источники,
          "ворота стоят на файле, который и так не ставится")

# --- ПРАВИТЬ_РУКАМИ и НЕ_СТАВИТЬ не противоречат друг другу ------------------
пересечение = set(ik.ПРАВИТЬ_РУКАМИ) & set(ik.НЕ_СТАВИТЬ)
check("файл не может быть одновременно «правь руками» и «не ставить»",
      not пересечение, f"={пересечение}")

# --- ограничители подагентов в шаблоне --------------------------------------
шаблон = json.loads((ik.КОМПЛЕКТ / "settings-hooks.json").read_text(encoding="utf-8"))
env = шаблон.get("env") or {}
check("в шаблоне есть ограничители подагентов",
      {"CLAUDE_CODE_MAX_SUBAGENT_SPAWN_DEPTH",
       "CLAUDE_CODE_MAX_CONCURRENT_SUBAGENTS"} <= set(env), f"={sorted(env)}")
# Глубина 1 выверена запуском 29.08.2026: главная сессия зовёт подагента при
# любом значении, значит считается вложенность. Ноль или отрицательное
# запретили бы делегирование целиком, и заметить это было бы нечем.
check("глубина ровно 1", env.get("CLAUDE_CODE_MAX_SUBAGENT_SPAWN_DEPTH") == "1",
      f"={env.get('CLAUDE_CODE_MAX_SUBAGENT_SPAWN_DEPTH')}")
check("значения — строки", all(isinstance(v, str) for v in env.values()),
      "переменные окружения нестрокового типа до процесса не доедут")
check("одновременных больше одного",
      int(env.get("CLAUDE_CODE_MAX_CONCURRENT_SUBAGENTS", "0")) >= 2,
      "потолок ниже двух убивает всякий веер")

# --- проводка не ссылается на несуществующий хук -----------------------------
#
# Самая тихая из поломок комплекта. Хук сносится или переименовывается, строка в
# `settings-hooks.json` остаётся — и событие начинает срабатывать в пустоту:
# ошибка запуска процесса, никакой проверки, а поведение просто исчезает. Так
# 29.08.2026 из проводки убирали `warn-grep-root`, слитый в диспетчер
# `pretooluse`; заметить недосмотр было бы нечем.
#
# Обратная сторона (файл есть, а в проводке его нет) НЕ ошибка: помощники вроде
# `compact-order.py` зовутся руками и ни на каком событии не стоят.
ЧУЖИЕ = {откуда for откуда, *_ in ik.СОСЕД}
позвано = set()
for событие, записи in (шаблон.get("hooks") or {}).items():
    for запись in записи:
        for х in запись.get("hooks") or []:
            for кусок in (х.get("command") or "").split():
                # Путь внутри дома приводим к пути внутри комплекта: проводка
                # говорит `.claude/hooks/x.py`, а в репозитории это
                # `trah-setup/hooks/x.py`. Так проверка накрывает не только
                # хуки, но и всё остальное, что проводка умеет звать, —
                # например кран строки состояния.
                if "/.claude/" in кусок and кусок.endswith(".py"):
                    позвано.add(кусок.split("/.claude/", 1)[1])
# Порог, а не точное число: он стоит против сломавшегося РАЗБОРА. Пустой набор
# сделал бы проверку ниже вечно зелёной — она бы сравнивала пустоту с пустотой.
check("проводка вообще кого-то зовёт", len(позвано) >= 5, f"={len(позвано)}")
пропавшие = sorted(п for п in позвано
                   if п not in ЧУЖИЕ and not (ik.КОМПЛЕКТ / п).exists())
check("каждый файл из проводки существует", not пропавшие,
      f"проводка зовёт то, чего нет: {пропавшие}")

# --- настроенные_mcp --------------------------------------------------------
def дом_с(данные) -> Path:
    д = Path(tempfile.mkdtemp())
    if данные is not None:
        текст = данные if isinstance(данные, str) else json.dumps(данные)
        (д / ".claude.json").write_text(текст, encoding="utf-8")
    return д


check("серверы верхнего уровня видны",
      ik.настроенные_mcp(дом_с({"mcpServers": {"serena": {}, "playwright": {}}}))
      == {"serena", "playwright"})
check("серверы проектов тоже видны",
      "pm-mcp" in ik.настроенные_mcp(дом_с(
          {"mcpServers": {"serena": {}},
           "projects": {"/x": {"mcpServers": {"pm-mcp": {}}}}})))
check("файла нет — пусто", ik.настроенные_mcp(дом_с(None)) == set())
check("битый JSON — пусто, а не падение",
      ik.настроенные_mcp(дом_с("{это не json")) == set())
check("ключа нет — пусто", ik.настроенные_mcp(дом_с({"model": "opus"})) == set())
check("projects с null не роняет",
      ik.настроенные_mcp(дом_с({"projects": {"/x": None}})) == set())

# --- ворота: навык не ставится без своего сервера ---------------------------
class Отчёт(ik.Отчёт):
    pass


def поставить(дом: Path) -> tuple[list[str], list[str]]:
    # Сухой прогон печатает свой доклад в stdout. В общем прогоне тестов он
    # утопил бы строку с итогом, поэтому глушим: проверяем поля отчёта, а не
    # то, что он напечатал.
    отчёт = ik.Отчёт(True)          # всухую: на диск ничего не пишется
    with io.StringIO() as глушь, contextlib.redirect_stdout(глушь):
        ik.поставить_общее(отчёт, дом, {})
    return отчёт.сделано, отчёт.пропущено


д = дом_с({"mcpServers": {"serena": {}}})       # playwright НЕ настроен
_, пропущено = поставить(д)
check("без playwright навык browser пропущен",
      any("skills/browser" in с for с in пропущено),
      f"пропущено={[с[:60] for с in пропущено][:4]}")
check("в объяснении названо, чего не хватает",
      any("playwright" in с for с in пропущено))

д = дом_с({"mcpServers": {"serena": {}, "playwright": {}}})
сделано, пропущено = поставить(д)
check("с playwright навык browser ставится",
      not any("skills/browser" in с for с in пропущено),
      f"пропущено={[с[:60] for с in пропущено][:4]}")

# Навык без ворот ставится в обоих случаях — иначе ворота задевали бы лишнее.
д = дом_с({"mcpServers": {}})
_, пропущено = поставить(д)
check("навык security от MCP не зависит",
      not any("skills/security" in с for с in пропущено))
check("агенты от MCP не зависят",
      not any("agents/" in с for с in пропущено))

print(f"  {всего - провалов}/{всего} проверок прошло")
sys.exit(1 if провалов else 0)
