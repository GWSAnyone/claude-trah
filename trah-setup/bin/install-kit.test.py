check("значения — строки", all(isinstance(v, str) for v in env.values()),
      "переменные окружения нестрокового типа до процесса не доедут")
check("одновременных больше одного",
      int(env.get("CLAUDE_CODE_MAX_CONCURRENT_SUBAGENTS", "0")) >= 2,
      "потолок ниже двух убивает всякий веер")

# --- фильтр по утилитам стоит на настоящих командах --------------------------
#
# Заведено по факту: ключи ТРЕБУЕТ были именами файлов хуков, а фильтр сверяет
