# --- ключи шаблона доезжают до settings.json --------------------------------
#
# Заведено по факту: `statusLine` и `promptCacheTtl` лежали в шаблоне и не
# попадали в настройки НИКОГДА — `проводка` переносила только hooks, permissions
# и env. Кран строки состояния ставился файлом, не вызывался ни разу, счёт кеша
# не копился. Ни одна проверка этого не видела, потому что все они смотрели на
# шаблон, а не на то, что получилось.
def настройки_после(было=None) -> tuple[dict, list[str], dict]:
    """Прогнать `проводка` в свежем доме и вернуть, что получилось.

    Третьим — шаблон с уже подставленными `@PY@` и `@HOME@`: сравнивать вышедшее
    с сырым шаблоном нельзя, там плейсхолдеры.
    """
    д = Path(tempfile.mkdtemp())
    (д / ".claude").mkdir()
    if было is not None:
        (д / ".claude/settings.json").write_text(json.dumps(было), encoding="utf-8")
    отчёт = ik.Отчёт(False)
    with io.StringIO() as глушь, contextlib.redirect_stdout(глушь):
        ik.проводка(отчёт, д, {у: "/usr/bin/" + у for у in ik.ТРЕБУЕТ.values()},
                    заменять=False)
    ждём = json.loads((ik.КОМПЛЕКТ / "settings-hooks.json").read_text(encoding="utf-8")
                      .replace("@HOME@", ik.в_шаблон(д)).replace("@PY@", ik.в_шаблон(sys.executable)))
    вышло = json.loads((д / ".claude/settings.json").read_text(encoding="utf-8"))
    return вышло, отчёт.руками, ждём


