# --- проводка не ссылается на несуществующий хук -----------------------------
#
# Самая тихая из поломок комплекта. Хук сносится или переименовывается, строка в
# `settings-hooks.json` остаётся — и событие начинает срабатывать в пустоту:
# ошибка запуска процесса, никакой проверки, а поведение просто исчезает. Так
# 29.08.2026 из проводки убирали `warn-grep-root`, слитый в диспетчер
# `pretooluse`; заметить недосмотр было бы нечем.
#
# Обратная сторона (файл есть, а в проводке его нет) НЕ ошибка: помощники вроде
# `compact-order.py` зовутся руками и ни на каком событии не стоят.
# Чужих файлов в проводке комплекта больше нет: с 07.09.2026 модули соседних
# продуктов живут в своём реестре `modules.local.json`, а не в проводке и не в
# списке диспетчера.
ЧУЖИЕ: set[str] = set()
позвано = set()
for событие, записи in (шаблон.get("hooks") or {}).items():
    for запись in записи:
        for х in запись.get("hooks") or []:
            for кусок in (х.get("command") or "").split():
                # Путь внутри дома приводим к пути внутри комплекта: проводка
                # говорит `.claude/hooks/x.py`, а в репозитории это
                # `trah-setup/hooks/x.py`. Так проверка накрывает не только
                # хуки, но и всё остальное, что проводка умеет звать, —
                # например кран строки состояния.
                if "/.claude/" in кусок and кусок.endswith(".py"):
                    позвано.add(кусок.split("/.claude/", 1)[1])
# Порог, а не точное число: он стоит против сломавшегося РАЗБОРА. Пустой набор
# сделал бы проверку ниже вечно зелёной — она бы сравнивала пустоту с пустотой.
check("проводка вообще кого-то зовёт", len(позвано) >= 5, f"={len(позвано)}")
пропавшие = sorted(п for п in позвано
                   if п not in ЧУЖИЕ and not (ik.КОМПЛЕКТ / п).exists())
check("каждый файл из проводки существует", not пропавшие,
      f"проводка зовёт то, чего нет: {пропавшие}")

