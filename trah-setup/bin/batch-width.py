#!/usr/bin/env python3
"""Ширина пачек: сколько вызовов инструментов приходится на один ход ассистента.

ПОЧЕМУ ПО СТЕНОГРАММЕ, А НЕ ХУКОМ. Событие `Stop` приходит один раз на весь
ответ, а не на каждую пачку, и посчитать им ширину нельзя — выйдет сумма за
пользовательский ход. Стенограмма же хранит всё и меряется задним числом, в том
числе ДО правки промпта, и во время работы не стоит ничего.

ЧТО ТАМ НА САМОМ ДЕЛЕ. Один ответ модели разложен по записям: на каждый блок
своя строка, общий у них `requestId`. Наивный счёт «по записи на ход» даёт
ширину 1 у всего подряд — первый замер 29.08.2026 так и сказал: 6987 ходов,
100% одиночных, максимум 1, при живых пачках по двадцать пять вызовов в той же
сессии. Поэтому записи группируются по `requestId`.

Наружу идут только числа: содержимое стенограммы в контекст не попадает.

    python3 batch-width.py                      # текущий проект целиком
    python3 batch-width.py --since 2026-08-29   # только ходы после даты
    python3 batch-width.py --sessions 3         # три последние сессии
    python3 batch-width.py путь.jsonl           # конкретная стенограмма

Ветки подагентов (`isSidechain`) по умолчанию исключены: у подагента свой
промпт и своя дисциплина, смешивать их с главным потоком значит мерить не то.
"""
import json
import sys
from collections import Counter
from pathlib import Path

ПРОЕКТЫ = Path.home() / ".claude" / "projects"


def стенограммы(доводы: list[str], сессий: int | None) -> list[Path]:
    """Какие файлы считать: явные пути, иначе каталог текущего проекта."""
    пути = [Path(д) for д in доводы if д.endswith(".jsonl")]
    if not пути:
        каталог = ПРОЕКТЫ / str(Path.cwd()).replace("/", "-")
        if not каталог.is_dir():
            return []
        пути = sorted(каталог.glob("*.jsonl"), key=lambda p: p.stat().st_mtime)
    if сессий:
        пути = пути[-сессий:]
    return пути


def ходы(путь: Path, с_даты: str | None, с_подагентами: bool) -> list[tuple[str, int, list[str]]]:
    """Список (время, ширина, инструменты) по каждой ПАЧКЕ.

    Пачка — это один ответ модели, но в стенограмме он разложен по записям: на
    каждый блок своя строка, общий у них `requestId`. Считать по записям значит
    получить ширину 1 у всего на свете — ровно это и показал первый замер
    29.08.2026: 6987 ходов, 100% одиночных, максимум 1, при живых пачках по
    двадцать пять вызовов в той же сессии. Поэтому группируем.
    """
    группы: dict[str, list] = {}
    порядок: list[str] = []
    try:
        строки = путь.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return []
    for строка in строки:
        строка = строка.strip()
        if not строка:
            continue
        try:
            з = json.loads(строка)
        except json.JSONDecodeError:
            continue
        if з.get("type") != "assistant":
            continue
        if з.get("isSidechain") and not с_подагентами:
            continue
        когда = з.get("timestamp") or ""
        if с_даты and когда < с_даты:
            continue
        содержимое = (з.get("message") or {}).get("content")
        if not isinstance(содержимое, list):
            continue
        имена = [б.get("name", "?") for б in содержимое
                 if isinstance(б, dict) and б.get("type") == "tool_use"]
        if not имена:
            continue
        ключ = (з.get("requestId") or (з.get("message") or {}).get("id")
                or з.get("uuid") or когда)
        if ключ not in группы:
            группы[ключ] = [когда, []]
            порядок.append(ключ)
        группы[ключ][1].extend(имена)
    return [(группы[к][0], len(группы[к][1]), группы[к][1]) for к in порядок]


def медиана(числа: list[int]) -> float:
    if not числа:
        return 0.0
    ч = sorted(числа)
    середина = len(ч) // 2
    return float(ч[середина]) if len(ч) % 2 else (ч[середина - 1] + ч[середина]) / 2


def свод(все: list[tuple[str, int, list[str]]]) -> dict:
    ширины = [ш for _, ш, _ in все]
    одиночные = Counter()
    for _, ш, имена in все:
        if ш == 1:
            одиночные[имена[0]] += 1
    гист = Counter()
    for ш in ширины:
        гист["5+" if ш >= 5 else str(ш)] += 1
    return {
        "ходов": len(ширины),
        "вызовов": sum(ширины),
        "среднее": round(sum(ширины) / len(ширины), 2) if ширины else 0.0,
        "медиана": медиана(ширины),
        "максимум": max(ширины) if ширины else 0,
        "доля_одиночных": round(100 * гист["1"] / len(ширины)) if ширины else 0,
        "гистограмма": гист,
        "одиночные": одиночные,
    }


def печать(с: dict) -> None:
    if not с["ходов"]:
        print("ходов с вызовами не найдено")
        return
    print(f"ходов с вызовами: {с['ходов']}")
    print(f"вызовов всего:    {с['вызовов']}")
    print(f"ширина: среднее {с['среднее']}  медиана {с['медиана']}  максимум {с['максимум']}")
    print(f"доля ходов шириной 1: {с['доля_одиночных']}%  ({с['гистограмма']['1']})")
    порядок = ["1", "2", "3", "4", "5+"]
    print("гистограмма: " + "  ".join(f"{к}:{с['гистограмма'][к]}" for к in порядок
                                      if с["гистограмма"][к]))
    if с["одиночные"]:
        верх = "  ".join(f"{и} {n}" for и, n in с["одиночные"].most_common(6))
        print("чаще всего в одиночку: " + верх)


def main() -> int:
    доводы = sys.argv[1:]
    с_даты = None
    сессий = None
    с_подагентами = "--subagents" in доводы
    for i, д in enumerate(доводы):
        if д == "--since" and i + 1 < len(доводы):
            с_даты = доводы[i + 1]
        if д == "--sessions" and i + 1 < len(доводы):
            сессий = int(доводы[i + 1])
    пути = стенограммы(доводы, сессий)
    if not пути:
        print("стенограмм не найдено")
        return 1
    все: list[tuple[str, int, list[str]]] = []
    for п in пути:
        все.extend(ходы(п, с_даты, с_подагентами))
    print(f"стенограмм: {len(пути)}" + (f", с даты {с_даты}" if с_даты else ""))
    печать(свод(все))
    return 0


if __name__ == "__main__":
    sys.exit(main())
