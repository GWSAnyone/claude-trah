#!/usr/bin/env python3
"""Доезжают ли ОДНОВРЕМЕННО бриф и патчи бинарника.

    check-brief-delivery.py          запуск как в деле: обёртка + копия переменной
    check-brief-delivery.py мимо     прежнее поведение: путь подменён на копию

ЗАЧЕМ. Эти две вещи приходят разными дорогами, и одна тихо отменяет другую.
Патчи живут в самом бинарнике. Брифы подаёт ОБЁРТКА `~/.local/bin/claude`: она
находит `~/.claude/brief.md` и `<проект>/.claude/brief.md`, склеивает их и
добавляет `--append-system-prompt-file`. Подменить путь на патченую копию —
значит выкинуть обёртку из запуска вместе с обоими брифами.

Именно это и случилось 22.08.2026: служба таусозавра получила
`PRITONOZAVR_CLAUDE=…/trah/current`, и все её сессии пошли без единого правила.
Молча — сессия поднимается, отвечает, просто ведёт себя как чужая. Проверено
этой пробой в обе стороны: с обёрткой видны и брифы, и патчи; мимо обёртки —
только патчи.

Правильный способ включить патченую сборку — передать её обёртке переменной
`CLAUDE_WRAPPER_TARGET`: это её штатная лазейка, и стоит она первой в
разрешении цели.

Проба уходит в ловушку `sink.py` и не стоит ни одного токена.
"""
import importlib.util
import os
import sys
from pathlib import Path

ЗДЕСЬ = Path(__file__).resolve().parent
спец = importlib.util.spec_from_file_location("trah", ЗДЕСЬ / "trah.py")
trah = importlib.util.module_from_spec(спец)
спец.loader.exec_module(trah)

ОБЁРТКА = Path.home() / ".local/bin/claude"
КОПИЯ = Path.home() / ".local/share/claude/trah/current"

# Каталог важен: проектный бриф обёртка ищет вверх от текущего.
КОРЕНЬ = ЗДЕСЬ.parent.parent

def первая_строка(текст: str) -> str:
    """Чем узнать этот бриф в системном промпте.

    Метку ВЫЧИСЛЯЕМ, а не зашиваем. Зашитая «You are Siesta» — это фраза из
    брифа одного конкретного человека: у любого другого проба падала бы всегда,
    и падала бы врущим образом — «правила не доехали», хотя доехали чужие.
    """
    for строка in текст.splitlines():
        строка = строка.strip().lstrip("#- ").strip()
        if len(строка) >= 20:
            return строка[:60]
    return ""


def признаки(есть_копия: bool) -> dict[str, tuple[str, str]]:
    вышло: dict[str, tuple[str, str]] = {}

    # Метку берём из ЖИВОГО файла, а не собираем бриф заново. Проба отвечает на
    # вопрос «доезжает ли то, что лежит на диске», и собранный тут же второй
    # текст этого вопроса не задаёт — он спрашивает про себя самого. Прежняя
    # редакция звала питоновский сборщик, и после разделения комплектов проба
    # падала словами «кусков брифа для области global нет», ничего не проверив.
    глобальный = Path.home() / ".claude/brief.md"
    if глобальный.exists():
        метка = первая_строка(глобальный.read_text(encoding="utf-8"))
        if метка:
            вышло["бриф глобальный"] = ("система", метка)

    # Проектный бриф — только если он тут есть. У чужого человека своей
    # экосистемы может не быть вовсе, и требовать её значит требовать чужого.
    проектный = КОРЕНЬ / ".claude/brief.md"
    if проектный.exists():
        метка = первая_строка(проектный.read_text(encoding="utf-8"))
        if метка:
            вышло["бриф проекта"] = ("система", метка)

    # Патчи бинарника проверяем, только если патченая копия собрана: для
    # развёртывания она не нужна вовсе, и её отсутствие — не поломка.
    if есть_копия:
        вышло["патч системного промпта (символьный слой)"] = (
            "система", "where a symbolic code layer is available")
        вышло["патч описания Bash (инструмент действия)"] = (
            "Bash", "This is a tool of action")
    return вышло


def main() -> int:
    мимо = "мимо" in sys.argv
    есть_копия = КОПИЯ.exists()
    if мимо and not есть_копия:
        print(f"встречную пробу гонять не по чему: патченой копии нет ({КОПИЯ})",
              file=sys.stderr)
        return 1
    if есть_копия:
        os.environ["CLAUDE_WRAPPER_TARGET"] = str(КОПИЯ)
    os.chdir(КОРЕНЬ)

    цель = КОПИЯ if мимо else ОБЁРТКА
    if not цель.exists():
        print(f"нечего запускать: {цель} не существует", file=sys.stderr)
        return 1

    что_ищем = признаки(есть_копия)
    if not что_ищем:
        print("нечего проверять: бриф пуст", file=sys.stderr)
        return 1

    поймано = trah.проба(цель, "default")
    плохо = 0
    брифов_мимо = 0
    for что, (где, метка) in что_ищем.items():
        есть = метка in поймано.get(где, "")
        print(("  ✓ " if есть else "  ✗ ") + f"{что}  ({метка[:40]}…)")
        if not есть:
            плохо += 1
            if что.startswith("бриф"):
                брифов_мимо += 1
    if мимо:
        # Мимо обёртки брифов быть НЕ ДОЛЖНО — это доказательство поломки, и
        # ноль промахов здесь означал бы, что проба ничего не проверяет.
        всего_брифов = sum(1 for к in что_ищем if к.startswith("бриф"))
        print(f"запуск мимо обёртки: брифов не доехало {брифов_мимо} "
              f"из {всего_брифов} — должны были не доехать все")
        return 0 if брифов_мимо == всего_брифов else 1
    return 1 if плохо else 0


if __name__ == "__main__":
    sys.exit(main())
