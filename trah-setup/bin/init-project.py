#!/usr/bin/env python3
"""Проектный уровень: разложить скелет в рабочем каталоге.

Зачем это вообще нужно. Комплект ставит ГЛОБАЛЬНЫЙ уровень — хуки, агентов,
навыки, общий бриф. Но пять его частей молча рассчитывают на то, что в рабочем
каталоге есть `docs/plans/` и `docs/reports/`:

  * агент `critical-reviewer` пишет отчёт в `docs/reports/`;
  * навык `security` складывает туда же находки;
  * навык `checkpoint` ищет план под `docs/plans/`;
  * навык `start` перечисляет свежие планы оттуда же;
  * хук чекпоинта пишет указатель на активный план.

До 08.09.2026 комплект не вёз про это НИ ОДНОГО правила и не заводил ни одного
каталога. Человек получал пять частей, ссылающихся на соглашение, которого ему
никто не объяснил, — ровно та молчаливая полуустановка, против которой написан
весь комплект.

Что кладём: `CLAUDE.md`-указатель, скелет брифа каталога, правило раскладки
документации и два `README` — в `docs/plans/` и `docs/reports/`.

Чего НЕ делаем: не выдумываем содержание. Бриф каталога — знание хозяина, а не
наше. Кладётся скелет с вопросами в заголовках; заполняет человек.

Существующий файл не трогается НИКОГДА. Проектный уровень — место, где у
человека чаще всего уже что-то есть, и затереть его чужой `CLAUDE.md` значит
сделать ровно то, чего комплект обещает не делать.

Запуск:
    python3 trah-setup/bin/init-project.py <каталог>            # показать
    python3 trah-setup/bin/init-project.py <каталог> --write    # положить
"""

import sys
from pathlib import Path

КОМПЛЕКТ = Path(__file__).resolve().parent.parent
ШАБЛОН = КОМПЛЕКТ / "project-template"


def файлы_шаблона() -> list[Path]:
    return sorted(п for п in ШАБЛОН.rglob("*") if п.is_file())


def разложить(куда: Path, писать: bool) -> dict:
    """Разложить шаблон. Возвращает три списка: положено, было, пропущено."""
    имя = куда.resolve().name
    итог = {"положено": [], "было": [], "пусто": []}
    for источник in файлы_шаблона():
        отн = источник.relative_to(ШАБЛОН)
        цель = куда / отн
        if цель.exists():
            итог["было"].append(отн.as_posix())
            continue
        текст = источник.read_text(encoding="utf-8").replace("@PROJECT@", имя)
        if писать:
            цель.parent.mkdir(parents=True, exist_ok=True)
            цель.write_text(текст, encoding="utf-8")
        итог["положено"].append(отн.as_posix())
    return итог


def доклад(куда: Path, итог: dict, писать: bool) -> None:
    заголовок = "ПРОЕКТНЫЙ УРОВЕНЬ" if писать else "ПРОЕКТНЫЙ УРОВЕНЬ (показ)"
    print(f"{заголовок}: {куда}")
    print("=" * 70)
    if итог["положено"]:
        print(f"\n{'ПОЛОЖЕНО' if писать else 'ЛЯЖЕТ'} — {len(итог['положено'])}:")
        for п in итог["положено"]:
            print(f"  + {п}")
    if итог["было"]:
        print(f"\nУЖЕ ЕСТЬ, НЕ ТРОНУТО — {len(итог['было'])}:")
        for п in итог["было"]:
            print(f"  = {п}")
        print("\n  Эти файлы принадлежат хозяину. Если их надо сблизить с нашим")
        print("  форматом — это разговор с ним и вердикт, а не работа скрипта.")
    if not итог["положено"] and not итог["было"]:
        print("\nШаблон пуст — проверь установку комплекта.")

    print("\nДАЛЬШЕ РУКАМИ:")
    print("  • заполнить .claude/brief.md — заголовки там это вопросы,")
    print("    на которые сессия обязана иметь ответ, не читая код;")
    print("  • дописать в CLAUDE.md абзац «чем эта работа отличается»;")
    print("  • привязать Serena к КОРНЮ каталога проектов, а не к каждому")
    print("    проекту по отдельности.")
    if not писать:
        print("\nЭто был показ. Ничего не записано. Повторить с --write.")
    print("─" * 70)


def main() -> int:
    д = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not д:
        print(__doc__)
        return 1
    куда = Path(д[0]).expanduser()
    if not куда.is_dir():
        print(f"нет такого каталога: {куда}", file=sys.stderr)
        return 1
    писать = "--write" in sys.argv
    итог = разложить(куда, писать)
    доклад(куда, итог, писать)
    return 0


if __name__ == "__main__":
    sys.exit(main())
