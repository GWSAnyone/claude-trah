#!/usr/bin/env python3
"""Проверки `count-bullet.py` на поддельном бинарнике. Токенов не стоит.

Считать надо ВХОЖДЕНИЯ, а не строки — на этом и обманулся `grep -c`. И две
копии, разошедшиеся дальше 330-го байта, для строки поиска неразличимы: счёт
вариантов обязан их склеивать, иначе патч будет искать то, чего нет.
"""
import contextlib
import importlib.util
import io
import sys
import tempfile
from pathlib import Path

СКРИПТ = Path(__file__).resolve().parent / "count-bullet.py"
спец = importlib.util.spec_from_file_location("count_bullet", СКРИПТ)
cb = importlib.util.module_from_spec(спец)
спец.loader.exec_module(cb)

всего = 0
провалов = 0


def check(имя: str, условие: bool, подробность: str = "") -> None:
    global всего, провалов
    всего += 1
    if not условие:
        провалов += 1
        print(f"  ✗ {имя} {подробность}")


def бинарь(*куски: bytes) -> tuple[bytes, list[int]]:
    """Склеивает куски и запоминает смещения тех, что начинаются с якоря."""
    данные = b""
    места: list[int] = []
    for к in куски:
        if к.startswith(cb.ЯКОРЬ):
            места.append(len(данные))
        данные += к
    return данные, места


def вывод(*пути: Path) -> tuple[int, str]:
    """Код возврата и напечатанное: у скрипта нет иного способа отдать ответ."""
    сохранённый = sys.argv
    sys.argv = ["count-bullet.py", *[str(п) for п in пути]]
    try:
        with io.StringIO() as поток, contextlib.redirect_stdout(поток):
            код = cb.main()
            напечатано = поток.getvalue()
    finally:
        sys.argv = сохранённый
    return код, напечатано


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        МУСОР = b"\x00\x01\x02 " + "просто байты ".encode()
        А = cb.ЯКОРЬ + b"prefer dedicated tools\n" + b"A" * 400
        Б = cb.ЯКОРЬ + b"prefer dedicated tools\n" + b"B" * 400

        # Б лежит первым, А — двумя копиями следом: порядок вариантов задаётся
        # первым вхождением, а не тем, каких копий больше.
        данные, места = бинарь(МУСОР, Б, МУСОР, А, А)
        путь = Path(tmp) / "бинарь"
        путь.write_bytes(данные)

        код, текст = вывод(путь)
        check("код возврата ноль", код == 0, str(код))
        check("шапка несёт путь и число вхождений",
              f"═══ {путь}: вхождений 3" in текст, текст)
        check("вариант 1 — тот, что встретился раньше",
              f"вариант 1: 1 шт., смещения [{места[0]}]" in текст, текст)
        check("одинаковые копии склеены в один вариант",
              f"вариант 2: 2 шт., смещения [{места[1]}, {места[2]}]" in текст, текст)
        check("перевод строки в хвосте заменён разделителем", " | " in текст, текст)
        длиннейшая = max(len(с) for с in текст.splitlines())
        check("хвост обрезан до 320 знаков", длиннейшая <= 4 + 320, str(длиннейшая))

        # Копии, совпадающие первые 330 байт и расходящиеся дальше, — один
        # вариант: строке поиска эта разница недоступна.
        общее = cb.ЯКОРЬ + b"C" * 400
        данные2, _ = бинарь(общее + b" tail-1", МУСОР, общее + b" tail-2")
        поздний = Path(tmp) / "поздний-разрыв"
        поздний.write_bytes(данные2)
        _, текст2 = вывод(поздний)
        check("оба вхождения найдены", "вхождений 2" in текст2, текст2)
        check("разрыв дальше окна не плодит вариант",
              "вариант 1: 2 шт." in текст2 and "вариант 2" not in текст2, текст2)

        # Два вхождения в одной строке: `grep -c` тут показал бы единицу.
        одной_строкой = Path(tmp) / "одной-строкой"
        одной_строкой.write_bytes(А.replace(b"\n", b" ") + А.replace(b"\n", b" "))
        _, текст3 = вывод(одной_строкой)
        check("две копии без перевода строки — всё равно два вхождения",
              "вхождений 2" in текст3, текст3)

        пусто = Path(tmp) / "без-якоря"
        пусто.write_bytes(МУСОР * 3)
        _, текст4 = вывод(пусто)
        check("без якоря — ноль вхождений", "вхождений 0" in текст4, текст4)
        check("без якоря вариантов не печатается", "вариант" not in текст4, текст4)

        порожний = Path(tmp) / "порожний"
        порожний.write_bytes(b"")
        код5, текст5 = вывод(порожний)
        check("пустой файл не роняет", код5 == 0 and "вхождений 0" in текст5, текст5)

        # Файл сборки не UTF-8 целиком, и окно обрезает байты посреди символа.
        битый = Path(tmp) / "битый"
        битый.write_bytes(cb.ЯКОРЬ + b"\xff\xfe\xfd" + "хвост".encode() + b"D" * 400)
        код6, текст6 = вывод(битый)
        check("битые байты не роняют разбор", код6 == 0 and "вхождений 1" in текст6,
              текст6)
        check("битые байты заменены, а не потеряны", "�" in текст6, текст6)

        # Несколько бинарников за один запуск — каждому своя шапка.
        _, текст7 = вывод(путь, поздний)
        check("файлы разбираются подряд", текст7.count("═══") == 2, текст7)
        check("шапка второго файла на месте",
              f"═══ {поздний}: вхождений 2" in текст7, текст7)

        код8, текст8 = вывод()
        check("без доводов — тишина и ноль", код8 == 0 and текст8 == "", repr(текст8))

        # Несуществующий путь — падение, а не молчаливый ноль: опечатка в
        # имени не должна выглядеть как «вхождений нет».
        try:
            вывод(Path(tmp) / "нет-такого")
            упало = False
        except FileNotFoundError:
            упало = True
        check("пропавший файл роняет, а не молчит", упало)

    check("варианты сортируются по первому вхождению, а не по порядку словаря",
          [к for к, _ in cb.хвостов_по_порядку({b"a": [40], b"b": [90, 5]})]
          == [b"b", b"a"])
    check("пустой набор хвостов — пустой список", cb.хвостов_по_порядку({}) == [])

    print(f"всего: {всего}   провалов: {провалов}")
    return 1 if провалов else 0


if __name__ == "__main__":
    sys.exit(main())
