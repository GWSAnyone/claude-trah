    if not н["есть"]:
        print("  ~/.claude/settings.json нет — проводка ляжет на пустое место")
    elif "ошибка" in н:
        print(f"  settings.json не разбирается: {н['ошибка']}")
    else:
        print(f"  своя проводка: событий {len(н['события'])}, вызовов {н['вызовов']}")
        if н["события"]:
            print(f"  события: {', '.join(н['события'])}")
        if н["ключи"]:
            print(f"  прочие ключи: {', '.join(н['ключи'])}")

    х = о["хуки"]
    print(f"\nХУКИ: наших вызовов {х['наших_вызовов']}, чужих {х['чужих_вызовов']}")
    if х["пересечения"]:
        print("\n  ПЕРЕСЕКАЮТСЯ ПО НАЗНАЧЕНИЮ — по каждому нужен вердикт:")
        for п in х["пересечения"]:
            ч = п["чужой"]
            print(f"\n  чужой: {ч['событие']} [{ч['матчер'] or '*'}]")
            print(f"         {ч['команда'][:96]}")
            for с in п["пересекается_с"]:
                print(f"    ↔ наша способность «{с['способность']}» ({с['почему']})")
                print(f"      она {с['зачем_наша']}")
                print(f"      наши файлы: {', '.join(с['наши_файлы'])}")
        print("\n  Вердикт по каждой строке — твой и хозяина, не скрипта:")
        print("    ОСТАВИТЬ ОБА  — оба хука работают, событие это допускает")
        print("    СЛИТЬ         — одна логика вместо двух, писать заново")
