#!/usr/bin/env python3
"""Опись чужой машины: что у хозяина уже есть и с чем комплект столкнётся.

Зачем отдельный инструмент. Установщик отвечает на вопрос «что я положу», а
агенту-настройщику нужен другой: «что здесь УЖЕ живёт и чего я лишу человека,
если поставлю не глядя». Разница не косметическая. `install-kit.py --dry-run`
печатает список файлов, которые он запишет, — и файл хозяина в этом списке
выглядит ровно как наш собственный, потому что установщику всё равно, чей он.

Опись отвечает на вопрос хозяина, а не установщика, и потому делит найденное на
четыре кучи:

  НАШЕ            — стоит от комплекта и совпадает с ним байт в байт;
  СТОЛКНОВЕНИЕ    — по тому же пути лежит ЧУЖОЙ файл, и он не наш;
  ПРАВЛЕНО        — стояло от комплекта, но с тех пор человек его правил;
  ЧУЖОЕ           — вещи хозяина, которых комплект не касается вовсе.

Последняя куча — главная. Цель комплекта не заменить рабочее место, а
дополнить его, поэтому список «чего мы НЕ тронем» человек должен увидеть
раньше, чем список того, что мы поставим.

Свои и чужие различаются по памятке `~/.claude/.trah-manifest.json`, которую
пишет установщик: путь → отпечаток содержимого на момент установки. Памятки
нет — значит комплект здесь не стоял, и ЛЮБОЙ совпавший по имени файл считается
чужим. Это намеренно осторожно: ошибиться в сторону «не трогать» дёшево,
ошибиться в другую — значит стереть чужую работу.

Запуск:
    python3 trah-setup/bin/inventory.py            # доклад человеку
    python3 trah-setup/bin/inventory.py --json     # то же машинно
    python3 trah-setup/bin/inventory.py --дом ПУТЬ # осмотреть другой дом
"""

import hashlib
import importlib.util
import json
import sys
from pathlib import Path

КОМПЛЕКТ = Path(__file__).resolve().parent.parent
ПАМЯТКА = ".claude/.trah-manifest.json"


def _установщик():
    """Таблицы состава берём из самого установщика, а не переписываем.

    Второй список того же самого — это способ разойтись с ним молча: файл
    добавят в `ОБЩЕЕ`, а опись про него не узнает и скажет человеку неправду.
    Имя файла с дефисом обычным `import` не берётся, отсюда importlib.
    """
    путь = КОМПЛЕКТ / "bin/install-kit.py"
    spec = importlib.util.spec_from_file_location("install_kit", путь)
    модуль = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(модуль)
    return модуль


def отпечаток(путь: Path) -> str:
    return hashlib.sha256(путь.read_bytes()).hexdigest()


def памятка(дом: Path, уст) -> dict:
    """То же представление о «своём», что и у установщика.

    Читаем через его же `Отчёт`, а не разбираем файл сами: там живёт ещё и
    переход для машин, где комплект стоял до появления памятки. Опись,
    считающая своим не то же, что установщик, вреднее отсутствующей.
    """
    отчёт = уст.Отчёт(True, дом)
    return отчёт.памятка


def состав_комплекта(уст) -> list[tuple[str, str]]:
    """Пары «файл комплекта → куда ляжет».

    Берём у установщика, а не составляем заново: второй список того же самого
    разошёлся бы с первым молча.
    """
    return уст.состав()


def разложить(дом: Path, уст) -> dict:
    """Разложить состав комплекта по четырём кучам."""
    было = памятка(дом, уст)
    кучи = {"наше": [], "столкновение": [], "правлено": [], "новое": []}
    for откуда, куда in состав_комплекта(уст):
        источник = КОМПЛЕКТ / откуда
        цель = дом / куда
        if not источник.exists():
            continue
        if not цель.exists():
            кучи["новое"].append(куда)
            continue
        наш = отпечаток(источник)
        их = отпечаток(цель)
        if наш == их:
            кучи["наше"].append(куда)
        elif куда in было:
            # Стояло от нас, но содержимое разошлось. Разошлось оно либо
            # потому, что человек правил файл под себя, либо потому, что
            # комплект с тех пор ушёл вперёд. Различить эти два случая по
            # одному отпечатку нельзя, и врать об этом не надо: обе ветки
            # требуют одного и того же — показать человеку разницу.
            кучи["правлено"].append(куда)
        else:
            кучи["столкновение"].append(куда)
    return кучи


def чужое(дом: Path, уст) -> dict:
    """Вещи хозяина, которых комплект не касается.

    Считаем по каталогам, где комплект вообще что-то кладёт: навыки, агенты,
    хуки, правила, стили вывода. Файл, лежащий там и не входящий в состав
    комплекта, — вещь хозяина, и она останется на месте.
    """
    наши_цели = {куда for _, куда in состав_комплекта(уст)}
    итог = {}
    места = [
        ("навыки", ".claude/skills", "*/SKILL.md"),
        ("агенты", ".claude/agents", "*.md"),
        ("правила", ".claude/rules", "*.md"),
        ("стили вывода", ".claude/output-styles", "*.md"),
        # Маска «всё», а не `*.py`: чужой хук вполне может быть на shell или
        # на чём угодно ещё. Первая редакция глядела только на питон и молча
        # не замечала `autosummary.sh` — то есть ровно ту чужую систему, ради
        # которой опись и написана.
        ("хуки", ".claude/hooks", "*"),
        ("команды", ".claude/commands", "*.md"),
    ]
    for имя, каталог, маска in места:
        корень = дом / каталог
        if not корень.is_dir():
            continue
        чужие = []
        for файл in sorted(корень.glob(маска)):
            if not файл.is_file():
                continue
            отн = файл.relative_to(дом).as_posix()
            if отн in наши_цели:
                continue
            if файл.name.endswith(".test.py"):
                continue
            # Наши же следы: резервные копии, спасённый файл точки входа,
            # кеш питона. Первая редакция с маской `*` объявила чужими 71 хук,
            # из которых 69 были копиями `.bak-<время>`, положенными нами же.
            if ".bak-" in файл.name or файл.name.endswith((".before-trah", ".pyc")):
                continue
            чужие.append(отн)
        if чужие:
            итог[имя] = чужие
    return итог


