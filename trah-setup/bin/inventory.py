def _вызовы(дом: Path) -> list[dict]:
    """Плоский список записей проводки: событие, матчер, команда."""
    путь = дом / ".claude/settings.json"
    if not путь.exists():
        return []
    try:
        д = json.loads(путь.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return []
    итог = []
    for событие, блоки in (д.get("hooks") or {}).items():
        for блок in блоки or []:
            for вызов in блок.get("hooks") or []:
                итог.append({
                    "событие": событие,
                    "матчер": блок.get("matcher") or "",
                    "команда": вызов.get("command") or "",
                })
    return итог


def наши_команды(дом: Path, уст) -> set[str]:
    """Команды из нашего шаблона проводки, с подставленными путями.

    Плейсхолдеры `@HOME@` и `@PY@` установщик заменяет при записи, поэтому
    сравнивать с сырым шаблоном нельзя: там их ещё нет. Интерпретатор берём
    тот же, каким запущены мы, — установщик подставляет `sys.executable`.
    """
    файл = уст.КОМПЛЕКТ / "settings-hooks.json"
    текст = файл.read_text(encoding="utf-8") \
        .replace("@HOME@", уст.в_шаблон(дом)).replace("@PY@", уст.в_шаблон(sys.executable))
    шаблон = json.loads(текст)
    return {в.get("command") or ""
            for блоки in (шаблон.get("hooks") or {}).values()
            for б in блоки or [] for в in б.get("hooks") or []}


def _наш_вызов(команда: str, дом: Path, уст) -> bool:
    if команда in наши_команды(дом, уст):
        return True
    # Запасной признак: имя нашего файла внутри команды. Спасает случай, когда
    # интерпретатор в настройках не тот, каким запущена опись, — путь до хука
    # при этом остаётся нашим.
    имена = {п.name for п in уст.ХУКИ_ИЗ.glob("*.py")
             if not п.name.endswith(".test.py")}
    имена |= {п.name for п in (уст.КОМПЛЕКТ / "statusline").glob("*.py")
              if not п.name.endswith(".test.py")}
    return any(и in команда for и in имена)


def сверка_хуков(дом: Path, уст) -> dict:
    """Чужие хуки против наших — по назначению, не по именам файлов.

    Возвращает материал ДЛЯ РЕШЕНИЯ, а не решение. Вердикт по каждой строке
    принимают агент с человеком: оставить оба, слить, заменить нашим, убрать
    наш, переделать. Скрипт этого решить не может — он не знает, что чужой хук
    значит для хозяина и чего тот от него ждёт.
    """
    # Признак «наш» — совпадение с ШАБЛОНОМ проводки, а не с каталогом хуков.
    # По каталогу два наших же вызова считались чужими: кран строки состояния
    # лежит в `statusline/`, а уборка `serena-hooks` — вообще чужая утилита,
    # которую вписываем мы. Опись, называющая своё чужим, заставит агента
    # спорить с хозяином о том, чего у хозяина нет.
    свои, чужие = [], []
    for в in _вызовы(дом):
        (свои if _наш_вызов(в["команда"], дом, уст) else чужие).append(в)

    пересечения = []
    for в in чужие:
        низ = в["команда"].lower()
        совпало = []
        for с in СПОСОБНОСТИ:
            по_событию = в["событие"] in с["события"]
            по_слову = any(сл in низ for сл in с["слова"])
            if not (по_событию or по_слову):
                continue
            причина = "и событие, и слово в команде" if по_событию and по_слову \
                else ("то же событие" if по_событию else "слово в команде")
            совпало.append({
                "способность": с["имя"],
                "почему": причина,
                "зачем_наша": с["зачем"],
                "наши_файлы": с["наши"],
            })
        if совпало:
            пересечения.append({"чужой": в, "пересекается_с": совпало})

    без = [в for в in чужие
           if not any(п["чужой"] is в for п in пересечения)]
    покрыто = {п["способность"] for пер in пересечения for п in пер["пересекается_с"]}
    return {
        "наших_вызовов": len(свои),
        "чужих_вызовов": len(чужие),
        "пересечения": пересечения,
        "без_пересечений": без,
        "наши_способности_под_вопросом": sorted(покрыто),
    }


