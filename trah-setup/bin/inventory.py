КЛЮЧ_ОБЁРТКИ = "claudeCode.claudeProcessWrapper"


def _без_комментариев(текст: str) -> str:
    """JSON редактора допускает `//`-комментарии, обычный разбор на них падает.

    Режем построчно и только те, что начинают строку: `//` внутри строкового
    значения (путь вида `https://…`) резать нельзя.
    """
    строки = []
    for строка in текст.splitlines():
        if строка.lstrip().startswith("//"):
            continue
        строки.append(строка)
    return "\n".join(строки)


def редакторы(дом: Path) -> list[dict]:
    """Что стоит у редактора в `claudeCode.claudeProcessWrapper`.

    Зачем это в описи. Расширение Claude Code запускает CLI САМО и слова
    `trah` не передаёт. Если настройка не указывает на переходник
    `~/.local/bin/claude-trah`, расширение поднимает сборку МИМО обёртки: без
    брифа, без своей конфигурации MCP, с потолком пачки 10 вместо 32 и с
    гардом чтения, упавшим в `warn`. Снаружи это выглядит работающим —
    измерено 30.08.2026, подагент спокойно прочитал файл проекта через `grep`.
    """
    итог = []
    for имя, путь in РЕДАКТОРЫ:
        файл = дом / путь
        if not файл.is_file():
            continue
        запись = {"редактор": имя, "файл": str(путь), "значение": None,
                  "вердикт": ""}
        try:
            д = json.loads(_без_комментариев(файл.read_text(encoding="utf-8")))
        except (json.JSONDecodeError, OSError) as e:
            запись["вердикт"] = f"настройки не разбираются: {e}"
            итог.append(запись)
            continue
        значение = д.get(КЛЮЧ_ОБЁРТКИ)
        запись["значение"] = значение
        переходник = str(дом / ".local/bin/claude-trah")
        if значение is None:
            запись["вердикт"] = ("ключа нет — расширение поднимет CLI мимо "
                                 "обёртки, без брифа и без режима")
        elif значение == переходник or значение.endswith("/claude-trah"):
            запись["вердикт"] = "указывает на переходник — верно"
        elif "/trah/" in значение:
            запись["вердикт"] = ("указывает на СБОРКУ напрямую — правки промпта "
                                 "будут, а бриф, MCP и потолок пачки нет")
        else:
            запись["вердикт"] = "указывает на что-то своё — прочитай и реши"
        итог.append(запись)
    return итог


def настройки(дом: Path) -> dict:
    """Что уже стоит в settings.json — по верхам, без содержимого."""
    путь = дом / ".claude/settings.json"
    if not путь.exists():
        return {"есть": False}
    try:
        д = json.loads(путь.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as e:
        return {"есть": True, "ошибка": str(e)}
    хуки = д.get("hooks") or {}
    return {
        "есть": True,
        "события": sorted(хуки),
        "вызовов": sum(len(з.get("hooks") or [])
                       for блок in хуки.values() for з in блок),
        "ключи": sorted(k for k in д if k not in ("hooks",)),
    }


def опись(дом: Path) -> dict:
    уст = _установщик()
    return {
        "дом": str(дом),
        "памятка": (дом / ПАМЯТКА).exists(),
        "переход": not (дом / ПАМЯТКА).exists()
        and (дом / ".claude/trah-kit-path").exists(),
        "кучи": разложить(дом, уст),
        "чужое": чужое(дом, уст),
        "настройки": настройки(дом),
        "хуки": сверка_хуков(дом, уст),
        "редакторы": редакторы(дом),
        "mcp": sorted(уст.настроенные_mcp(дом)),
        "окружение": уст.проверить_окружение(),
    }


def _строки(заголовок: str, пути: list[str], предел: int = 12) -> None:
    if not пути:
        return
    print(f"\n{заголовок} — {len(пути)}:")
    for п in пути[:предел]:
        print(f"  {п}")
    if len(пути) > предел:
        print(f"  … и ещё {len(пути) - предел}")


