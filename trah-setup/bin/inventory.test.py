#!/usr/bin/env python3
"""Проверки описи. Токенов не стоит.

Опись — единственное место, где комплект отвечает на вопрос «чьё это». Ошибка
здесь не роняет ничего и потому особенно опасна: назвал чужой файл своим —
установщик его перезапишет; назвал свой чужим — агент пойдёт спорить с
человеком о файле, которого человек в глаза не видел.

Дом для проверок собирается синтетический: чужой навык под нашим именем, чужие
хуки на тех же событиях, что и наши, и чужой хук, который ни с чем не
пересекается. Живой дом для этого не годится — он у каждого свой.
"""
import importlib.util
import json
import sys
import tempfile
from pathlib import Path

КАТАЛОГ = Path(__file__).resolve().parent
спец = importlib.util.spec_from_file_location("inventory", КАТАЛОГ / "inventory.py")
inv = importlib.util.module_from_spec(спец)
спец.loader.exec_module(inv)
уст = inv._установщик()

всего = 0
провалов = 0


def check(имя: str, условие: bool, подробность: str = "") -> None:
    global всего, провалов
    всего += 1
    if not условие:
        провалов += 1
        print(f"  ✗ {имя} {подробность}")


print("inventory.py")


def чужой_дом() -> Path:
    """Дом человека, который уже обжил Claude Code по-своему."""
    д = Path(tempfile.mkdtemp())
    (д / ".claude/hooks").mkdir(parents=True)
    (д / ".claude/skills/checkpoint").mkdir(parents=True)
    (д / ".claude/agents").mkdir(parents=True)

    # Свой навык под тем же именем, что наш.
    (д / ".claude/skills/checkpoint/SKILL.md").write_text(
        "# мой чекпоинт\n", encoding="utf-8")
    # Свой навык, которого у нас нет вовсе.
    (д / ".claude/skills/deploy").mkdir()
    (д / ".claude/skills/deploy/SKILL.md").write_text("# мой деплой\n", encoding="utf-8")
    # Свой агент.
    (д / ".claude/agents/my-reviewer.md").write_text("# мой ревьюер\n", encoding="utf-8")
    # Свои хуки: система сжатия, система журнала и звонилка ни о чём.
    (д / ".claude/hooks/autosummary.sh").write_text("#!/bin/sh\n", encoding="utf-8")
    (д / ".claude/settings.json").write_text(json.dumps({
        "hooks": {
            "PreCompact": [{"matcher": "manual", "hooks": [
                {"type": "command", "command": "/bin/sh ~/.claude/hooks/autosummary.sh"}]}],
            "Stop": [{"hooks": [
                {"type": "command", "command": "/usr/bin/python3 ~/bin/save-state.py"}]}],
            "Notification": [{"hooks": [
                {"type": "command", "command": "/usr/bin/notify-send готово"}]}],
        },
        "model": "opus",
    }, ensure_ascii=False), encoding="utf-8")
    return д


д = чужой_дом()
о = inv.опись(д)

# --- своё и чужое ------------------------------------------------------------
check("памятки нет — комплект здесь не стоял", о["памятка"] is False)
check("чужой файл под нашим именем — столкновение",
      any("skills/checkpoint" in п for п in о["кучи"]["столкновение"]),
      f"={о['кучи']['столкновение']}")
check("наши файлы, которых у хозяина нет, — новое",
      any("agents/senior-reviewer.md" in п for п in о["кучи"]["новое"]))
check("ничего не считается нашим на чистой машине",
      о["кучи"]["наше"] == [], f"={о['кучи']['наше']}")

# --- чего не тронем ----------------------------------------------------------
check("чужой навык, которого у нас нет, назван",
      any("skills/deploy" in п for п in о["чужое"].get("навыки", [])),
      f"={о['чужое'].get('навыки')}")
check("чужой агент назван",
      any("my-reviewer" in п for п in о["чужое"].get("агенты", [])))
check("чужой навык под НАШИМ именем в «не тронем» не попал",
      not any("skills/checkpoint" in п for п in о["чужое"].get("навыки", [])),
      "он в столкновениях, а не здесь")
# Чужой хук на shell — та самая система, ради которой опись и написана. Первая
# редакция глядела маской `*.py` и его не видела.
check("чужой хук не на питоне тоже назван",
      any("autosummary.sh" in п for п in о["чужое"].get("хуки", [])),
      f"={о['чужое'].get('хуки')}")

# --- сверка хуков по назначению ---------------------------------------------
х = о["хуки"]
check("наших вызовов в чужом доме нет", х["наших_вызовов"] == 0,
      f"={х['наших_вызовов']}")
check("все три чужих вызова найдены", х["чужих_вызовов"] == 3,
      f"={х['чужих_вызовов']}")

пересеклись = {п["чужой"]["команда"] for п in х["пересечения"]}
check("чужая система сжатия опознана",
      any("autosummary" in к for к in пересеклись), f"={пересеклись}")
check("чужая запись состояния опознана",
      any("save-state" in к for к in пересеклись))
check("звонилка ни с чем не пересеклась",
      any("notify-send" in в["команда"] for в in х["без_пересечений"]),
      f"={[в['команда'] for в in х['без_пересечений']]}")

имена = {с["способность"] for п in х["пересечения"] for с in п["пересекается_с"]}
check("названа наша способность «сжатие контекста»", "сжатие контекста" in имена,
      f"={имена}")
check("названа наша способность «запись состояния на диск»",
      "запись состояния на диск" in имена)
check("у каждого пересечения сказано, ПОЧЕМУ оно пересечение",
      all(с["почему"] for п in х["пересечения"] for с in п["пересекается_с"]))
check("у каждого пересечения названо, что даёт наша сторона",
      all(с["зачем_наша"] for п in х["пересечения"] for с in п["пересекается_с"]))

# --- свои вызовы не выдаются за чужие ----------------------------------------
#
# Ловушка, на которую опись попалась при первом же живом прогоне: кран строки
# состояния лежит не в `hooks/`, а в `statusline/`, и признак «имя файла из
# каталога хуков» объявлял его чужим.
наши = inv.наши_команды(д, уст)
check("шаблон проводки даёт непустой список наших команд", len(наши) >= 10,
      f"={len(наши)}")
check("кран строки состояния считается нашим",
      any("cache-tap.py" in к for к in наши), f"={[к for к in наши if 'cache' in к]}")
for к in наши:
    check_имя = "все команды шаблона опознаются как наши"
    if not inv._наш_вызов(к, д, уст):
        check(check_имя, False, f"не опознана: {к[:70]}")
        break
else:
    check("все команды шаблона опознаются как наши", True)

# --- настройки ---------------------------------------------------------------
check("чужие события проводки перечислены",
      set(о["настройки"]["события"]) == {"PreCompact", "Stop", "Notification"},
      f"={о['настройки']['события']}")
check("чужие ключи верхнего уровня названы", "model" in о["настройки"]["ключи"])

# --- переход: комплект стоял до появления памятки ----------------------------
#
# Найдено живым прогоном 08.09.2026 на машине автора комплекта. Правило «чужое
# не трогаем» без этого перехода ломало ОБНОВЛЕНИЕ: файл комплекта, ушедший
# вперёд в репозитории, памятки не имеет — и объявлялся чужим. Признак того,
# что комплект тут стоял, — метка `~/.claude/trah-kit-path`, её пишет только
# установщик.
def дом_после_старой_установки() -> Path:
    д = Path(tempfile.mkdtemp())
    (д / ".claude/hooks").mkdir(parents=True)
    (д / ".claude/trah-kit-path").write_text("/куда-то\n", encoding="utf-8")
    # Наш хук, но содержимое разошлось: репозиторий ушёл вперёд.
    (д / ".claude/hooks/checkpoint.py").write_text("# старая редакция\n",
                                                   encoding="utf-8")
    # Наши же копии рядом — они не вещь хозяина.
    (д / ".claude/hooks/checkpoint.py.bak-20260101-000000").write_text(
        "# ещё старее\n", encoding="utf-8")
    return д


д2 = дом_после_старой_установки()
о2 = inv.опись(д2)
check("метка о прежней установке опознана", о2["переход"] is True)
check("наш файл с разошедшимся содержимым — ПРАВЛЕНО, а не столкновение",
      any("hooks/checkpoint.py" in п for п in о2["кучи"]["правлено"]),
      f"правлено={о2['кучи']['правлено']}, столкновения={о2['кучи']['столкновение']}")
check("столкновений при переходе нет вовсе", о2["кучи"]["столкновение"] == [],
      f"={о2['кучи']['столкновение']}")
check("наши резервные копии не считаются вещами хозяина",
      not any(".bak-" in п for п in о2["чужое"].get("хуки", [])),
      f"={о2['чужое'].get('хуки')}")

# Без метки тот же дом читается иначе: комплект тут не стоял.
(д2 / ".claude/trah-kit-path").unlink()
о3 = inv.опись(д2)
check("без метки тот же файл становится столкновением",
      any("hooks/checkpoint.py" in п for п in о3["кучи"]["столкновение"]),
      f"={о3['кучи']['столкновение']}")

# --- редактор: расширение мимо обёртки ---------------------------------------
#
# Ключа нет — расширение поднимает CLI мимо обёртки, и снаружи это выглядит
# работающим. Измерено 30.08.2026: подагент спокойно прочитал файл проекта
# через `grep`, хотя гард чтения должен был отбить.
def дом_с_редактором(значение, комментарий: bool = False) -> Path:
    д = Path(tempfile.mkdtemp())
    (д / ".config/Code/User").mkdir(parents=True)
    тело = {"editor.fontSize": 13}
    if значение is not None:
        тело["claudeCode.claudeProcessWrapper"] = значение
    текст = json.dumps(тело, ensure_ascii=False, indent=2)
    if комментарий:
        текст = "// мои настройки\n" + текст
    (д / ".config/Code/User/settings.json").write_text(текст, encoding="utf-8")
    return д


случаи = [
    (None, "ключа нет"),
    ("~/.local/bin/claude-trah", "переходник"),
    ("/home/x/.local/share/claude/trah/current", "СБОРКУ напрямую"),
    ("/usr/bin/my-own-launcher", "что-то своё"),
]
for значение, ждём in случаи:
    р = inv.редакторы(дом_с_редактором(значение))
    check(f"вердикт для {значение!r}", len(р) == 1 and ждём in р[0]["вердикт"],
          f"={[x['вердикт'] for x in р]}")

check("комментарии в настройках редактора не роняют разбор",
      inv.редакторы(дом_с_редактором("/x/claude-trah", комментарий=True))[0]
      ["значение"] == "/x/claude-trah")
check("без файла настроек редактор не выдумывается",
      inv.редакторы(Path(tempfile.mkdtemp())) == [])

# --- опись ничего не пишет ---------------------------------------------------
до = {p for p in д.rglob("*")}
inv.опись(д)
check("опись не создаёт и не удаляет файлов", {p for p in д.rglob("*")} == до)

print(f"  {всего - провалов}/{всего} проверок прошло")
sys.exit(1 if провалов else 0)
