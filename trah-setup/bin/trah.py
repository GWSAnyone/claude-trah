# ─────────────────────────────────────────────────────────── куски доктрины ──
def прочитать_куски() -> list[dict]:
    """Куски с заголовком-JSON между `---`.

    YAML не берём намеренно: pyyaml в системе нет, а свой разбор YAML — это
    источник тихих ошибок ровно там, где ошибка означает промах патча.

    Маршрута ровно два, и выбирать между ними не приходится — маршрут диктует
    сам кусок. Есть `edits` — значит в штатном промпте есть что подменить, и
    кусок уезжает в бинарник, на своё место по якорю. Нет `edits` — подменять
    нечего, текст целиком наш, и уезжает он брифом. Третий маршрут `either`
    убран 07.09.2026: код обрабатывал его наравне с `binary`, в бриф он не
    попадал никогда (там требуется `scope`, а у `either` его не было), то есть
    выбор существовал только на бумаге и путал читателя.

    Несоответствие — не предупреждение, а остановка. Кусок, заявивший `brief`
    и написавший `edits`, сегодня молча терял бы правки; кусок, заявивший
    `binary` без `edits`, не доехал бы никуда вовсе.

    У вычисляемого куска (`"computed": true`) тело в файле — только объяснение,
    зачем он нужен; настоящее собирает служба и кладёт в
    `~/.claude/fragments/computed/<id>.md`. Комплект от службы не зависит:
    файла нет — кусок просто выпадает из сборки. Подставить вместо него
    объяснение было бы хуже пропуска: в промпт уехал бы текст про то, что
    фактов нет, вместо самих фактов.
    """
    куски = []
    for путь in sorted(КУСКИ.glob("*.md")):
        if путь.name == "README.md":
            continue
        текст = путь.read_text(encoding="utf-8")
        m = re.match(r"^---\n(.*?)\n---\n?(.*)$", текст, re.S)
        if not m:
            raise SystemExit(f"{путь.name}: нет заголовка между --- и ---")
        try:
            заголовок = json.loads(m.group(1))
        except json.JSONDecodeError as e:
            raise SystemExit(f"{путь.name}: заголовок не разбирается как JSON — {e}")
        маршрут = заголовок.get("route")
        есть_правки = bool(заголовок.get("edits"))
        if маршрут not in ("binary", "brief"):
            raise SystemExit(f"{путь.name}: route должен быть binary или brief, "
                             f"а не {маршрут!r}")
        if маршрут == "binary" and not есть_правки:
            raise SystemExit(f"{путь.name}: маршрут binary без edits — "
                             f"подменять в бинарнике нечего")
        if маршрут == "brief":
            if есть_правки:
                raise SystemExit(f"{путь.name}: маршрут brief с edits — "
                                 f"правки не уедут никуда, выбери одно")
            if not заголовок.get("scope"):
                raise SystemExit(f"{путь.name}: маршрут brief без scope — "
                                 f"кусок выпадет из сборки брифа молча")
        тело = m.group(2).strip("\n")
        if заголовок.get("computed"):
            собрано = ВЫЧИСЛЕННЫЕ / (заголовок["id"] + ".md")
            if not собрано.exists():
                continue
            тело = собрано.read_text(encoding="utf-8").strip("\n")
            if not тело.strip():
                continue
        заголовок["тело"] = тело
        заголовок["файл"] = путь.name
        куски.append(заголовок)
    return куски


def собрать_скрипт(куски: list[dict], только_сверка: bool = False) -> str:
    """Скрипт правок для tweakcc adhoc-patch.

    Работает по РАСПАКОВАННОЙ JS-области: копии текста в области байткода bun
    скрипту не видны, и это удача — там длина строки закодирована, удлинять её
    нельзя.

    Каждая правка обязана совпасть ровно указанное число раз. Это главный
    сторож: tweakcc на нашем бинарнике рапортовал «applied successfully»,
    промахнувшись двумя кусками из четырёх, а один и тот же пункт лежал в
    исходнике двумя копиями, и патч одной оставлял вторую живой.

    ДВЕ ФОРМЫ ЗАПИСИ. Не-ASCII в исходнике встречается и живым символом, и
    экранированным `\\uXXXX` — зависит от того, как собиралась конкретная
    строка. Якорь с длинным тире, найденный в самом бинарнике, в распакованном
    JS может выглядеть как `don't gold-plate\\u2014but`. Поэтому для каждой
    правки готовим обе формы, скрипт берёт ту, что совпала, и подставляет текст
    в той же форме: смешать их — значит вписать живой символ туда, где вся
    строка экранирована.
    """
    правки = []
    for к in куски:
        if к.get("route") != "binary":
            continue
        for e in к.get("edits", []):
            якорь = e["anchor"]
            чем = якорь + "\n" + к["тело"] if e["op"] == "insert_after" else e["with"]
            # Обратная кавычка и `${` в НАШЕМ тексте ломают сборку: часть
            # описаний лежит в бинаре внутри JS-шаблонных строк, где кавычка
            # закрывает строку, а `${` начинает подстановку. Копия после такой
            # правки не запускается вовсе — 26.08.2026 сборка отбилась
            # «SyntaxError: Unexpected identifier 'grep'», и понять по этому
            # сообщению, какой кусок виноват, нельзя. Поэтому называем виновника
            # по имени здесь.
            #
            # ЯКОРЬ ИЗ ПРОВЕРКИ ИСКЛЮЧЁН, и это не послабление. Якорь — дословный
            # кусок оригинала: он уже лежит в бинаре в форме, которая там
            # законна, и возвращается на то же место как был. Проверять его
            # значит отбивать давно работающие куски: у `tool-edit-single-
            # replacement` якорь содержит кавычки с самого начала и собирался
            # годами. Проверяем ровно то, что пишет автор куска.
            наше = к["тело"] if e["op"] == "insert_after" else e.get("with", "")
            for знак, чем_плох in (("`", "закрывает шаблонную строку"),
                                   ("${", "подстановка в шаблонной строке")):
                if знак in наше:
                    raise SystemExit(
                        f"кусок «{к['id']}»: в тексте замены есть {знак!r} — "
                        f"{чем_плох}. Уберите: собранная копия не запустится.")
            правки.append(
                {
                    "id": к["id"],
                    "anchor": якорь,
                    "anchorEsc": экранировать(якорь),
                    "count": e["count"],
                    # Подставляемый текст ВСЕГДА экранирован. Якорь — дело
                    # другое, его форму диктует исходник, поэтому для него
                    # готовятся обе. А вот живой не-ASCII символ, вписанный в
                    # исходник, доезжает до модели покалеченным: 22.08.2026
                    # длинное тире приехало как «â» — байты E2 80 94,
                    # прочитанные как latin-1. `\\uXXXX` понимается любым видом
                    # строкового литерала и через побайтовую обработку проходит
                    # без потерь.
                    "with": однострочно(экранировать(чем)),
                }
            )
    # Параметр скрипта называется `js`, а не `code`: комментарий в
    # src/commands.ts:172 устарел, настоящий вызов — new Function('js','vars',…)
    # на строке 209. Печатать из скрипта нельзя: stdout это канал передачи
    # результата, обёртка ждёт там ровно JSON.
    # ВСЕ несошедшиеся якоря собираются и называются РАЗОМ. Прежняя редакция
    # роняла сборку на первом же промахе, и обновление версии превращалось в
    # перебор: починил один якорь — пересобрал — узнал про следующий. На 2.1.251
    # промахов было три, и узнавать их по одному стоило трёх полных сборок.
    #
    # В режиме сверки (`trah.py check`) скрипт НИЧЕГО не подставляет и всегда
    # бросает отчёт: у `adhoc-patch` stdout занят результатом, и единственный
    # канал наружу — исключение.
    return (
        "const EDITS = " + json.dumps(правки, ensure_ascii=False) + ";\n"
        "const СВЕРКА = " + ("true" if только_сверка else "false") + ";\n"
        "const счёт = (s, a) => s.split(a).length - 1;\n"
        "let out = js;\n"
        "const отчёт = [], беды = [];\n"
        "for (const e of EDITS) {\n"
        "  const прямо = счёт(out, e.anchor);\n"
        "  const экран = e.anchorEsc === e.anchor ? 0 : счёт(out, e.anchorEsc);\n"
        "  const [якорь, n] = прямо >= экран ? [e.anchor, прямо] : [e.anchorEsc, экран];\n"
        "  отчёт.push({id: e.id, ждём: e.count, прямо: прямо, экран: экран});\n"
        "  if (n !== e.count) {\n"
        "    беды.push('кусок ' + e.id + ': якорь найден ' + n +\n"
        "      ' раз (прямо ' + прямо + ', экранированный ' + экран +\n"
        "      '), ожидалось ' + e.count);\n"
        "    continue;\n"
        "  }\n"
        "  if (!СВЕРКА) out = out.split(якорь).join(e.with);\n"
        "}\n"
        "if (СВЕРКА) throw new Error('ОТЧЁТ' + JSON.stringify(отчёт));\n"
        "if (беды.length) throw new Error('якорей не сошлось: ' + беды.length +\n"
        "  '\\n' + беды.join('\\n') +\n"
        "  '\\nТекст в бинарнике изменился — правки переписать, "
        "а не применять вслепую.');\n"
        "return out;\n"
    )


def экранировать(текст: str) -> str:
    """Не-ASCII в форме `\\uXXXX`, как это записано в исходнике Claude Code."""
    return "".join(с if ord(с) < 128 else f"\\u{ord(с):04x}" for с in текст)


def однострочно(текст: str) -> str:
    """Переводы строк — escape-последовательностью, а не живым символом.

    ПОЧЕМУ. Строки промптов лежат в исходнике в трёх видах: шаблонные с
    обратными кавычками, одинарные и двойные. В шаблонной живой перевод строки
    допустим, в остальных двух он рвёт литерал, и бинарник перестаёт
    запускаться — `SyntaxError: Unexpected EOF`. Проверено 22.08.2026 на
    промпте общего подагента: он записан двойными кавычками.

    `\\n` работает во всех трёх видах одинаково, поэтому вставляем только его и
    не гадаем, в какой литерал попали. Обратные слэши НЕ трогаем: в якорях уже
    есть `\\``, и экранирование их сломало бы.
    """
    return текст.replace("\n", "\\n")


def записан_ли(копия: Path, кусок: dict) -> bool:
    """Есть ли текст куска в собранном файле — фактом, а не выводом из маршрута.

    Счётчик якорей ловит промах ПО ВХОДУ: якорь не найден — сборка падает. Эта
    проверка смотрит с другой стороны, по выходу: текст действительно лежит в
    файле. Дешёвая страховка от случая, когда подстановка прошла, но текст
    попал не туда, куда мы думали.

    Ищем по первым словам полезной нагрузки, в обеих формах записи — не-ASCII
    в исходнике встречается и живым символом, и как `\\uXXXX`.
    """
    if кусок.get("route") != "binary":
        return False
    данные = копия.read_bytes()
    for e in кусок.get("edits", []):
        нагрузка = кусок["тело"] if e["op"] == "insert_after" else e["with"]
        проба_ = нагрузка.strip().split("\n")[0][:60]
        if not проба_:
            continue
        формы = {проба_, экранировать(проба_)}
        if not any(ф.encode("utf-8") in данные for ф in формы):
            return False
    return True


# ─────────────────────────────────────────────────────────────────── сборка ──
def целевая_версия() -> str:
    """Версия, на которую нацелен комплект. Объявлена явно, одна на всех.

    До 29.08.2026 версия по умолчанию бралась как САМАЯ СВЕЖАЯ в `versions/`.
    Это тихий прицел: приезжает обновление, рядом ложится новый файл, и `build`
    без номера начинает целиться в него — с якорями от прежней версии. Так
    установка в день выхода 2.1.251 встала на неё и упала на первом же
    несошедшемся якоре, а звучало это как поломка комплекта.

    Прицел меняется только командой `upgrade`, и только после того, как сухая
    сверка, сборка, проверка доставки и все наборы проверок прошли.
    """
    if not ПИН.exists():
        raise SystemExit(f"нет файла прицела {ПИН}: впишите в него номер версии")
    версия = ПИН.read_text(encoding="utf-8").strip()
    if not версия:
        raise SystemExit(f"{ПИН} пуст: впишите номер версии")
    return версия


def пути(версия: str | None) -> tuple[str, Path, Path, Path, Path]:
    версия = версия or целевая_версия()
    return (
        версия,
        ДОЛЯ / "versions" / версия,
        ДОЛЯ / "trah" / версия,
        ДОЛЯ / "trah" / f"{версия}.origin.sha256",
        ДОЛЯ / "trah" / f"{версия}.manifest.json",
    )


def сумма(путь: Path) -> str:
    return subprocess.run(
        ["sha256sum", str(путь)], capture_output=True, text=True, check=True
    ).stdout.split()[0]


def build(версия: str | None) -> int:
    версия, оригинал, копия, файл_суммы, файл_манифеста = пути(версия)
    if not оригинал.exists():
        print(f"нет оригинала: {оригинал}", file=sys.stderr)
        return 1
    if not (TWEAKCC / "dist/index.mjs").exists():
        print(f"tweakcc не собран: {TWEAKCC}/dist/index.mjs", file=sys.stderr)
        print("  pnpm install --ignore-scripts && pnpm run build:dev", file=sys.stderr)
        return 1

    копия.parent.mkdir(parents=True, exist_ok=True)
    БЛОКНОТ.mkdir(parents=True, exist_ok=True)

    # Сторож №3: целостность оригинала. Сумма снимается один раз и сверяется
    # перед каждой сборкой. Изменился — значит приехало обновление под тем же
    # номером или в штатный файл кто-то писал, и прошлые патчи к нему уже не
    # относятся.
    текущая = сумма(оригинал)
    if файл_суммы.exists():
        было = файл_суммы.read_text().split()[0]
        if было != текущая:
            print("ОРИГИНАЛ ИЗМЕНИЛСЯ с прошлой сборки — останавливаюсь.", file=sys.stderr)
            print(f"  было  {было}\n  стало {текущая}", file=sys.stderr)
            print(f"Разобраться, что приехало, затем: rm {файл_суммы}", file=sys.stderr)
            return 1
    else:
        файл_суммы.write_text(f"{текущая}  {оригинал}\n")
        print(f"сумма оригинала снята: {текущая[:16]}…")

    # Каждая сборка начинается с чистой копии: иначе правки наложились бы сами
    # на себя, и счётчик якорей поймал бы это уже поздно.
    # Удалить, а не перезаписать: tweakcc снимает с копии право записи, и
    # copyfile поверх такого файла падает с Errno 13.
    копия.unlink(missing_ok=True)
    shutil.copyfile(оригинал, копия)
    копия.chmod(0o755)

    куски = прочитать_куски()
    для_бинарника = [к for к in куски if к.get("route") == "binary"]
    print(f"кусков: {len(куски)}, в бинарник идёт {len(для_бинарника)}")

    # Шаг 1: метка режима. Единственное, что берём из корпуса tweakcc — сам
    # корпус из критического пути убран, потому что он рапортует успех при
    # промахе. Строгий список нужен, чтобы `--apply` не притащил ВСЕ настройки
    # по умолчанию из ~/.tweakcc/config.json.
    # `--yes` здесь НЕТ: форк его выкинул — у него `--apply` и так не спрашивает
    # («apply saved customizations without interactive UI»), а лишний флаг валит
    # разбор на `error: unknown option '--yes'`. Вернёшься на апстрим через
    # TWEAKCC_DIR — флаг придётся вернуть сюда же.
    выполнить(
        ["node", str(TWEAKCC / "dist/index.mjs"), "--apply",
         "--patches", "patches-applied-indication"],
        окружение={"TWEAKCC_CC_INSTALLATION_PATH": str(копия)},
    )

    # Шаг 2: наши правки. Идут ПОСЛЕ `--apply`: он восстанавливает из бэкапа и
    # стёр бы их. Песочница скрипта не работает на Node 26 — tweakcc знает
    # флаги Node 20–24, а там они снова переименованы; скрипт свой.
    скрипт = БЛОКНОТ / "edits.js"
    скрипт.write_text(собрать_скрипт(куски), encoding="utf-8")
    выполнить(
        ["node", str(TWEAKCC / "dist/index.mjs"), "adhoc-patch",
         "--script", f"@{скрипт}", "-p", str(копия),
         "--confirm-possible-dangerous-patch", "--dangerous-no-script-sandbox"],
    )

    if сумма(оригинал) != текущая:
        print("ОРИГИНАЛ ПОСТРАДАЛ ВО ВРЕМЯ СБОРКИ — разбираться немедленно.", file=sys.stderr)
        return 1

    манифест = {
        "версия": версия,
        "собрано": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "сумма_оригинала": текущая,
        "куски": {
            к["id"]: {
                "маршрут": к.get("route"),
                "файл": к["файл"],
                "записан": записан_ли(копия, к),
                # Проверка доставки — отдельный прогон: записано не значит
                # доставлено, и вычитать из брифа можно только по доставке.
                "доставлен": "не проверялось",
            }
            # Только куски бинарника: манифест — запись о ДОСТАВКЕ в копию.
            # Кускам брифа доставлять нечего, а строки «записан: false» рядом с
            # настоящими промахами читаются как поломка и прячут её.
            for к in для_бинарника
        },
    }
    # Манифест пишется ТОЛЬКО после дымового запуска: манифест несобравшейся
    # сборки — это ложное разрешение вычитать куски из брифа.
    # Сторож №1: метка режима — и одновременно дымовой запуск. Патч может
    # порвать синтаксис исходника (живой перевод строки внутри литерала в
    # двойных кавычках рвёт его гарантированно), и тогда бинарник не стартует
    # вовсе. Раньше сборка этого не замечала и рапортовала успех поверх
    # `SyntaxError: Unexpected EOF`.
    р = subprocess.run([str(копия), "--version"], capture_output=True, text=True)
    if р.returncode != 0 or "Claude Code" not in р.stdout:
        print("СОБРАННАЯ КОПИЯ НЕ ЗАПУСКАЕТСЯ — сборка не удалась.", file=sys.stderr)
        sys.stderr.write(р.stdout + р.stderr)
        копия.unlink(missing_ok=True)
        файл_манифеста.unlink(missing_ok=True)
        return 1
    if "tweakcc" not in р.stdout:
        print("метки режима нет в --version: патч метки не применился", file=sys.stderr)
        return 1

    файл_манифеста.write_text(
        json.dumps(манифест, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    # Устойчивая ссылка на последнюю собранную копию. По ней сборку находит
    # обёртка (`bin/claude`, ветка слова `trah`) и всё, что зовёт режим из
    # настроек, а не руками: путь с номером версии протух бы на первом же
    # обновлении Claude Code, а этот — нет.
    ссылка = копия.parent / "current"
    ссылка.unlink(missing_ok=True)
    ссылка.symlink_to(копия.name)

    print(f"оригинал цел, копия собрана: {копия}")
    print(f"ссылка:   {ссылка} → {копия.name}")
    print(f"манифест: {файл_манифеста}")
    print(р.stdout.strip())
    return 0


def выполнить(команда: list[str], окружение: dict | None = None) -> None:
    среда = {**os.environ, **(окружение or {})}
    р = subprocess.run(команда, env=среда, capture_output=True, text=True)
    if р.returncode != 0:
        sys.stdout.write(р.stdout)
        sys.stderr.write(р.stderr)
        raise SystemExit(f"шаг сборки не прошёл: {' '.join(команда[:3])}…")


def check(версия: str | None) -> int:
    """Сухая сверка якорей с версией: что сломается при сборке, СПИСКОМ.

    Зачем отдельно от `build`. Обновление Claude Code сдвигает минифицированные
    имена, и часть якорей перестаёт совпадать. Узнавать об этом сборкой дорого
    вдвойне: она пишет копию, снимает сумму оригинала и трогает ссылку
    `current`, а падает всё равно на разборе якорей. Сверка не пишет НИЧЕГО —
    ни копии, ни манифеста, ни суммы, — и называет все промахи разом.

    Считается по РАСПАКОВАННОЙ JS-области, тем же путём, что и сборка. Побайтовый
    счёт по самому файлу версии для этого не годится: в бинарнике рядом лежит
    область байткода со своими копиями строк, и число там своё. Проверено
    29.08.2026 на 2.1.251: побайтово «промахнулись» 21 якорь из 26, из них
    настоящих — три.
    """
    версия, оригинал, _, _, _ = пути(версия)
    if not оригинал.exists():
        print(f"нет оригинала: {оригинал}", file=sys.stderr)
        return 1
    if not (TWEAKCC / "dist/index.mjs").exists():
        print(f"tweakcc не собран: {TWEAKCC}/dist/index.mjs", file=sys.stderr)
        return 1

    БЛОКНОТ.mkdir(parents=True, exist_ok=True)
    # Черновая копия: `adhoc-patch` правит файл на месте, а штатный файл версии
    # не открывается на запись НИКОГДА. Скрипт сверки всё равно бросает
    # исключение, так что записи не случится и в неё, — но полагаться на это
    # значит ставить главное правило в зависимость от чужого кода.
    черновик = БЛОКНОТ / f"сверка-{версия}"
    черновик.unlink(missing_ok=True)
    shutil.copyfile(оригинал, черновик)
    черновик.chmod(0o755)

    скрипт = БЛОКНОТ / "check.js"
    скрипт.write_text(собрать_скрипт(прочитать_куски(), только_сверка=True),
                      encoding="utf-8")
    р = subprocess.run(
        ["node", str(TWEAKCC / "dist/index.mjs"), "adhoc-patch",
         "--script", f"@{скрипт}", "-p", str(черновик),
         "--confirm-possible-dangerous-patch", "--dangerous-no-script-sandbox"],
        capture_output=True, text=True,
    )
    черновик.unlink(missing_ok=True)

    поток = р.stdout + р.stderr
    метка = поток.find("ОТЧЁТ")
    if метка < 0:
        print("сверка не дала отчёта — разбираться со сборщиком:", file=sys.stderr)
        sys.stderr.write(поток)
        return 2
    хвост = поток[метка + len("ОТЧЁТ"):]
    отчёт = json.JSONDecoder().raw_decode(хвост.lstrip())[0]

    print(f"{версия}: якорей {len(отчёт)}")
    плохо = 0
    for з in отчёт:
        нашлось = max(з["прямо"], з["экран"])
        if нашлось == з["ждём"]:
            print(f"  ✓  {з['id']}")
        else:
            плохо += 1
            print(f"  ✗  {з['id']}: найден {нашлось} раз, ждём {з['ждём']}"
                  f"  (прямо {з['прямо']}, экранированный {з['экран']})")
    if плохо:
        print(f"\nне сошлось якорей: {плохо}. Переписать их под {версия} —"
              f" и только потом собирать.", file=sys.stderr)
    return 1 if плохо else 0


def проверки() -> int:
    """Все наборы проверок, одним прогоном и с общим приговором.

    Ищутся в двух местах: в самом комплекте и в мастерской `dev/` рядом с ним.
    Мастерская не ставится на машину, но её инструменты ломаются так же тихо,
    как всё остальное, — и проверяются вместе со всем остальным.
    """
    корень = Path(__file__).resolve().parent.parent
    наборы = sorted(корень.glob("*/*.test.py"))
    наборы += sorted((корень.parent / "dev").glob("*.test.py"))
    плохо = []
    for набор in наборы:
        р = subprocess.run([sys.executable, str(набор)],
                           capture_output=True, text=True)
        имя = f"{набор.parent.name}/{набор.name}"
        # Набор может отчитаться нулём и при этом напечатать провалы: часть из
        # них считает провалы сама и выходит кодом, часть — только печатает.
        сорвалось = р.returncode != 0 or "✗" in р.stdout
        print(f"  {'✗' if сорвалось else '✓'}  {имя}")
        if сорвалось:
            плохо.append(имя)
            sys.stdout.write(р.stdout[-2000:])
            sys.stderr.write(р.stderr[-2000:])
    print(f"\nнаборов {len(наборы)}, сорвалось {len(плохо)}")
    for имя in плохо:
        print(f"  ✗ {имя}")
    return 1 if плохо else 0


def upgrade(версия: str | None) -> int:
    """Переезд на новую версию целиком, без «а это я забыл».

    Порядок неслучаен и каждый шаг отбивает свою беду:

        сверка   — якоря под новой версией, ВСЕ промахи разом и без записи;
        сборка   — копия и манифест, с дымовым запуском внутри;
        доставка — пробы: записано не значит доехало;
        проверки — все наборы комплекта: правка сборщика могла сломать соседа;
        прицел   — version.txt переписывается ПОСЛЕДНИМ.

    Прицел последним потому, что он и есть выключатель: пока в нём старый
    номер, `deploy` и `build` без аргумента продолжают работать с прежней,
    рабочей копией. Сорвался любой шаг — переезда не было вовсе.
    """
    if not версия:
        print("upgrade требует номер версии: trah.py upgrade 2.1.251",
              file=sys.stderr)
        return 2
    прежняя = целевая_версия() if ПИН.exists() else "—"
    print(f"переезд {прежняя} → {версия}\n\n[1/5] сверка якорей")
    if check(версия):
        return 1
    print("\n[2/5] сборка")
    if build(версия):
        return 1
    print("\n[3/5] доставка")
    if verify(версия):
        return 1
    print("\n[4/5] наборы проверок")
    if проверки():
        return 1
    print("\n[5/5] прицел")
    ПИН.write_text(версия + "\n", encoding="utf-8")
    print(f"{ПИН.name}: {прежняя} → {версия}")
    print("Копия собрана и указатель переставлен — осталось перезапустить сессии.")
    return 0


# ──────────────────────────────────────────────────────── проверка доставки ──
def verify(версия: str | None) -> int:
    """Что реально уехало в поле `tools`, а не что записано в файл.

    Это единственная проверка, закрывающая дыру tweakcc: он проверяет запись,
    но не доставку. Пробы идут в ловушку и не стоят токенов.

    Промпты подагентов так проверить нельзя: подагент запускается уже после
    ответа модели, а ловушка ответа не даёт. Для них честный предел — запись.
    """
    версия, _, копия, _, файл_манифеста = пути(версия)
    if not файл_манифеста.exists():
        print("манифеста нет, сначала build", file=sys.stderr)
        return 1
    манифест = json.loads(файл_манифеста.read_text())
    куски = {к["id"]: к for к in прочитать_куски()}

    режимы = sorted(
        {м for к in куски.values() for м in (к.get("verify") or {}).get("modes", [])}
    )
    поймано: dict[str, dict[str, str]] = {}
    for режим in режимы:
        поймано[режим] = проба(копия, режим)

    плохо = 0

    # Сторож кодировки. Живой не-ASCII символ, вписанный в исходник, доезжает
    # до модели покалеченным: 22.08.2026 длинное тире приехало как «â» — байты
    # E2 80 94, прочитанные как latin-1. Ловим по классическим следам такой
    # порчи; молча это не заметишь, потому что текст на месте и читается.
    СЛЕДЫ_ПОРЧИ = ("â€", "Ð", "Ã©", "â", "â ")
    for режим, тексты_ in поймано.items():
        for где_, текст_ in тексты_.items():
            if any(след in текст_ for след in СЛЕДЫ_ПОРЧИ):
                плохо += 1
                print(f"  ✗  КОДИРОВКА: {где_} в режиме {режим} приехал покалеченным")

    for id_, состояние in манифест["куски"].items():
        проверка = (куски.get(id_) or {}).get("verify")
        if not проверка:
            # Пробой не проверяются те, чей текст подаётся не в первом запросе:
            # промпты подагентов (подагент запускается после ответа модели),
            # промпт сжатия (сжатие случается посреди сессии) и сообщение
            # режима (приезжает системным сообщением живой сессии). Их предел —
            # проверка записи, и из брифа они не вычитаются: route=binary.
            состояние["доставлен"] = "проверить пробой нельзя"
            print(f"  ·  {id_}: пробой не проверяется, предел — запись")
            continue
        # Куда смотреть: в описание инструмента или в системный промпт.
        где = "система" if проверка.get("where") == "system" else проверка["tool"]
        нашлось = any(
            проверка["marker"] in поймано.get(м, {}).get(где, "")
            for м in проверка["modes"]
        )
        отсутствует_инструмент = all(
            где not in поймано.get(м, {}) for м in проверка["modes"]
        )
        if нашлось:
            состояние["доставлен"] = "проверено"
            print(f"  ✓  {id_}: доставлено ({где})")
        elif отсутствует_инструмент:
            состояние["доставлен"] = "инструмента не было в пробе"
            print(f"  ?  {id_}: {где} — в пробе такого нет")
        else:
            состояние["доставлен"] = "НЕ доставлено"
            плохо += 1
            print(f"  ✗  {id_}: НЕ доставлено — из брифа вычитать нельзя")

    файл_манифеста.write_text(
        json.dumps(манифест, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return 1 if плохо else 0


def проба(копия: Path, режим: str) -> dict[str, str]:
    """Один запуск в ловушку, возвращает описания инструментов.

    ENABLE_TOOL_SEARCH=1 обязателен: ANTHROPIC_BASE_URL сам по себе выключает
    отложенную загрузку описаний, и без этой переменной проба показала бы не
    то, что бывает в обычной работе.
    """
    БЛОКНОТ.mkdir(parents=True, exist_ok=True)
    улов = БЛОКНОТ / f"probe-{режим}.jsonl"
    улов.write_text("")
    ловушка = subprocess.Popen(
        [sys.executable, str(Path(__file__).resolve().parent / "sink.py"),
         str(ПОРТ_ПРОБЫ), str(улов)],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True,
    )
    try:
        time.sleep(1)
        subprocess.run(
            [str(копия), "--model", "claude-opus-5", "--permission-mode", режим,
             "--print", "2+2"],
            env={**os.environ, "ENABLE_TOOL_SEARCH": "1",
                 "ANTHROPIC_BASE_URL": f"http://127.0.0.1:{ПОРТ_ПРОБЫ}"},
            capture_output=True, text=True, timeout=180,
        )
    except subprocess.TimeoutExpired:
        pass
    finally:
        ловушка.terminate()
        ловушка.wait(timeout=10)

    # Ключ «системный промпт» стоит рядом с именами инструментов намеренно: для
    # проверки это такой же текст, уехавший к модели, и куску всё равно, в
    # каком поле запроса он оказался.
    описания: dict[str, str] = {}
    for строка in улов.read_text().splitlines():
        if not строка.strip():
            continue
        тело = json.loads(строка)["body"]
        for t in тело.get("tools") or []:
            описания[t["name"]] = t.get("description", "")
        система = тело.get("system")
        if isinstance(система, list):
            описания["система"] = "\n".join(
                б.get("text", "") for б in система if isinstance(б, dict)
            )
        elif isinstance(система, str):
            описания["система"] = система
    return описания


def status(версия: str | None) -> int:
    версия, оригинал, копия, файл_суммы, файл_манифеста = пути(версия)
    print(f"версия:   {версия}")
    print(f"оригинал: {оригинал} ({'цел' if файл_суммы.exists() and сумма(оригинал) == файл_суммы.read_text().split()[0] else 'сумма не снята или разошлась'})")
    print(f"копия:    {копия} ({'есть' if копия.exists() else 'нет'})")
    if файл_манифеста.exists():
        м = json.loads(файл_манифеста.read_text())
        print(f"собрано:  {м['собрано']}")
        for id_, с in м["куски"].items():
            print(f"  {id_:<28} {с['маршрут']:<7} доставка: {с['доставлен']}")
    else:
        print("манифеста нет")
    return 0


# ── бриф ─────────────────────────────────────────────────────────────────────
#
# Бриф собирается из кусков маршрута `brief` — тех, что раньше лежали двумя
# сплошными файлами (~/.claude/brief.md и <проект>/.claude/brief.md). Смысл
# раскроя не в экономии: сплошной файл нечем переопределять посекционно, а
# уклад в таусозавре должен уметь снять один модуль и оставить остальные.
#
# ВЫЧИТАНИЕ. Кусок брифа уходит из сборки только если ВСЕ куски, названные в
# его `covered_by`, доставлены в бинарник и доставка ПРОВЕРЕНА пробой. Промах
# патча означает, что кусок остаётся в брифе: режим деградирует до обычного
# поведения, а не до потери правила. Поэтому же вычитание никогда не делается
# для штатного бинарника — там не доставлено ничего.
def собрать_бриф(область: str, урезать: bool, версия: str | None = None,
                без_личного: bool = False) -> str:
    куски = [к for к in прочитать_куски()
             if к.get("route") == "brief" and к.get("scope") == область
             and not (без_личного and к.get("personal"))]
    куски.sort(key=lambda к: к.get("order", 0))
    if not куски:
        raise SystemExit(f"кусков брифа для области «{область}» нет")

    доставлено: dict[str, str] = {}
    if урезать:
        _, _, _, _, файл_манифеста = пути(версия)
        if файл_манифеста.exists():
            м = json.loads(файл_манифеста.read_text())
            доставлено = {id_: с["доставлен"] for id_, с in м["куски"].items()}

    вышло = []
    for к in куски:
        покрыт = к.get("covered_by") or []
        if урезать and покрыт and all(доставлено.get(c) == "проверено" for c in покрыт):
            continue
        разделитель = "\n" if к.get("kind") == "bullet" else "\n\n"
        вышло.append((разделитель, к["тело"]))

    if not вышло:
        return ""
    текст = вышло[0][1]
    for разделитель, тело in вышло[1:]:
        текст += разделитель + тело
    return текст + "\n"


# Куда ложится собранный бриф каждой области.
#
# Собранный бриф — СБОРНЫЙ файл. Правится кусок, а не файл: правка файла
# напрямую переживёт ровно до следующей пересборки, и молча. Расхождение ловит
# `bin/trah.test.py`, он собирает брифы заново и сверяет побайтово.
#
# В `~/.claude/brief.md` файл попадает копированием при установке — обёртка
# читает именно его. Писать туда отсюда нельзя: сборка не должна трогать то,
# что стоит в деле, без отдельного решения.
#
# ГЛОБАЛЬНАЯ область лежит в самом комплекте. ПРОЕКТНЫЕ — снаружи: бриф
# экосистемы принадлежит её репозиторию, а не комплекту, и зашивать сюда чужой
# путь значит сломать это у каждого, кто разложил репозитории иначе.
#
# Правило поиска: каталог-сосед с именем области, рядом с корнем комплекта.
# Переопределяется переменной `TRAH_BRIEF_<ОБЛАСТЬ>`. Нет такого каталога —
# область просто не собирается, и это не ошибка: у чужого человека своей
# экосистемы может не быть вовсе.
КОРЕНЬ_КОМПЛЕКТА = Path(__file__).resolve().parent.parent.parent


def все_области() -> list[str]:
    """Какие области вообще есть — по кускам, а не по списку в коде.

    Список в коде — это второе место, где записано то же самое: завёл кусок с
    новой областью, а сборка её не знает, и узнать об этом неоткуда.
    """
    области = {к.get("scope") for к in прочитать_куски() if к.get("route") == "brief"}
    области.discard(None)
    # `global` первой: она общая, остальные — по алфавиту.
    прочие = sorted(о for о in области if о != "global")
    return (["global"] if "global" in области else []) + прочие


def куда_бриф(область: str) -> Path | None:
    если_задано = os.environ.get("TRAH_BRIEF_" + область.upper())
    if если_задано:
        return Path(если_задано)
    # Область `global` — бриф службы. Он ушёл в архив вместе с ней, и его куски
    # тоже: этот комплект их не видит и собрать не может. Пути нет намеренно —
    # собрать бриф из ПОЛОВИНЫ кусков хуже, чем не собрать вовсе: получится
    # текст, который выглядит целым.
    # `trah` — бриф интерактивного режима. Лежит в самом комплекте, а не у
    # соседа: это не отдельный проект, а второй профиль того же человека, и
    # каталога-соседа с таким именем не будет ни у кого.
    if область == "trah":
        return КОРЕНЬ_КОМПЛЕКТА / "trah-setup/trah-brief.md"
    сосед = КОРЕНЬ_КОМПЛЕКТА.parent / область / ".claude/brief.md"
    return сосед if сосед.parent.exists() else None


def brief(аргумент: str | None) -> int:
    """trah.py brief [область] [--lean] [--write] [--skip-personal]

    Без `--write` бриф печатается. С `--write` — раскладывается по файлам,
    и без области раскладываются все.

    `--skip-personal` выбрасывает куски, описывающие конкретную машину, человека
    или экосистему. Это режим установки на ЧУЖУЮ машину: там такой кусок не
    правило, а чужая биография в промпте, и платит за неё чужой человек.
    """
    урезать = "--lean" in sys.argv
    писать = "--write" in sys.argv
    без_личного = "--skip-personal" in sys.argv

    if писать:
        области = [аргумент] if аргумент else все_области()
        for область in области:
            путь = куда_бриф(область)
            if путь is None:
                # Не ошибка: у чужого человека этой экосистемы просто нет. А вот
                # молча ничего не написать и отчитаться успехом — ошибка.
                print(f"  {область:<20} пропущена: некуда писать "
                      f"(нет каталога-соседа, TRAH_BRIEF_{область.upper()} не задан)")
                continue
            текст = собрать_бриф(область, урезать, без_личного=без_личного)
            было = путь.read_text(encoding="utf-8") if путь.exists() else None
            путь.parent.mkdir(parents=True, exist_ok=True)
            путь.write_text(текст, encoding="utf-8")
            print(f"  {область:<20} {'без изменений' if текст == было else 'пересобран'}"
                  f" ({len(текст)} байт) → {путь}")
        return 0

    sys.stdout.write(собрать_бриф(аргумент or "global", урезать,
                                  без_личного=без_личного))
    return 0


# ── модули брифа наружу ──────────────────────────────────────────────────────
#
# Куда выкладываются куски брифа и указатель к ним, чтобы внешний уклад мог снять
# один модуль и оставить остальные.
#
# Заказчик был один — служба, поднимавшая сессии профилем; она ушла в архив, и
# сегодня `modules --install` не читает никто. Команда оставлена: раскрой брифа
# по кускам это его устройство, а не услуга одному потребителю, и восстановить
# выкладку дороже, чем её сохранить.
#
# ПОЧЕМУ В `~/.claude`, А НЕ В КАТАЛОГЕ ПРОЕКТА. Тот, кто читает эти куски,
# поднимает сессии в разных деревьях и не должен знать дороги ни к одному из
# них: путь в чужих настройках — связь, которая рвётся при переезде каталога и о
# которой никто не вспомнит. `~/.claude/` знают все.
МОДУЛИ = ДОМ / ".claude/fragments"


def указатель_модулей() -> list[dict]:
    """Что можно снять укладом: id, область, порядок и зачем кусок нужен.

    Только маршрут `brief`. Куски бинарника снять нельзя в принципе: они
    запечены в сборке, и переопределить их профилем можно было бы только
    отдельной сборкой на уклад. В указателе их нет, чтобы окно не предлагало
    рычага, которого не существует.
    """
    вышло = []
    for к in прочитать_куски():
        if к.get("route") != "brief":
            continue
        тело = к["тело"]
        первая = тело.splitlines()[0] if тело else ""
        вышло.append({
            "id": к["id"],
            "scope": к.get("scope", ""),
            "kind": к.get("kind", "section"),
            "order": к.get("order", 0),
            # Заголовок раздела — как он выглядит в брифе. У пункта списка
            # заголовка нет, и придумывать его нельзя: показываем начало текста,
            # обрезав по слову, — человек узнаёт пункт по первым словам.
            "label": подпись(первая, к.get("kind")),
            "why": к.get("why", ""),
            # Личный кусок описывает КОНКРЕТНУЮ машину, человека или экосистему:
            # железо этого стола, ноут с его адресом, атлас пятнадцати ботов.
            # На чужой машине такой кусок — не правило, а чужая биография в
            # промпте, и платить за неё будет чужой человек, на каждом ходе.
            # Установщик их не ставит, а заводит заново по ответам хозяина.
            "personal": bool(к.get("personal")),
            "bytes": len(тело.encode("utf-8")),
        })
    # Сначала `global`, потом области по алфавиту. Порядок не косметический:
    # окно рисует список сверху вниз, и общие правила должны читаться раньше
    # частных — как они и подаются модели.
    вышло.sort(key=lambda м: (м["scope"] != "global", м["scope"], м["order"]))
    return вышло


def подпись(первая: str, вид: str | None) -> str:
    строка = первая.lstrip("#- ").strip()
    if вид != "bullet" or len(строка) <= 60:
        return строка
    обрез = строка[:60].rsplit(" ", 1)[0]
    return обрез + "…"


def modules(аргумент: str | None) -> int:
    """trah.py modules [--install]

    Без `--install` указатель печатается. С `--install` куски брифа и указатель
    ставятся в `~/.claude/fragments/`, откуда их читает служба.
    """
    указатель = указатель_модулей()
    # Установка на чужую машину: личные куски не ставим и в указатель не пишем,
    # иначе окно предложит снять кусок, которого на диске нет.
    if "--skip-personal" in sys.argv:
        указатель = [м for м in указатель if not м["personal"]]
    if "--install" not in sys.argv:
        print(json.dumps(указатель, ensure_ascii=False, indent=2))
        return 0

    МОДУЛИ.mkdir(parents=True, exist_ok=True)
    # Ставим ТОЛЬКО куски брифа и подчищаем лишнее: кусок переименовали или
    # убрали, а старый файл остался — служба собрала бы бриф с текстом, которого
    # в источнике уже нет, и разошлась бы с ним молча.
    нужные = {м["id"] + ".md" for м in указатель}
    for стар in МОДУЛИ.glob("*.md"):
        if стар.name not in нужные:
            стар.unlink()
            print(f"  убран лишний {стар.name}")
    for м in указатель:
        имя = м["id"] + ".md"
        shutil.copyfile(КУСКИ / имя, МОДУЛИ / имя)
    (МОДУЛИ / "index.json").write_text(
        json.dumps(указатель, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print(f"поставлено кусков: {len(указатель)} → {МОДУЛИ}")
    return 0


def main() -> int:
    команда = sys.argv[1] if len(sys.argv) > 1 else "status"
    аргумент = sys.argv[2] if len(sys.argv) > 2 and not sys.argv[2].startswith("-") else None
    return {"build": build, "verify": verify, "status": status,
            "brief": brief, "modules": modules, "check": check,
            "upgrade": upgrade, "tests": lambda _: проверки()}[команда](аргумент)


if __name__ == "__main__":
    raise SystemExit(main())
