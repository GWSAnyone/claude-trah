#!/usr/bin/env python3
"""Проверки двери `./trah`. Токенов не стоит, сборок не запускает.

Главное здесь одно: обычный `./trah` собирает прицел и никогда не переезжает
сам. До 02.10.2026 он целился в новейшую версию на машине и уходил в `upgrade`
без спроса — Claude Code обновился за ночь, и рутинный запуск переписывал прицел.

Второе: сборка без проверки доставки оставляет манифест «не проверялось», и
вычитание брифа по `covered_by` молча не срабатывает. Поэтому за `build` идёт
`verify`.
"""
import importlib.machinery
import importlib.util
import json
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent.parent
загрузчик = importlib.machinery.SourceFileLoader("trah_door", str(КОРЕНЬ / "trah"))
спец = importlib.util.spec_from_loader("trah_door", загрузчик)
дверь = importlib.util.module_from_spec(спец)
загрузчик.exec_module(дверь)

всего = 0
провалов = 0


def check(имя: str, условие: bool, подробность: str = "") -> None:
    global всего, провалов
    всего += 1
    if not условие:
        провалов += 1
        print(f"  ✗ {имя} {подробность}")


def прогон(версии: list[str], прицел: str, собрана: str | None = None,
           доставка: str = "проверено", заново: bool = False,
           всухую: bool = False) -> tuple[list, object]:
    """Шаг сборки на поддельном доме; вызовы подпроцессов записываются, не идут."""
    with tempfile.TemporaryDirectory() as tmp:
        дом = Path(tmp)
        (дом / "versions").mkdir()
        (дом / "trah").mkdir()
        for в in версии:
            (дом / "versions" / в).write_text("x")
        if собрана:
            (дом / "trah" / собрана).write_text("x")
            (дом / "trah" / f"{собрана}.manifest.json").write_text(json.dumps(
                {"куски": {"a": {"доставлен": доставка}}}), encoding="utf-8")
        пин = дом / "version.txt"
        пин.write_text(прицел + "\n")
        вызовы: list = []

        def выполнить(ход, имя, команда, ввод=None):
            вызовы.append([str(к) for к in команда[2:]])
            ход.сделано.append(имя)
            return True

        прежнее = (дверь.ДОМ_СБОРОК, дверь.ПИН, дверь.выполнить)
        дверь.ДОМ_СБОРОК, дверь.ПИН, дверь.выполнить = дом, пин, выполнить
        try:
            ход = дверь.Ход(всухую)
            дверь.шаг_сборка(ход, заново=заново)
        finally:
            дверь.ДОМ_СБОРОК, дверь.ПИН, дверь.выполнить = прежнее
        return вызовы, ход


print("trah (дверь)")

# --- новейшая на машине не уводит прицел --------------------------------------
вызовы, ход = прогон(["2.1.284", "2.1.287"], "2.1.284", собрана="2.1.284")
check("новая версия на машине: ни одного подпроцесса", вызовы == [], f"={вызовы}")
check("новая версия на машине: команда переезда в «руками»",
      any("./trah upgrade 2.1.287" in с for с in ход.руками), f"={ход.руками}")

вызовы, ход = прогон(["2.1.284", "2.1.287"], "2.1.284")
check("не собрана: собирается прицел, а не новейшая",
      вызовы == [["build", "2.1.284"], ["verify", "2.1.284"]], f"={вызовы}")
check("upgrade не зовётся никогда", not any("upgrade" in в for в in вызовы))

вызовы, ход = прогон(["2.1.287"], "2.1.284")
check("прицела нет на машине: провал, а не переезд",
      вызовы == [] and ход.провалено, f"={вызовы} {ход.провалено}")

# --- доставка ----------------------------------------------------------------
вызовы, _ = прогон(["2.1.284"], "2.1.284", собрана="2.1.284", доставка="не проверялось")
check("собрана, но доставка не проверялась: verify", вызовы == [["verify", "2.1.284"]],
      f"={вызовы}")
вызовы, _ = прогон(["2.1.284"], "2.1.284", собрана="2.1.284", заново=True)
check("build: пересборка и проверка доставки",
      вызовы == [["build", "2.1.284"], ["verify", "2.1.284"]], f"={вызовы}")
вызовы, _ = прогон(["2.1.284"], "2.1.284", всухую=True)
check("--check: только сверка якорей", вызовы == [["check", "2.1.284"]], f"={вызовы}")

print(f"  проверок {всего}, провалов {провалов}")
raise SystemExit(1 if провалов else 0)
