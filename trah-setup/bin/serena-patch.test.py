#!/usr/bin/env python3
"""Проверки наложения патчей Serena. Сети и установки не трогают.

Главное здесь: «наложен» и «не ложится» не путаются. Прямой прогон по уже
наложенному патчу тоже отвечает отказом, и без обратной пробы наложенный патч
выглядел бы сломанным. И второе: патч, которому нужно размытие контекста,
считается не легшим — лечь не туда хуже, чем не лечь.
"""
import contextlib
import importlib.util
import io
import subprocess
import sys
import tempfile
from pathlib import Path

КАТАЛОГ = Path(__file__).resolve().parent
спец = importlib.util.spec_from_file_location("serena_patch", КАТАЛОГ / "serena-patch.py")
sp = importlib.util.module_from_spec(спец)
спец.loader.exec_module(sp)

всего = 0
провалов = 0


def check(имя: str, условие: bool, подробность: str = "") -> None:
    global всего, провалов
    всего += 1
    if not условие:
        провалов += 1
        print(f"  ✗ {имя} {подробность}")


def дерево(текст: str) -> Path:
    корень = Path(tempfile.mkdtemp())
    (корень / "serena").mkdir()
    (корень / "serena" / "m.py").write_text(текст, encoding="utf-8")
    return корень


def патч_между(было: str, стало: str) -> Path:
    а, б = дерево(было), дерево(стало)
    дифф = subprocess.run(["diff", "-u", str(а / "serena/m.py"), str(б / "serena/m.py")],
                          capture_output=True, text=True).stdout
    строки = дифф.split("\n")
    строки[0], строки[1] = "--- a/serena/m.py", "+++ b/serena/m.py"
    п = Path(tempfile.mkdtemp()) / "01-test.patch"
    п.write_text("Шапка патча: patch её пропускает.\n\n" + "\n".join(строки), encoding="utf-8")
    return п


print("serena-patch.py")

# Доклад инструмента печатает свои ✓/✗, а `./trah tests` читает любой ✗ в выводе
# набора как провал. Отчёт наборa — только строки `check`.
def тихо(функция):
    def обёртка(*а, **к):
        with contextlib.redirect_stdout(io.StringIO()):
            return функция(*а, **к)
    return обёртка


sp.apply = тихо(sp.apply)
sp.наложить = тихо(sp.наложить)

ИСХОДНИК = "".join(f"line {i}\n" for i in range(20))
ПРАВЛЕНО = ИСХОДНИК.replace("line 10\n", "line 10 patched\n")
патч = патч_между(ИСХОДНИК, ПРАВЛЕНО)

# --- три состояния ------------------------------------------------------------
чистое = дерево(ИСХОДНИК)
check("на чистом исходнике патч ложится", sp.состояние(чистое, патч) == "ложится",
      sp.состояние(чистое, патч))
check("всухую ничего не пишется",
      sp.наложить(чистое, [патч], всухую=True) == [] and
      (чистое / "serena/m.py").read_text() == ИСХОДНИК)

check("наложение проходит", sp.наложить(чистое, [патч], всухую=False) == [])
check("файл действительно правлен", (чистое / "serena/m.py").read_text() == ПРАВЛЕНО)
check("наложенный опознаётся как наложенный, а не сломанный",
      sp.состояние(чистое, патч) == "наложен", sp.состояние(чистое, патч))
check("повторное наложение ничего не портит",
      sp.наложить(чистое, [патч], всухую=False) == [] and
      (чистое / "serena/m.py").read_text() == ПРАВЛЕНО)
check("резервных копий patch не оставил",
      sorted(п.name for п in (чистое / "serena").iterdir()) == ["m.py"],
      str(sorted(п.name for п in (чистое / "serena").iterdir())))

# --- сдвиг допустим, размытие нет ----------------------------------------------
сдвинуто = дерево("new header\n" * 5 + ИСХОДНИК)
check("сдвиг по строкам не мешает", sp.состояние(сдвинуто, патч) == "ложится",
      sp.состояние(сдвинуто, патч))

размыто = дерево(ИСХОДНИК.replace("line 8\n", "line 8 changed upstream\n"))
check("контекст изменился — не ложится, а не ложится с fuzz",
      sp.состояние(размыто, патч) == "не ложится", sp.состояние(размыто, патч))
check("не легший назван по имени",
      sp.наложить(размыто, [патч], всухую=False) == ["01-test.patch"])
check("не легший не оставил полуправки",
      (размыто / "serena/m.py").read_text() == ИСХОДНИК.replace("line 8\n", "line 8 changed upstream\n"))

# --- apply не накладывает на чужой коммит ---------------------------------------
прежние = sp.установка, sp.прицел
sp.установка = lambda: (дерево(ИСХОДНИК), "0" * 40)
sp.прицел = lambda: "1" * 40
check("apply отказывает, если стоит не прицел", sp.apply([]) == 1)
sp.установка, sp.прицел = прежние

# --- комплект сам по себе целый -------------------------------------------------
check("в комплекте есть патчи", len(sp.патчи()) >= 4, str(sp.патчи()))
check("прицел — полный хеш коммита", len(sp.прицел()) == 40, sp.прицел())
for п in sp.патчи():
    текст = п.read_text(encoding="utf-8")
    check(f"{п.name}: пути от корня пакета", "+++ b/serena/" in текст)
    check(f"{п.name}: есть шапка с причиной", not текст.startswith("---"))

print(f"проверок {всего}, провалов {провалов}")
sys.exit(1 if провалов else 0)
